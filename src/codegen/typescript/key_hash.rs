//! Instance `KeyHash` of generated TypeScript types (RTPS 2.5 9.6.4.8).
//!
//! A file with a keyed type carries `HddsKeyHolder` (the `KeyHolder`
//! serialization, `PLAIN_CDR2` big endian, alignment capped at 4, zero
//! padding) and `hddsMd5` (RFC 1321; browsers have no synchronous MD5).
//! `computeKey<T>()` writes the `KeyHolder` members in member-id order, as
//! the shared model (`codegen::key_holder`) orders them, and passes the
//! padded-or-MD5 choice computed at generation time.

use std::cell::RefCell;
use std::fmt::Write as _;

use super::super::key_holder::{
    is_default_case, KhCase, KhNode, KhPrim, KhScalar, KhStruct, KhUnion, TypeIndex, MD5_K, MD5_S,
};
use super::super::keywords::ts_ident;
use super::codec::{case_cond, disc_key};
use crate::ast::{Definition, IdlFile, Struct, UnionLabel};
use crate::codegen::data_model::union_label_value;
use crate::codegen::python::scope::flat;

thread_local! {
    /// Type index of the file being generated.
    // @audit-ok: thread_local! RefCell is inherently thread-safe (one instance per thread)
    static INDEX: RefCell<TypeIndex> = RefCell::new(TypeIndex::default());
}

const WRITER: &str = r#"/** KeyHolder serialization of RTPS 2.5 9.6.4.8 (generated by hddsgen):
 * PLAIN_CDR2 big endian, alignment capped at 4, zero padding. */
class HddsKeyHolder {
  private readonly buf: number[] = [];
  constructor(private readonly maxAlign = 4) {}

  private put(bytes: number[]): void {
    const align = Math.min(bytes.length, this.maxAlign);
    while (align > 1 && this.buf.length % align !== 0) {
      this.buf.push(0);
    }
    for (const b of bytes) {
      this.buf.push(b & 0xff);
    }
  }

  private be(v: number | bigint, size: number): void {
    const n = BigInt.asUintN(8 * size, typeof v === "bigint" ? v : BigInt(Math.trunc(v)));
    const bytes: number[] = [];
    for (let i = size - 1; i >= 0; i--) {
      bytes.push(Number((n >> BigInt(8 * i)) & 0xffn));
    }
    this.put(bytes);
  }

  boolean(v: boolean): void {
    this.buf.push(v ? 1 : 0);
  }
  octet(v: number | bigint): void {
    this.be(v, 1);
  }
  char(v: string | number): void {
    this.be(typeof v === "string" ? v.charCodeAt(0) : v, 1);
  }
  wchar(v: string | number): void {
    this.be(typeof v === "string" ? v.charCodeAt(0) : v, 2);
  }
  i8(v: number | bigint): void {
    this.be(v, 1);
  }
  i16(v: number | bigint): void {
    this.be(v, 2);
  }
  u16(v: number | bigint): void {
    this.be(v, 2);
  }
  i32(v: number | bigint): void {
    this.be(v, 4);
  }
  u32(v: number | bigint): void {
    this.be(v, 4);
  }
  i64(v: number | bigint): void {
    this.be(v, 8);
  }
  u64(v: number | bigint): void {
    this.be(v, 8);
  }
  f32(v: number): void {
    const view = new DataView(new ArrayBuffer(4));
    view.setFloat32(0, v, false);
    this.put(Array.from(new Uint8Array(view.buffer)));
  }
  f64(v: number): void {
    const view = new DataView(new ArrayBuffer(8));
    view.setFloat64(0, v, false);
    this.put(Array.from(new Uint8Array(view.buffer)));
  }
  octets(v: ArrayLike<number>): void {
    for (let i = 0; i < v.length; i++) {
      this.buf.push(v[i] & 0xff);
    }
  }
  /** `string`: length counting the NUL, the UTF-8 bytes, the NUL. */
  string(v: string): void {
    const data = new TextEncoder().encode(v);
    this.u32(data.length + 1);
    this.octets(data);
    this.buf.push(0);
  }
  /** `wstring`: length in bytes, UTF-16 code units, no NUL. */
  wstring(v: string): void {
    this.u32(v.length * 2);
    for (let i = 0; i < v.length; i++) {
      const unit = v.charCodeAt(i);
      this.buf.push((unit >> 8) & 0xff, unit & 0xff);
    }
  }
  /** The KeyHash: zero-padded when the KeyHolder's maximum size is at most
   * 16 bytes (`padded`), the MD5 of the serialization otherwise. */
  finish(padded: boolean): Uint8Array {
    if (padded && this.buf.length <= 16) {
      const out = new Uint8Array(16);
      out.set(this.buf);
      return out;
    }
    return hddsMd5(Uint8Array.from(this.buf));
  }
}

/** MD5 (RFC 1321). */
function hddsMd5(data: Uint8Array): Uint8Array {
  const K = [@K@];
  const S = [@S@];
  const blocks = ((data.length + 8) >>> 6) + 1;
  const msg = new Uint8Array(blocks * 64);
  msg.set(data);
  msg[data.length] = 0x80;
  const bits = data.length * 8;
  for (let i = 0; i < 8; i++) {
    msg[blocks * 64 - 8 + i] = Math.floor(bits / 2 ** (8 * i)) & 0xff;
  }
  const INIT = [0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476];
  let [a0, b0, c0, d0] = INIT;
  const m = new Array<number>(16);
  for (let off = 0; off < msg.length; off += 64) {
    for (let i = 0; i < 16; i++) {
      const o = off + 4 * i;
      m[i] = (msg[o] | (msg[o + 1] << 8) | (msg[o + 2] << 16) | (msg[o + 3] << 24)) >>> 0;
    }
    let a = a0;
    let b = b0;
    let c = c0;
    let d = d0;
    for (let i = 0; i < 64; i++) {
      let f: number;
      let g: number;
      if (i < 16) {
        f = (b & c) | (~b & d);
        g = i;
      } else if (i < 32) {
        f = (d & b) | (~d & c);
        g = (5 * i + 1) % 16;
      } else if (i < 48) {
        f = b ^ c ^ d;
        g = (3 * i + 5) % 16;
      } else {
        f = c ^ (b | ~d);
        g = (7 * i) % 16;
      }
      f = ((f >>> 0) + a + K[i] + m[g]) >>> 0;
      a = d;
      d = c;
      c = b;
      b = (b + (((f << S[i]) | (f >>> (32 - S[i]))) >>> 0)) >>> 0;
    }
    a0 = (a0 + a) >>> 0;
    b0 = (b0 + b) >>> 0;
    c0 = (c0 + c) >>> 0;
    d0 = (d0 + d) >>> 0;
  }
  const out = new Uint8Array(16);
  [a0, b0, c0, d0].forEach((word, w) => {
    for (let i = 0; i < 4; i++) {
      out[4 * w + i] = (word >>> (8 * i)) & 0xff;
    }
  });
  return out;
}

"#;

/// Index `ast` for the structs about to be generated; return the writer
/// to emit when some struct has a `KeyHolder` the model covers.
pub(super) fn begin_file(ast: &IdlFile) -> Option<String> {
    fn walk(defs: &[Definition], idx: &TypeIndex) -> bool {
        defs.iter().any(|d| match d {
            Definition::Struct(s) => matches!(idx.key_holder(s), Ok(Some(_))),
            Definition::Union(u) => u.discriminator_is_key(),
            Definition::Module(m) => walk(&m.definitions, idx),
            _ => false,
        })
    }
    let index = TypeIndex::new(ast);
    let needed = walk(&ast.definitions, &index);
    INDEX.with(|cell| *cell.borrow_mut() = index);
    needed.then(|| {
        let k: Vec<String> = MD5_K.iter().map(|v| format!("0x{v:08x}")).collect();
        let s: Vec<String> = MD5_S.iter().map(ToString::to_string).collect();
        WRITER
            .replace("@K@", &k.join(", "))
            .replace("@S@", &s.join(", "))
    })
}

/// Writer method of a primitive.
const fn method(p: KhPrim) -> &'static str {
    match p {
        KhPrim::Bool => "boolean",
        KhPrim::Octet => "octet",
        KhPrim::Char => "char",
        KhPrim::I8 => "i8",
        KhPrim::I16 => "i16",
        KhPrim::U16 => "u16",
        KhPrim::WChar => "wchar",
        KhPrim::I32 => "i32",
        KhPrim::U32 => "u32",
        KhPrim::I64 => "i64",
        KhPrim::U64 => "u64",
        KhPrim::F32 => "f32",
        KhPrim::F64 => "f64",
    }
}

struct Emit {
    out: String,
    next_var: usize,
}

impl Emit {
    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.out.push_str("  ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn var(&mut self, prefix: &str) -> String {
        let v = format!("_{prefix}{}", self.next_var);
        self.next_var += 1;
        v
    }

    fn scalar(&mut self, ind: usize, s: &KhScalar, place: &str) {
        self.line(ind, &format!("w.{}({place});", method(s.prim())));
    }

    fn node(&mut self, ind: usize, n: &KhNode, place: &str) -> Result<(), String> {
        match n {
            KhNode::Scalar(s) => self.scalar(ind, s, place),
            KhNode::String { .. } => self.line(ind, &format!("w.string({place});")),
            KhNode::WString { .. } => self.line(ind, &format!("w.wstring({place});")),
            KhNode::Sequence { elem, .. } => {
                self.line(ind, &format!("w.u32({place}.length);"));
                if elem.prim() == KhPrim::Octet {
                    self.line(ind, &format!("w.octets({place});"));
                } else {
                    let v = self.var("e");
                    self.line(ind, &format!("for (const {v} of {place}) {{"));
                    self.scalar(ind + 1, elem, &v);
                    self.line(ind, "}");
                }
            }
            KhNode::Array { elem, dims } => {
                let mut cur = place.to_string();
                let mut depth = ind;
                for _ in dims {
                    let v = self.var("e");
                    self.line(depth, &format!("for (const {v} of {cur}) {{"));
                    cur = v;
                    depth += 1;
                }
                self.scalar(depth, elem, &cur);
                for _ in dims {
                    depth -= 1;
                    self.line(depth, "}");
                }
            }
            KhNode::Struct(s) => self.structure(ind, s, place)?,
            KhNode::Union(u) => self.union(ind, u, place)?,
        }
        Ok(())
    }

    /// A derived interface extends its base's: a base member is read from
    /// the same object as the type's own members.
    fn structure(&mut self, ind: usize, s: &KhStruct, place: &str) -> Result<(), String> {
        for m in s.hash_order() {
            let p = format!("{place}.{}", ts_ident(&m.field.name));
            self.node(ind, &m.node, &p)?;
        }
        Ok(())
    }

    fn case_body(&mut self, ind: usize, case: &KhCase, place: &str) -> Result<(), String> {
        if let Some(n) = &case.node {
            let p = format!("({place} as any).{}", ts_ident(&case.field.name));
            self.node(ind, n, &p)?;
        }
        Ok(())
    }

    fn union(&mut self, ind: usize, u: &KhUnion, place: &str) -> Result<(), String> {
        let d = self.var("d");
        self.line(ind, &format!("const {d} = {place}.discriminator;"));
        self.scalar(ind, &u.disc, &d);
        if u.disc_is_key {
            return Ok(());
        }
        let key = self.var("k");
        let (expr, big) = INDEX.with(|cell| disc_key(&cell.borrow(), &u.disc_type, &d));
        self.line(ind, &format!("const {key} = {expr};"));
        let mut first = true;
        let mut default: Option<&KhCase> = None;
        for case in &u.cases {
            if is_default_case(&case.labels) {
                default = Some(case);
                continue;
            }
            // An unreadable label is refused when the union's own codec is
            // generated.
            let values: Vec<i64> = case
                .labels
                .iter()
                .filter_map(|l| match l {
                    UnionLabel::Value(v) => {
                        INDEX.with(|cell| union_label_value(&cell.borrow(), &u.disc_type, v))
                    }
                    UnionLabel::Default => None,
                })
                .collect();
            if values.is_empty() {
                continue;
            }
            let kw = if first { "if" } else { "} else if" };
            first = false;
            self.line(ind, &format!("{kw} ({}) {{", case_cond(&key, &values, big)));
            self.case_body(ind + 1, case, place)?;
        }
        if let Some(case) = default {
            self.line(ind, if first { "{" } else { "} else {" });
            self.case_body(ind + 1, case, place)?;
            self.line(ind, "}");
        } else if !first {
            self.line(ind, "}");
        }
        Ok(())
    }
}

/// `computeKey<Name>()` of `s`.
pub(super) fn compute_key_function(s: &Struct) -> String {
    let mut out = String::new();
    out.push_str(
        "/** Instance KeyHash (RTPS 2.5 9.6.4.8): the KeyHolder serialized as\n \
         * PLAIN_CDR2 big endian, zero-padded to 16 bytes when its maximum size is\n \
         * at most 16, its MD5 otherwise. All zeros for a type without key. */\n",
    );
    let name = &flat(&s.name);
    let holder = INDEX.with(|cell| cell.borrow().key_holder(s));
    let emitted: Result<(String, bool), Option<String>> = match holder {
        Ok(Some(kh)) => {
            let mut e = Emit {
                out: String::new(),
                next_var: 0,
            };
            e.structure(1, &kh, "obj")
                .map(|()| (e.out, kh.is_padded_form()))
                .map_err(Some)
        }
        Ok(None) => Err(None),
        Err(reason) => Err(Some(reason)),
    };
    match emitted {
        Ok((body, padded)) => {
            let _ = writeln!(
                out,
                "export function computeKey{name}(obj: {name}, protectedKey = false): Uint8Array {{"
            );
            out.push_str("  const w = new HddsKeyHolder(protectedKey ? 8 : 4);\n");
            out.push_str(&body);
            let _ = writeln!(out, "  return w.finish({padded} && !protectedKey);");
        }
        Err(reason) => {
            let _ = writeln!(
                out,
                "export function computeKey{name}(_obj: {name}): Uint8Array {{"
            );
            if let Some(reason) = reason {
                let reason = reason.replace(['\n', '\r'], " ");
                let _ = writeln!(
                    out,
                    "  // No KeyHolder generated: the key of this type is not covered by\n  \
                     // hddsgen's KeyHash model ({reason})."
                );
            }
            out.push_str("  return new Uint8Array(16);\n");
        }
    }
    out.push_str("}\n\n");
    out
}
