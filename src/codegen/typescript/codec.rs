/// How a resolved type serializes.
enum Kind {
    Prim(PrimitiveType),
    Str {
        wide: bool,
        bound: u32,
    },
    Seq {
        inner: IdlType,
        bound: u32,
    },
    Array {
        elem: IdlType,
        dims: Vec<u32>,
    },
    Map {
        key: IdlType,
        value: IdlType,
        bound: u32,
    },
    Named(String),
    Bitset(String),
    Unknown(String),
}

/// (put, get) method of a fixed-size primitive that needs alignment.
const fn prim_methods(p: &PrimitiveType) -> Option<(&'static str, &'static str)> {
    match p {
        PrimitiveType::Short | PrimitiveType::Int16 => Some(("putInt16", "getInt16")),
        PrimitiveType::UnsignedShort | PrimitiveType::UInt16 => Some(("putUint16", "getUint16")),
        PrimitiveType::Long | PrimitiveType::Int32 => Some(("putInt32", "getInt32")),
        PrimitiveType::UnsignedLong | PrimitiveType::UInt32 => Some(("putUint32", "getUint32")),
        PrimitiveType::LongLong | PrimitiveType::Int64 => Some(("putBigInt64", "getBigInt64")),
        PrimitiveType::UnsignedLongLong | PrimitiveType::UInt64 => {
            Some(("putBigUint64", "getBigUint64"))
        }
        PrimitiveType::Float => Some(("putFloat32", "getFloat32")),
        PrimitiveType::Double | PrimitiveType::LongDouble => Some(("putFloat64", "getFloat64")),
        _ => None,
    }
}

/// (put, get) method of an integer holder of `width` bytes.
pub(super) const fn int_methods(width: usize, signed: bool) -> (&'static str, &'static str) {
    match (width, signed) {
        (1, true) => ("writeInt8", "readInt8"),
        (1, false) => ("writeUint8", "readUint8"),
        (2, true) => ("putInt16", "getInt16"),
        (2, false) => ("putUint16", "getUint16"),
        (4, true) => ("putInt32", "getInt32"),
        (4, false) => ("putUint32", "getUint32"),
        (_, true) => ("putBigInt64", "getBigInt64"),
        (_, false) => ("putBigUint64", "getBigUint64"),
    }
}

/// Code emitter: the type index, the output and a counter for unique local
/// names.
struct Gen<'a> {
    idx: &'a TypeIndex,
    out: String,
    var: usize,
    /// Emitting an XCDR1 decoder (`decode<Name>Cdr1`): no DHEADER, nested
    /// structures and unions through their own XCDR1 decoder.
    v1: bool,
    key_only: bool,
}

impl<'a> Gen<'a> {
    const fn new(idx: &'a TypeIndex) -> Self {
        Self {
            idx,
            out: String::new(),
            var: 0,
            v1: false,
            key_only: false,
        }
    }

    /// Whether `ty` is a structure or union (which has an XCDR1 decoder of
    /// its own).
    fn is_aggregate(&self, ty: &IdlType) -> bool {
        match self.idx.resolve(ty) {
            IdlType::Named(n) => {
                matches!(self.idx.named(&n), Some(Named::Struct(_) | Named::Union(_)))
            }
            _ => false,
        }
    }

    fn fresh(&mut self, prefix: &str) -> String {
        let v = format!("_{prefix}{}", self.var);
        self.var += 1;
        v
    }

    fn line(&mut self, ind: usize, text: &str) {
        for _ in 0..ind {
            self.out.push_str("  ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn kind(&self, ty: &IdlType) -> Kind {
        let resolved = self.idx.resolve(ty);
        match resolved {
            // string<N> / wstring<N>: a string (rules 3-4), not a sequence.
            IdlType::BoundedString { wide, bound } => Kind::Str { wide, bound },
            IdlType::Primitive(PrimitiveType::String) => Kind::Str {
                wide: false,
                bound: 0,
            },
            IdlType::Primitive(PrimitiveType::WString) => Kind::Str {
                wide: true,
                bound: 0,
            },
            IdlType::Primitive(p) => Kind::Prim(p),
            // sequence<char> / sequence<wchar> are sequences on the wire: an
            // element count, then the elements (1 or 2 bytes), no NUL (rule
            // 11 versus rules 3-4).
            IdlType::Sequence { inner, bound } => Kind::Seq {
                inner: *inner,
                bound: bound.unwrap_or(0),
            },
            IdlType::Array { .. } => {
                let (elem, dims) = flatten_array(self.idx, &resolved)
                    .unwrap_or_else(|| (resolved.clone(), vec![]));
                Kind::Array { elem, dims }
            }
            IdlType::Map { key, value, bound } => Kind::Map {
                key: *key,
                value: *value,
                bound: bound.unwrap_or(0),
            },
            IdlType::Named(n) => match self.idx.named(&n) {
                Some(
                    Named::Struct(_) | Named::Union(_) | Named::Enum { .. } | Named::Bitmask { .. },
                ) => Kind::Named(flat(&n)),
                Some(Named::Bitset) => Kind::Bitset(flat(&n)),
                Some(Named::Typedef(_)) | None => Kind::Unknown(n),
            },
        }
    }

    /// TypeScript expression of a fresh default value of `ty` (DDS-XTypes
    /// 1.3 Table 9, spec text line 2311): zero (`0n` for 64-bit integers),
    /// `false`, the NUL character, the empty string, array or map, an array
    /// of defaults, the first literal of an enumeration, a structure, union
    /// or bitset of defaults (`default<Name>()`).
    fn default_expr(&self, ty: &IdlType) -> String {
        match self.idx.resolve(ty) {
            IdlType::Primitive(p) => match p {
                PrimitiveType::Boolean => "false".to_string(),
                PrimitiveType::Char | PrimitiveType::WChar => "\"\\u0000\"".to_string(),
                PrimitiveType::String | PrimitiveType::WString => "\"\"".to_string(),
                PrimitiveType::LongLong
                | PrimitiveType::UnsignedLongLong
                | PrimitiveType::Int64
                | PrimitiveType::UInt64 => "0n".to_string(),
                PrimitiveType::Void => "undefined".to_string(),
                _ => "0".to_string(),
            },
            IdlType::BoundedString { .. } => "\"\"".to_string(),
            IdlType::Sequence { .. } => "[]".to_string(),
            IdlType::Map { .. } => "new Map()".to_string(),
            resolved @ IdlType::Array { .. } => {
                let Some((elem, dims)) = flatten_array(self.idx, &resolved) else {
                    return "[]".to_string();
                };
                let mut e = self.default_expr(&elem);
                for d in dims.iter().rev() {
                    e = format!("Array.from({{ length: {d} }}, () => {e})");
                }
                e
            }
            IdlType::Named(n) => match self.idx.named(&n) {
                Some(Named::Struct(_) | Named::Union(_) | Named::Bitset) => {
                    format!("default{}()", flat(&n))
                }
                Some(Named::Enum { literals, .. }) => literals
                    .first()
                    .map_or_else(|| "0".to_string(), |(lit, _)| format!("{}.{lit}", flat(&n))),
                // No flag set; a numeric enum does not take the literal 0
                // without a cast (it names no flag).
                Some(Named::Bitmask { bit_bound }) => {
                    if data_model::bitmask_width(*bit_bound) == 8 {
                        "0n".to_string()
                    } else {
                        format!("(0 as {})", flat(&n))
                    }
                }
                Some(Named::Typedef(_)) | None => "undefined".to_string(),
            },
        }
    }

    fn is_octet(&self, ty: &IdlType) -> bool {
        matches!(
            self.idx.resolve(ty),
            IdlType::Primitive(PrimitiveType::Octet | PrimitiveType::UInt8)
        )
    }

    // -------------------------------------------------------------------
    // Encoding: statements writing the value of the expression `place`
    // through the cursor `buf`.
    // -------------------------------------------------------------------

    fn enc(&mut self, ind: usize, place: &str, ty: &IdlType) {
        match self.kind(ty) {
            Kind::Prim(p) => self.enc_prim(ind, place, &p),
            Kind::Str { wide, bound } => {
                let m = if wide { "putWString" } else { "putString" };
                self.line(ind, &format!("buf.{m}({place}, {bound});"));
            }
            Kind::Seq { inner, bound } => {
                let dh = self.begin_dheader(ind, ty);
                self.line(
                    ind,
                    &format!("Cdr2Buffer.bounded({place}.length, {bound});"),
                );
                self.line(ind, &format!("buf.putUint32({place}.length);"));
                if self.is_octet(&inner) {
                    self.line(ind, &format!("buf.putBytes({place});"));
                } else {
                    let x = self.fresh("x");
                    self.line(ind, &format!("for (const {x} of {place}) {{"));
                    self.enc(ind + 1, &x, &inner);
                    self.line(ind, "}");
                }
                self.end_dheader(ind, dh.as_deref());
            }
            Kind::Array { elem, dims } => {
                let dh = self.begin_dheader(ind, ty);
                if dims.len() == 1 && self.is_octet(&elem) {
                    self.line(
                        ind,
                        &format!("Cdr2Buffer.exact({place}.length, {});", dims[0]),
                    );
                    self.line(ind, &format!("buf.putBytes({place});"));
                } else {
                    let mut cur = place.to_string();
                    let mut depth = ind;
                    for d in &dims {
                        let x = self.fresh("x");
                        self.line(depth, &format!("Cdr2Buffer.exact({cur}.length, {d});"));
                        self.line(depth, &format!("for (const {x} of {cur}) {{"));
                        cur = x;
                        depth += 1;
                    }
                    self.enc(depth, &cur, &elem);
                    for _ in &dims {
                        depth -= 1;
                        self.line(depth, "}");
                    }
                }
                self.end_dheader(ind, dh.as_deref());
            }
            Kind::Map { key, value, bound } => {
                let dh = self.begin_dheader(ind, ty);
                self.line(ind, &format!("Cdr2Buffer.bounded({place}.size, {bound});"));
                self.line(ind, &format!("buf.putUint32({place}.size);"));
                let k = self.fresh("k");
                let v = self.fresh("v");
                self.line(ind, &format!("for (const [{k}, {v}] of {place}) {{"));
                self.enc(ind + 1, &k, &key);
                self.enc(ind + 1, &v, &value);
                self.line(ind, "}");
                self.end_dheader(ind, dh.as_deref());
            }
            Kind::Named(n) | Kind::Bitset(n) => {
                let prefix = if self.key_only && self.is_aggregate(ty) {
                    "encodeKey"
                } else {
                    "encode"
                };
                self.line(ind, &format!("{prefix}{n}({place}, buf);"));
            }
            Kind::Unknown(n) => self.line(
                ind,
                &format!(
                    "throw new Error(\"hddsgen: type '{}' is not defined in this IDL file\");",
                    idl_name(&n)
                ),
            ),
        }
    }

    /// Under XCDR2 a collection of non-primitive elements starts with a
    /// DHEADER (rules 9, 12, 15); returns the local holding its position.
    fn begin_dheader(&mut self, ind: usize, ty: &IdlType) -> Option<String> {
        if !collection_has_dheader(self.idx, ty) {
            return None;
        }
        let d = self.fresh("dh");
        self.line(ind, &format!("const {d} = buf.beginLen();"));
        Some(d)
    }

    fn end_dheader(&mut self, ind: usize, dh: Option<&str>) {
        if let Some(d) = dh {
            self.line(ind, &format!("buf.endLen({d});"));
        }
    }

    fn enc_prim(&mut self, ind: usize, place: &str, p: &PrimitiveType) {
        let stmt = match p {
            PrimitiveType::Boolean => format!("buf.writeBoolean({place});"),
            PrimitiveType::Octet | PrimitiveType::UInt8 => format!("buf.writeUint8({place});"),
            PrimitiveType::Int8 => format!("buf.writeInt8({place});"),
            PrimitiveType::Char => format!("buf.putChar({place});"),
            PrimitiveType::WChar => format!("buf.putWChar({place});"),
            PrimitiveType::String => format!("buf.putString({place}, 0);"),
            PrimitiveType::WString => format!("buf.putWString({place}, 0);"),
            PrimitiveType::Fixed { .. } => {
                "throw new Error(\"hddsgen: fixed is not serialized by the TypeScript backend\");"
                    .to_string()
            }
            PrimitiveType::Void => return,
            other => match prim_methods(other) {
                Some((put, _)) => format!("buf.{put}({place});"),
                None => return,
            },
        };
        self.line(ind, &stmt);
    }

    // -------------------------------------------------------------------
    // Decoding: statements declaring the local `target` with the value
    // read through the cursor `buf`.
    // -------------------------------------------------------------------

    fn dec(&mut self, ind: usize, target: &str, ty: &IdlType) {
        match self.kind(ty) {
            Kind::Prim(p) => {
                let expr = match p {
                    PrimitiveType::Boolean => "buf.getBoolean()".to_string(),
                    PrimitiveType::Octet | PrimitiveType::UInt8 => "buf.readUint8()".to_string(),
                    PrimitiveType::Int8 => "buf.readInt8()".to_string(),
                    PrimitiveType::Char => "buf.getChar()".to_string(),
                    PrimitiveType::WChar => "buf.getWChar()".to_string(),
                    PrimitiveType::String => "buf.getString(0)".to_string(),
                    PrimitiveType::WString => "buf.getWString(0)".to_string(),
                    PrimitiveType::Void => "undefined".to_string(),
                    // The local is still declared: the object built after
                    // it names it (unreachable, but type-checked).
                    PrimitiveType::Fixed { .. } => {
                        "hddsFail(\"hddsgen: fixed is not serialized by the TypeScript backend\")"
                            .to_string()
                    }
                    other => prim_methods(&other).map_or_else(
                        || "undefined".to_string(),
                        |(_, get)| format!("buf.{get}()"),
                    ),
                };
                self.line(ind, &format!("const {target}: any = {expr};"));
            }
            Kind::Str { wide, bound } => {
                let m = if wide { "getWString" } else { "getString" };
                self.line(ind, &format!("const {target}: any = buf.{m}({bound});"));
            }
            Kind::Seq { inner, bound } => {
                let end = self.begin_dheader_dec(ind, ty);
                let n = self.fresh("n");
                self.line(ind, &format!("const {n} = buf.getUint32();"));
                self.line(ind, &format!("Cdr2Buffer.bounded({n}, {bound});"));
                self.bound_values(ind, &n, &[&inner]);
                if self.is_octet(&inner) {
                    self.line(
                        ind,
                        &format!("const {target}: any = Array.from(buf.getBytes({n}));"),
                    );
                } else {
                    let v = self.fresh("v");
                    self.line(ind, &format!("const {target}: any[] = [];"));
                    self.line(ind, &format!("for (let _i = 0; _i < {n}; _i++) {{"));
                    self.dec(ind + 1, &v, &inner);
                    self.line(ind + 1, &format!("{target}.push({v});"));
                    self.line(ind, "}");
                }
                self.end_dheader_dec(ind, end.as_deref());
            }
            Kind::Array { elem, dims } => {
                let end = self.begin_dheader_dec(ind, ty);
                if dims.len() == 1 && self.is_octet(&elem) {
                    self.line(
                        ind,
                        &format!(
                            "const {target}: any = Array.from(buf.getBytes({}));",
                            dims[0]
                        ),
                    );
                } else {
                    self.dec_dims(ind, target, &elem, &dims);
                }
                self.end_dheader_dec(ind, end.as_deref());
            }
            Kind::Map { key, value, bound } => {
                let end = self.begin_dheader_dec(ind, ty);
                let n = self.fresh("n");
                let k = self.fresh("k");
                let v = self.fresh("v");
                self.line(ind, &format!("const {n} = buf.getUint32();"));
                self.line(ind, &format!("Cdr2Buffer.bounded({n}, {bound});"));
                self.bound_values(ind, &n, &[&key, &value]);
                self.line(ind, &format!("const {target} = new Map<any, any>();"));
                self.line(ind, &format!("for (let _i = 0; _i < {n}; _i++) {{"));
                self.dec(ind + 1, &k, &key);
                self.dec(ind + 1, &v, &value);
                self.line(ind + 1, &format!("{target}.set({k}, {v});"));
                self.line(ind, "}");
                self.end_dheader_dec(ind, end.as_deref());
            }
            Kind::Named(n) if self.v1 && self.is_aggregate(ty) => {
                self.line(ind, &format!("const {target}: any = decode{n}Cdr1(buf);"));
            }
            Kind::Named(n) | Kind::Bitset(n) => {
                self.line(ind, &format!("const {target}: any = decode{n}(buf);"));
            }
            Kind::Unknown(n) => self.line(
                ind,
                &format!(
                    "const {target}: any = hddsFail(\"hddsgen: type '{}' is not defined in this IDL file\");",
                    idl_name(&n)
                ),
            ),
        }
    }

    /// The bound of the values the `n` elements of a sequence (`parts`: its
    /// element type) or map (key and value types) can build, checked before
    /// any is: `buf.zeroWire(n, weight)` when they take no byte on the wire,
    /// `buf.storage(n, weight)` when an element can build more values than
    /// the bytes it takes at least (otherwise the bytes bound them already).
    /// The weight is written as a safe integer (at most 2^53 - 1).
    fn bound_values(&mut self, ind: usize, n: &str, parts: &[&IdlType]) {
        let min = parts.iter().fold(0u64, |acc, t| {
            acc.saturating_add(if self.v1 {
                least_wire::min_wire_xcdr1(self.idx, t)
            } else {
                least_wire::min_wire(self.idx, t)
            })
        });
        let weight = parts
            .iter()
            .fold(0u64, |acc, t| {
                acc.saturating_add(least_wire::value_weight(self.idx, t))
            })
            .min((1u64 << 53) - 1);
        if min == 0 {
            self.line(ind, &format!("buf.zeroWire({n}, {weight});"));
        } else if weight > min {
            self.line(ind, &format!("buf.storage({n}, {weight});"));
        }
    }

    /// Nested arrays, row-major.
    fn dec_dims(&mut self, ind: usize, target: &str, elem: &IdlType, dims: &[u32]) {
        let Some((&first, rest)) = dims.split_first() else {
            self.dec(ind, target, elem);
            return;
        };
        let v = self.fresh("v");
        self.line(ind, &format!("const {target}: any[] = [];"));
        self.line(ind, &format!("for (let _i = 0; _i < {first}; _i++) {{"));
        self.dec_dims(ind + 1, &v, elem, rest);
        self.line(ind + 1, &format!("{target}.push({v});"));
        self.line(ind, "}");
    }

    fn begin_dheader_dec(&mut self, ind: usize, ty: &IdlType) -> Option<String> {
        if self.v1 || !collection_has_dheader(self.idx, ty) {
            return None;
        }
        let end = self.fresh("end");
        self.line(ind, &format!("const {end} = buf.getLenEnd();"));
        Some(end)
    }

    fn end_dheader_dec(&mut self, ind: usize, end: Option<&str>) {
        if let Some(e) = end {
            self.line(ind, &format!("buf.skipTo({e});"));
        }
    }
}

/// `encode<Name>` / `decode<Name>` of a structure.
pub(super) fn struct_codec(idx: &TypeIndex, s: &Struct) -> String {
    struct_codec_impl(idx, s, false) + &struct_codec_impl(idx, s, true)
}

#[allow(clippy::too_many_lines)]
fn struct_codec_impl(idx: &TypeIndex, s: &Struct, key_only: bool) -> String {
    let name = &flat(&s.name);
    let idl = idl_name(&s.name);
    let ext = data_model::struct_ext(s);
    let mut g = Gen::new(idx);
    g.key_only = key_only;
    let chain = match member_chain(idx, s) {
        Ok(c) => c,
        Err(reason) => {
            let reason = reason.replace(['"', '\\', '\n'], " ");
            let _ = write!(
                g.out,
                "export function encode{name}(_obj: {name}, _buf: Cdr2Buffer): void {{\n  \
                 throw new Error(\"hddsgen: {idl}: {reason}\");\n}}\n\n\
                 export function decode{name}(_buf: Cdr2Buffer): {name} {{\n  \
                 throw new Error(\"hddsgen: {idl}: {reason}\");\n}}\n\n\
                 export function decode{name}Cdr1(_buf: Cdr1Buffer): {name} {{\n  \
                 throw new Error(\"hddsgen: {idl}: {reason}\");\n}}\n\n"
            );
            g.out.push_str(&by_encapsulation(name, ext));
            return g.out;
        }
    };
    let chain = if key_only {
        data_model::key_members(chain)
    } else {
        chain
    };
    let places: Vec<String> = chain
        .iter()
        .map(|m| format!("obj.{}", ts_ident(&m.field.name)))
        .collect();

    // ---- encode ----
    g.line(
        0,
        &format!("export function encode{name}(obj: {name}, buf: Cdr2Buffer): void {{"),
    );
    match ext {
        Ext::Final | Ext::Appendable => {
            // Rule 30 (line 7013): an APPENDABLE type is its DHEADER, then
            // its FINAL form.
            if ext == Ext::Appendable {
                g.line(1, "const _dh = buf.beginLen();");
            }
            for (m, place) in chain.iter().zip(&places) {
                if m.field.is_optional() {
                    // Rule 20: a presence flag, then the value.
                    g.line(1, &format!("if ({place} == null) {{"));
                    g.line(2, "buf.writeBoolean(false);");
                    g.line(1, "} else {");
                    g.line(2, "buf.writeBoolean(true);");
                    g.enc(2, place, &m.field.field_type);
                    g.line(1, "}");
                } else {
                    g.enc(1, place, &m.field.field_type);
                }
            }
            if ext == Ext::Appendable {
                g.line(1, "buf.endLen(_dh);");
            }
        }
        Ext::Mutable => {
            // Rules 21-22: DHEADER, then per member EMHEADER1, the NEXTINT
            // when the length code is 4, the value.
            g.line(1, "const _dh = buf.beginLen();");
            for (m, place) in chain.iter().zip(&places) {
                let mi = if m.field.is_optional() {
                    g.line(1, &format!("if ({place} != null) {{"));
                    2
                } else {
                    1
                };
                let lc = length_code(idx, &m.field.field_type);
                let mu = must_understand(&m.field);
                g.line(
                    mi,
                    &format!(
                        "buf.putEmheader({mu}, {lc}, {:#x}); // {}",
                        m.id, m.field.name
                    ),
                );
                if lc == 4 {
                    let n = g.fresh("n");
                    g.line(mi, &format!("const {n} = buf.beginLen();"));
                    g.enc(mi, place, &m.field.field_type);
                    g.line(mi, &format!("buf.endLen({n});"));
                } else {
                    g.enc(mi, place, &m.field.field_type);
                }
                if m.field.is_optional() {
                    g.line(1, "}");
                }
            }
            g.line(1, "buf.endLen(_dh);");
        }
    }
    g.line(0, "}");
    g.line(0, "");

    if key_only {
        return g.out.replacen(
            &format!("function encode{name}("),
            &format!("function encodeKey{name}("),
            1,
        );
    }

    // ---- decode ----
    g.line(
        0,
        &format!("export function decode{name}(buf: Cdr2Buffer): {name} {{"),
    );
    let locals: Vec<String> = (0..chain.len()).map(|i| format!("_f{i}")).collect();
    match ext {
        Ext::Final => {
            for (m, local) in chain.iter().zip(&locals) {
                if m.field.is_optional() {
                    let v = g.fresh("o");
                    g.line(1, &format!("let {local}: any = undefined;"));
                    g.line(1, "if (buf.getBoolean()) {");
                    g.dec(2, &v, &m.field.field_type);
                    g.line(2, &format!("{local} = {v};"));
                    g.line(1, "}");
                } else {
                    g.dec(1, local, &m.field.field_type);
                }
            }
        }
        Ext::Appendable => {
            // Type evolution (DDS-XTypes 1.3 7.4.1.2.3, spec text lines
            // 6195-6203; Table 9 line 2311): a member after the end the
            // DHEADER gives was not written (an older writer): it takes its
            // default; what follows the known members is skipped.
            g.line(1, "const _dh = buf.getLenEnd();");
            for (m, local) in chain.iter().zip(&locals) {
                let v = g.fresh("o");
                if m.field.is_optional() {
                    g.line(1, &format!("let {local}: any = undefined;"));
                    g.line(1, "if (buf.position < _dh && buf.getBoolean()) {");
                } else {
                    let dflt = g.default_expr(&m.field.field_type);
                    g.line(1, &format!("let {local}: any = {dflt};"));
                    g.line(1, "if (buf.position < _dh) {");
                }
                g.dec(2, &v, &m.field.field_type);
                g.line(2, &format!("{local} = {v};"));
                g.line(1, "}");
            }
            g.line(1, "buf.skipTo(_dh);");
        }
        Ext::Mutable => {
            // A member absent from the data takes its default value, never
            // what an object held before (7.4.1.2.3, lines 6195-6203; lines
            // 3390-3393); an absent optional member has no value.
            for (m, local) in chain.iter().zip(&locals) {
                let dflt = if m.field.is_optional() {
                    "undefined".to_string()
                } else {
                    g.default_expr(&m.field.field_type)
                };
                g.line(1, &format!("let {local}: any = {dflt};"));
            }
            g.line(1, "const _dh = buf.getLenEnd();");
            g.line(1, "while (buf.position < _dh) {");
            g.line(2, "const [_mu, _id, _end] = buf.getEmheader(_dh);");
            g.line(2, "switch (_id) {");
            for (m, local) in chain.iter().zip(&locals) {
                let v = g.fresh("m");
                g.line(3, &format!("case {:#x}: {{", m.id));
                g.dec(4, &v, &m.field.field_type);
                g.line(4, &format!("{local} = {v};"));
                g.line(4, "break;");
                g.line(3, "}");
            }
            g.line(3, "default:");
            g.line(
                4,
                "if (_mu) { throw new Error(`unknown must-understand member id 0x${_id.toString(16)}`); }",
            );
            g.line(2, "}");
            g.line(2, "buf.skipTo(_end);");
            g.line(1, "}");
            g.line(1, "buf.skipTo(_dh);");
        }
    }
    let fields: Vec<String> = chain
        .iter()
        .zip(&locals)
        .map(|(m, l)| format!("{}: {l}", ts_ident(&m.field.name)))
        .collect();
    g.line(1, &format!("return {{ {} }};", fields.join(", ")));
    g.line(0, "}");
    g.line(0, "");

    // ---- default (Table 9: no optional member, the others at their
    // default) ----
    let defaults: Vec<String> = chain
        .iter()
        .filter(|m| !m.field.is_optional())
        .map(|m| {
            format!(
                "{}: {}",
                ts_ident(&m.field.name),
                g.default_expr(&m.field.field_type)
            )
        })
        .collect();
    g.line(
        0,
        &format!("/** The default {idl} (DDS-XTypes 1.3 Table 9). */"),
    );
    g.line(0, &format!("export function default{name}(): {name} {{"));
    g.line(1, &format!("return {{ {} }};", defaults.join(", ")));
    g.line(0, "}");
    g.line(0, "");
    struct_dec1(&mut g, &chain, ext, name, &fields);
    g.out.push_str(&by_encapsulation(name, ext));
    g.out
}

/// `decode<Name>ByEncapsulation(encapsulationId, data)`: the body of a
/// sample decoded by the decoder its encapsulation identifier names
/// (DDS-XTypes 1.3 Table 60); then `extensibility<Name>`, the type's
/// extensibility (7.2.2.4.4) as the hdds TypeScript SDK names it, which
/// `createWriter` takes so every sample's identifier names it.
fn by_encapsulation(name: &str, ext: Ext) -> String {
    let kw = ext.keyword();
    format!(
        "/**\n * Decode the body of a sample whose encapsulation identifier is\n * \
         `encapsulationId` (DDS-XTypes 1.3 Table 60): CDR_LE (0x0001) and PL_CDR_LE\n * \
         (0x0003) as XCDR1, CDR2_LE (0x0007), D_CDR2_LE (0x0009) and PL_CDR2_LE\n * \
         (0x000b) as XCDR2; an Error otherwise.\n */\n\
         export function decode{name}ByEncapsulation(encapsulationId: number, data: ArrayBuffer | Uint8Array): {name} {{\n  \
         switch (encapsulationId) {{\n    \
         case 0x0001: case 0x0003: return decode{name}Cdr1(new Cdr1Buffer(data));\n    \
         case 0x0007: case 0x0009: case 0x000b: return decode{name}(new Cdr2Buffer(data));\n    \
         default: throw new Error(`encapsulation 0x${{encapsulationId.toString(16)}} is not decoded`);\n  \
         }}\n}}\n\n\
         /**\n * Extensibility of {name} (DDS-XTypes 1.3 7.2.2.4.4). Pass it to the hdds\n * \
         SDK's createWriter so every sample is labelled with it (Table 60).\n */\n\
         export const extensibility{name} = \"{kw}\" as const;\n\n"
    )
}

/// `decode<Name>Cdr1`, the XCDR1 decoder of a structure (DDS-XTypes 1.3
/// 7.4.1): FINAL and APPENDABLE alike, no DHEADER (a member of an
/// APPENDABLE structure past the end of the data at its default,
/// 7.4.1.2.3), an optional member as a parameter (rule 19); MUTABLE as a
/// parameter list closed by `PID_LIST_END` (rules 24-25), members by id, an
/// unknown one skipped unless it must be understood, a missing one at its
/// default.
fn struct_dec1(
    g: &mut Gen<'_>,
    chain: &[data_model::ChainMember],
    ext: Ext,
    name: &str,
    fields: &[String],
) {
    g.v1 = true;
    g.line(
        0,
        &format!("export function decode{name}Cdr1(buf: Cdr1Buffer): {name} {{"),
    );
    let locals: Vec<String> = (0..chain.len()).map(|i| format!("_f{i}")).collect();
    for (m, local) in chain.iter().zip(&locals) {
        if m.field.is_optional() {
            g.line(1, &format!("let {local}: any = undefined;"));
        } else if ext == Ext::Final {
            g.line(1, &format!("let {local}: any;"));
        } else {
            let dflt = g.default_expr(&m.field.field_type);
            g.line(1, &format!("let {local}: any = {dflt};"));
        }
    }
    if ext == Ext::Mutable {
        g.line(1, "for (;;) {");
        g.line(2, "const _p = buf.pl1Member();");
        g.line(2, "if (_p === undefined) { break; }");
        g.line(2, "const [_id, _mu, _end, _prev] = _p;");
        g.line(2, "switch (_id) {");
        for (m, local) in chain.iter().zip(&locals) {
            let v = g.fresh("m");
            g.line(3, &format!("case {:#x}: {{", m.id));
            g.dec(4, &v, &m.field.field_type);
            g.line(4, &format!("{local} = {v};"));
            g.line(4, "break;");
            g.line(3, "}");
        }
        g.line(3, "default:");
        g.line(
            4,
            "if (_mu) { throw new Error(`unknown must-understand member id 0x${_id.toString(16)}`); }",
        );
        g.line(2, "}");
        g.line(2, "buf.pl1Done(_end, _prev);");
        g.line(1, "}");
    } else {
        let app = ext == Ext::Appendable;
        for (m, local) in chain.iter().zip(&locals) {
            let mi = if app {
                g.line(1, "if (buf.position < buf.length) {");
                2
            } else {
                1
            };
            let v = g.fresh("o");
            g.line(mi, "{");
            if m.field.is_optional() {
                g.line(mi + 1, "const _p = buf.pl1Member();");
                g.line(
                    mi + 1,
                    "if (_p === undefined) { throw new Error(\"parameter list end where an optional member is expected\"); }",
                );
                g.line(mi + 1, "if (_p[2] > buf.position) {");
                g.dec(mi + 2, &v, &m.field.field_type);
                g.line(mi + 2, &format!("{local} = {v};"));
                g.line(mi + 1, "}");
                g.line(mi + 1, "buf.pl1Done(_p[2], _p[3]);");
            } else {
                g.dec(mi + 1, &v, &m.field.field_type);
                g.line(mi + 1, &format!("{local} = {v};"));
            }
            g.line(mi, "}");
            if app {
                g.line(1, "}");
            }
        }
    }
    g.line(1, &format!("return {{ {} }};", fields.join(", ")));
    g.line(0, "}");
    g.line(0, "");
    g.v1 = false;
}

/// The discriminator's holder width and signedness (rule 26: the
/// discriminator serializes as its type does; an enumeration at its
/// `@bit_bound` width).
fn disc_holder(idx: &TypeIndex, ty: &IdlType) -> (usize, bool) {
    match idx.resolve(ty) {
        IdlType::Primitive(p) => match p {
            PrimitiveType::Boolean
            | PrimitiveType::Octet
            | PrimitiveType::UInt8
            | PrimitiveType::Char => (1, false),
            PrimitiveType::Int8 => (1, true),
            PrimitiveType::WChar | PrimitiveType::UnsignedShort | PrimitiveType::UInt16 => {
                (2, false)
            }
            PrimitiveType::Short | PrimitiveType::Int16 => (2, true),
            PrimitiveType::UnsignedLong | PrimitiveType::UInt32 => (4, false),
            PrimitiveType::LongLong | PrimitiveType::Int64 => (8, true),
            PrimitiveType::UnsignedLongLong | PrimitiveType::UInt64 => (8, false),
            _ => (4, true),
        },
        IdlType::Named(n) => match idx.named(&n) {
            Some(Named::Enum { bit_bound, .. }) => (enum_width(*bit_bound), true),
            _ => (4, true),
        },
        _ => (4, true),
    }
}

/// The integer value of every label of every case of `u`, read by
/// `data_model::union_label_value` (integers, `TRUE` / `FALSE`, character
/// literals, enumerators, scoped or not); the `default` label has none.
///
/// # Errors
///
/// Returns the label no value can be read from.
pub(super) fn label_values(idx: &TypeIndex, u: &Union) -> Result<Vec<Vec<i64>>, String> {
    u.cases
        .iter()
        .map(|c| {
            c.labels
                .iter()
                .filter_map(|l| match l {
                    UnionLabel::Value(v) => Some(
                        union_label_value(idx, &u.discriminator, v)
                            .ok_or_else(|| format!("case label `{v}` has no value")),
                    ),
                    UnionLabel::Default => None,
                })
                .collect()
        })
        .collect()
}

/// The integer key of the discriminator held in `d`, as a TypeScript
/// expression, and the literal of a label value compared with it: a
/// boolean is 0 or 1, a char its code unit (it is held as a one-character
/// string), a 64-bit discriminator a bigint, any other a number.
pub(super) fn disc_key(idx: &TypeIndex, disc: &IdlType, d: &str) -> (String, bool) {
    let (width, _) = disc_holder(idx, disc);
    match idx.resolve(disc) {
        IdlType::Primitive(PrimitiveType::Boolean) => (format!("({d} ? 1 : 0)"), false),
        IdlType::Primitive(PrimitiveType::Char | PrimitiveType::WChar) => (
            format!("(typeof {d} === \"string\" ? {d}.charCodeAt(0) : Number({d}))"),
            false,
        ),
        _ if width == 8 => (format!("BigInt({d})"), true),
        _ => (format!("Number({d})"), false),
    }
}

/// The condition selecting a case of labels `values` on the key `k`.
pub(super) fn case_cond(k: &str, values: &[i64], big: bool) -> String {
    values
        .iter()
        .map(|v| {
            if big {
                format!("{k} === {v}n")
            } else {
                format!("{k} === {v}")
            }
        })
        .collect::<Vec<_>>()
        .join(" || ")
}

/// `default<Name>()` of a union (DDS-XTypes 1.3 Table 9, spec text line
/// 2342): the discriminator type's default (zero, `false`, the first
/// literal), and the default of the member it selects, if any.
pub(super) fn union_default(idx: &TypeIndex, u: &Union, labels: &[Vec<i64>]) -> String {
    let g = Gen::new(idx);
    let name = flat(&u.name);
    let (width, _) = disc_holder(idx, &u.discriminator);
    let (d0, disc) = match idx.resolve(&u.discriminator) {
        IdlType::Named(n) => match idx.named(&n) {
            Some(Named::Enum { literals, .. }) => literals.first().map_or_else(
                || (0, "0".to_string()),
                |(lit, v)| (*v, format!("{}.{lit}", flat(&n))),
            ),
            _ => (0, "0".to_string()),
        },
        IdlType::Primitive(PrimitiveType::Boolean) => (0, "false".to_string()),
        IdlType::Primitive(PrimitiveType::Char | PrimitiveType::WChar) => {
            (0, "\"\\u0000\"".to_string())
        }
        _ if width == 8 => (0, "0n".to_string()),
        _ => (0, "0".to_string()),
    };
    let selected = labels.iter().position(|l| l.contains(&d0)).or_else(|| {
        u.cases
            .iter()
            .position(|c| c.labels.iter().any(|l| matches!(l, UnionLabel::Default)))
    });
    let member = selected
        .map(|i| &u.cases[i].field)
        .filter(|f| !matches!(f.field_type, IdlType::Primitive(PrimitiveType::Void)))
        .map_or_else(String::new, |f| {
            format!(", {}: {}", ts_ident(&f.name), g.default_expr(&f.field_type))
        });
    format!(
        "/** The default {} (DDS-XTypes 1.3 Table 9). */\n\
         export function default{name}(): {name} {{\n  \
         return {{ discriminator: {disc}{member} }};\n}}\n\n",
        idl_name(&u.name)
    )
}

/// `encode<Name>` / `decode<Name>` of a union. FINAL and APPENDABLE
/// (DHEADER, rules 26, 30); a discriminator no case selects is serialized
/// alone (rule 26, line 6977: the selected member is optional). `labels`
/// are the label values of each case (`label_values`).
pub(super) fn union_codec(idx: &TypeIndex, u: &Union, labels: &[Vec<i64>]) -> String {
    let mut out = union_codec_impl(idx, u, labels, false);
    let mut key_union = u.clone();
    let labels = if u.discriminator_is_key() {
        key_union.cases.clear();
        &[][..]
    } else {
        labels
    };
    let key = union_codec_impl(idx, &key_union, labels, true);
    let end = key.find("export function decode").unwrap_or(key.len());
    let name = flat(&u.name);
    out.push_str(&key[..end].replacen(
        &format!("function encode{name}("),
        &format!("function encodeKey{name}("),
        1,
    ));
    out
}

#[allow(clippy::too_many_lines)]
fn union_codec_impl(idx: &TypeIndex, u: &Union, labels: &[Vec<i64>], key_only: bool) -> String {
    let name = &flat(&u.name);
    let mut g = Gen::new(idx);
    g.key_only = key_only;
    let ext = union_ext(u);
    let resolved = idx.resolve(&u.discriminator);
    let disc_enum = match &resolved {
        IdlType::Named(n) if matches!(idx.named(n), Some(Named::Enum { .. })) => Some(flat(n)),
        _ => None,
    };
    let (width, signed) = disc_holder(idx, &u.discriminator);
    let (put, get) = int_methods(width, signed);
    let is_bool = matches!(resolved, IdlType::Primitive(PrimitiveType::Boolean));
    let is_char = matches!(
        resolved,
        IdlType::Primitive(PrimitiveType::Char | PrimitiveType::WChar)
    );
    let (key, big) = disc_key(idx, &u.discriminator, "_d");

    let mut arms: Vec<(String, usize)> = Vec::new();
    let mut default = None;
    for (i, (case, values)) in u.cases.iter().zip(labels).enumerate() {
        if case.labels.iter().any(|l| matches!(l, UnionLabel::Default)) {
            default = Some(i);
        }
        if !values.is_empty() {
            arms.push((case_cond("_k", values, big), i));
        }
    }
    let case_ty = |i: usize| format!("{name}_{}", u.cases[i].field.name);
    let disc_write = if is_bool {
        "buf.writeBoolean(_d);".to_string()
    } else if is_char {
        let m = if width == 1 { "putChar" } else { "putWChar" };
        format!("buf.{m}(_d);")
    } else if let Some(e) = &disc_enum {
        format!("encode{e}(_d, buf);")
    } else if width == 8 {
        format!("buf.{put}(BigInt(_d));")
    } else {
        format!("buf.{put}(_d);")
    };
    let disc_read = if is_bool {
        "buf.getBoolean()".to_string()
    } else if is_char {
        let m = if width == 1 { "getChar" } else { "getWChar" };
        format!("buf.{m}()")
    } else if let Some(e) = &disc_enum {
        format!("decode{e}(buf)")
    } else {
        format!("buf.{get}()")
    };
    if ext == Ext::Mutable {
        let mut select: Vec<(String, usize)> = arms.clone();
        if let Some(i) = default {
            select.push((String::new(), i));
        }
        mutable_union(&mut g, u, &select, &disc_write, &disc_read, &key);
        g.out.push_str(&by_encapsulation(name, ext));
        return g.out;
    }

    // ---- encode ----
    g.line(
        0,
        &format!("export function encode{name}(obj: {name}, buf: Cdr2Buffer): void {{"),
    );
    if ext == Ext::Appendable {
        g.line(1, "const _dh = buf.beginLen();");
    }
    g.line(1, "const _d: any = obj.discriminator;");
    g.line(1, &format!("const _k = {key};"));
    if is_bool {
        g.line(1, "buf.writeBoolean(_d);");
    } else if is_char {
        let m = if width == 1 { "putChar" } else { "putWChar" };
        g.line(1, &format!("buf.{m}(_d);"));
    } else if let Some(e) = &disc_enum {
        g.line(1, &format!("encode{e}(_d, buf);"));
    } else if width == 8 {
        g.line(1, &format!("buf.{put}(BigInt(_d));"));
    } else {
        g.line(1, &format!("buf.{put}(_d);"));
    }
    let mut kw = "if";
    for (cond, i) in &arms {
        g.line(1, &format!("{kw} ({cond}) {{"));
        let place = format!(
            "(obj as {}).{}",
            case_ty(*i),
            ts_ident(&u.cases[*i].field.name)
        );
        g.enc(2, &place, &u.cases[*i].field.field_type);
        kw = "} else if";
    }
    if let Some(i) = default {
        g.line(1, if arms.is_empty() { "{" } else { "} else {" });
        let place = format!(
            "(obj as {}).{}",
            case_ty(i),
            ts_ident(&u.cases[i].field.name)
        );
        g.enc(2, &place, &u.cases[i].field.field_type);
        g.line(1, "}");
    } else if !arms.is_empty() {
        g.line(1, "}");
    }
    if ext == Ext::Appendable {
        g.line(1, "buf.endLen(_dh);");
    }
    g.line(0, "}");
    g.line(0, "");

    // ---- decode ----
    g.line(
        0,
        &format!("export function decode{name}(buf: Cdr2Buffer): {name} {{"),
    );
    if ext == Ext::Appendable {
        g.line(1, "const _dh = buf.getLenEnd();");
    }
    if is_bool {
        g.line(1, "const _d: any = buf.getBoolean();");
    } else if is_char {
        let m = if width == 1 { "getChar" } else { "getWChar" };
        g.line(1, &format!("const _d: any = buf.{m}();"));
    } else if let Some(e) = &disc_enum {
        g.line(1, &format!("const _d: any = decode{e}(buf);"));
    } else {
        g.line(1, &format!("const _d: any = buf.{get}();"));
    }
    g.line(1, &format!("const _k = {key};"));
    g.line(1, "let _r: any = { discriminator: _d };");
    let mut kw = "if";
    for (cond, i) in &arms {
        g.line(1, &format!("{kw} ({cond}) {{"));
        let v = g.fresh("v");
        g.dec(2, &v, &u.cases[*i].field.field_type);
        g.line(
            2,
            &format!(
                "_r = {{ discriminator: _d, {}: {v} }};",
                ts_ident(&u.cases[*i].field.name)
            ),
        );
        kw = "} else if";
    }
    if let Some(i) = default {
        g.line(1, if arms.is_empty() { "{" } else { "} else {" });
        let v = g.fresh("v");
        g.dec(2, &v, &u.cases[i].field.field_type);
        g.line(
            2,
            &format!(
                "_r = {{ discriminator: _d, {}: {v} }};",
                ts_ident(&u.cases[i].field.name)
            ),
        );
        g.line(1, "}");
    } else if !arms.is_empty() {
        g.line(1, "}");
    }
    if ext == Ext::Appendable {
        g.line(1, "buf.skipTo(_dh);");
    }
    g.line(1, &format!("return _r as {name};"));
    g.line(0, "}");
    g.line(0, "");

    // ---- XCDR1 decode: FINAL and APPENDABLE alike, no DHEADER ----
    g.v1 = true;
    g.line(
        0,
        &format!("export function decode{name}Cdr1(buf: Cdr1Buffer): {name} {{"),
    );
    g.line(1, &format!("const _d: any = {disc_read};"));
    g.line(1, &format!("const _k = {key};"));
    g.line(1, "let _r: any = { discriminator: _d };");
    let mut kw = "if";
    for (cond, i) in &arms {
        g.line(1, &format!("{kw} ({cond}) {{"));
        let v = g.fresh("v");
        g.dec(2, &v, &u.cases[*i].field.field_type);
        g.line(
            2,
            &format!(
                "_r = {{ discriminator: _d, {}: {v} }};",
                ts_ident(&u.cases[*i].field.name)
            ),
        );
        kw = "} else if";
    }
    if let Some(i) = default {
        g.line(1, if arms.is_empty() { "{" } else { "} else {" });
        let v = g.fresh("v");
        g.dec(2, &v, &u.cases[i].field.field_type);
        g.line(
            2,
            &format!(
                "_r = {{ discriminator: _d, {}: {v} }};",
                ts_ident(&u.cases[i].field.name)
            ),
        );
        g.line(1, "}");
    } else if !arms.is_empty() {
        g.line(1, "}");
    }
    g.line(1, &format!("return _r as {name};"));
    g.line(0, "}");
    g.line(0, "");
    g.v1 = false;
    g.out.push_str(&by_encapsulation(name, ext));
    g.out
}

/// A MUTABLE union (rule 27, spec text line 6986): DHEADER, the
/// discriminator as member 0 with the must-understand flag (7.2.2.4.4.4.6,
/// line 2299), then the selected case as member `union_case_ids(u)[i]`.
/// The decoder reads members by id, skips unknown ones (refuses them with
/// the M flag), requires the discriminator, and refuses a case member that
/// is not the one the discriminator selects. `select` lists the
/// (condition, case) pairs in selection order, the default case last with
/// an empty condition.
#[allow(clippy::too_many_lines)]
fn mutable_union(
    g: &mut Gen<'_>,
    u: &Union,
    select: &[(String, usize)],
    disc_write: &str,
    disc_read: &str,
    key: &str,
) {
    let idx = g.idx;
    let name = &flat(&u.name);
    let ids = union_case_ids(idx, u);
    let disc_lc = discriminator_length_code(idx, &u.discriminator);
    let is_void = |i: usize| {
        matches!(
            u.cases[i].field.field_type,
            IdlType::Primitive(PrimitiveType::Void)
        )
    };
    let open = |k: usize, cond: &str| match (k, cond.is_empty()) {
        (0, true) => "{".to_string(),
        (_, true) => "} else {".to_string(),
        (0, false) => format!("if ({cond}) {{"),
        (_, false) => format!("}} else if ({cond}) {{"),
    };

    // ---- encode ----
    g.line(
        0,
        &format!("export function encode{name}(obj: {name}, buf: Cdr2Buffer): void {{"),
    );
    g.line(1, "const _dh = buf.beginLen();");
    g.line(1, "const _d: any = obj.discriminator;");
    g.line(1, &format!("const _k = {key};"));
    g.line(1, &format!("buf.putEmheader(true, {disc_lc}, 0x0);"));
    g.line(1, disc_write);
    for (k, (cond, i)) in select.iter().enumerate() {
        g.line(1, &open(k, cond));
        if is_void(*i) {
            continue;
        }
        let field = &u.cases[*i].field;
        let lc = length_code(idx, &field.field_type);
        let mu = must_understand(field);
        let place = format!("(obj as {name}_{}).{}", field.name, ts_ident(&field.name));
        g.line(
            2,
            &format!(
                "buf.putEmheader({mu}, {lc}, {:#x}); // {}",
                ids[*i], field.name
            ),
        );
        if lc == 4 {
            g.line(2, "const _n = buf.beginLen();");
            g.enc(2, &place, &field.field_type);
            g.line(2, "buf.endLen(_n);");
        } else {
            g.enc(2, &place, &field.field_type);
        }
    }
    if !select.is_empty() {
        g.line(1, "}");
    }
    g.line(1, "buf.endLen(_dh);");
    g.line(0, "}");
    g.line(0, "");

    // ---- decode ----
    g.line(
        0,
        &format!("export function decode{name}(buf: Cdr2Buffer): {name} {{"),
    );
    g.line(1, "let _d: any = undefined;");
    g.line(1, "let _v: any = undefined;");
    g.line(1, "let _case = -1;");
    g.line(1, "const _dh = buf.getLenEnd();");
    g.line(1, "while (buf.position < _dh) {");
    g.line(2, "const [_mu, _id, _end] = buf.getEmheader(_dh);");
    g.line(2, "switch (_id) {");
    g.line(3, "case 0x0:");
    g.line(4, &format!("_d = {disc_read};"));
    g.line(4, "break;");
    for (i, case) in u.cases.iter().enumerate() {
        if is_void(i) {
            continue;
        }
        let v = g.fresh("v");
        g.line(3, &format!("case {:#x}: {{", ids[i]));
        g.dec(4, &v, &case.field.field_type);
        g.line(4, &format!("_v = {v};"));
        g.line(4, &format!("_case = {i};"));
        g.line(4, "break;");
        g.line(3, "}");
    }
    g.line(3, "default:");
    g.line(
        4,
        "if (_mu) { throw new Error(`unknown must-understand member id 0x${_id.toString(16)}`); }",
    );
    g.line(2, "}");
    g.line(2, "buf.skipTo(_end);");
    g.line(1, "}");
    g.line(1, "buf.skipTo(_dh);");
    // The discriminator checked against the case member read, the value
    // built: the same text ends the XCDR1 decoder.
    let tail_start = g.out.len();
    g.line(
        1,
        &format!(
            "if (_d === undefined) {{ throw new Error(\"{}: discriminator missing\"); }}",
            idl_name(&u.name)
        ),
    );
    g.line(1, &format!("const _k = {key};"));
    g.line(1, "let _sel = -1;");
    let mut field_of = Vec::new();
    for (k, (cond, i)) in select.iter().enumerate() {
        g.line(1, &open(k, cond));
        if !is_void(*i) {
            g.line(2, &format!("_sel = {i};"));
            field_of.push(*i);
        }
    }
    if !select.is_empty() {
        g.line(1, "}");
    }
    g.line(
        1,
        &format!(
            "if (_sel !== _case) {{ throw new Error(\"{}: the case member is not the one the discriminator selects\"); }}",
            idl_name(&u.name)
        ),
    );
    g.line(1, "const _r: any = { discriminator: _d };");
    for i in field_of {
        g.line(
            1,
            &format!(
                "if (_case === {i}) {{ _r.{} = _v; }}",
                ts_ident(&u.cases[i].field.name)
            ),
        );
    }
    g.line(1, &format!("return _r as {name};"));
    g.line(0, "}");
    g.line(0, "");
    let check_tail = g.out[tail_start..].to_string();

    // ---- XCDR1 decode: the parameter list of the discriminator (member
    // 0) and the selected case (rules 27, 24-25), checked as above ----
    g.v1 = true;
    g.line(
        0,
        &format!("export function decode{name}Cdr1(buf: Cdr1Buffer): {name} {{"),
    );
    g.line(1, "let _d: any = undefined;");
    g.line(1, "let _v: any = undefined;");
    g.line(1, "let _case = -1;");
    g.line(1, "for (;;) {");
    g.line(2, "const _p = buf.pl1Member();");
    g.line(2, "if (_p === undefined) { break; }");
    g.line(2, "const [_id, _mu, _end, _prev] = _p;");
    g.line(2, "switch (_id) {");
    g.line(3, "case 0x0:");
    g.line(4, &format!("_d = {disc_read};"));
    g.line(4, "break;");
    for (i, case) in u.cases.iter().enumerate() {
        if is_void(i) {
            continue;
        }
        let v = g.fresh("v");
        g.line(3, &format!("case {:#x}: {{", ids[i]));
        g.dec(4, &v, &case.field.field_type);
        g.line(4, &format!("_v = {v};"));
        g.line(4, &format!("_case = {i};"));
        g.line(4, "break;");
        g.line(3, "}");
    }
    g.line(3, "default:");
    g.line(
        4,
        "if (_mu) { throw new Error(`unknown must-understand member id 0x${_id.toString(16)}`); }",
    );
    g.line(2, "}");
    g.line(2, "buf.pl1Done(_end, _prev);");
    g.line(1, "}");
    g.out.push_str(&check_tail);
    g.v1 = false;
}

/// `encode<Name>` / `decode<Name>` of an enumeration: the value at its
/// `@bit_bound` width (7.3.1.2.1.6); decoding refuses a value that names no
/// literal.
pub(super) fn enum_codec(name: &str, width: usize) -> String {
    let (put, get) = int_methods(width, true);
    format!(
        "export function encode{name}(v: {name}, buf: Cdr2Buffer): void {{\n  \
         buf.{put}(v as number);\n}}\n\n\
         export function decode{name}(buf: Cdr2Buffer): {name} {{\n  \
         const v = buf.{get}();\n  \
         if ({name}[v] === undefined) {{ throw new Error(`${{v}} is not a literal of {name}`); }}\n  \
         return v as {name};\n}}\n\n"
    )
}

/// `encode<Name>` / `decode<Name>` of a bitmask: the value at its
/// `@bit_bound` width; a 64-bit bitmask is a bigint both ways.
pub(super) fn bitmask_codec(name: &str, width: usize) -> String {
    let (put, get) = int_methods(width, false);
    let value = if width == 8 {
        "BigInt(val)"
    } else {
        "Number(val)"
    };
    format!(
        "export function encode{name}(val: number | bigint, buf: Cdr2Buffer): void {{\n  \
         buf.{put}({value});\n}}\n\n\
         export function decode{name}(buf: Cdr2Buffer): {name} {{\n  \
         return buf.{get}();\n}}\n\n"
    )
}
