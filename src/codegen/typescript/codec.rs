//! XCDR2 codec of the generated TypeScript types (DDS-`XTypes` 1.3
//! 7.4.3.5.3, spec text lines 6750-7016).
//!
//! Every structure and union gets `encode<Name>(obj, buf)` and
//! `decode<Name>(buf)`, serializing through `Cdr2Buffer`, emitted once per
//! file. Alignment is `min(size, 4)` measured from the buffer's origin (the
//! offset it was created at), never from the first byte of a nested value
//! (rule 1: one ORIGIN for the whole body). Padding bytes are written as
//! zero.
//!
//! What the specification fixes at generation time comes from the shared
//! model (`codegen::data_model`): extensibility, member ids, DHEADERs of
//! collections, enumeration and bitmask widths, `EMHEADER1` length codes and
//! the must-understand flag.

