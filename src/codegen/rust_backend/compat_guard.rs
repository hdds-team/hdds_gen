//! `hdds` runtime compatibility guard emitted once per generated Rust file.
//!
//! The Rust backend's generated code calls straight into `hdds` internals
//! (the `DDS` trait, `core::ser` CDR2 traits, `xtypes` `TypeObject` shapes)
//! that are not part of the crate's stable public API. Generating with this
//! `hddsgen` and building against an `hdds` runtime from before those
//! internals existed used to fail with thousands of unrelated-looking
//! compiler errors (missing trait methods, missing fields, missing types)
//! with nothing pointing at "upgrade `hdds`" as the fix.
//!
//! This module emits a small `const` block, once per generated file, that
//! turns that into ONE error naming the required runtime version. See
//! `hdds::codegen` (in the `hdds` crate) for the other half of the contract.

/// ABI number this `hddsgen` release requires from `hdds::codegen::CODEGEN_ABI`.
///
/// Bump together with a bump of `hdds::codegen::CODEGEN_ABI` in the `hdds`
/// crate, whenever a change to the internals listed above would make code
/// generated under the OLD number silently wrong (not just a compile error)
/// against the NEW runtime.
pub const REQUIRED_CODEGEN_ABI: u32 = 1;

/// The `hdds` crate version this `hddsgen` targets: the minimum for the
/// current [`REQUIRED_CODEGEN_ABI`]. It is the single source for the version
/// written into `--example` Cargo.toml files and for the assertion message
/// below. The check itself is the ABI number, never a version string.
pub const REQUIRED_HDDS_VERSION: &str = "1.5.0";

/// The `hdds-micro` crate version the `gen micro --example` Cargo.toml
/// requests. `crates/hdds-micro/Cargo.toml` inherits the HDDS workspace
/// version (`version.workspace = true`), so this must move in step with
/// [`REQUIRED_HDDS_VERSION`] whenever the workspace version bumps.
pub const REQUIRED_HDDS_MICRO_VERSION: &str = "1.5.0";

/// Returns the compatibility guard block to splice into a generated file,
/// right after the `// DO NOT EDIT` banner and before anything that uses
/// `hdds` internals.
///
/// Shape, and what it can and cannot do:
/// - `_HDDS_CODEGEN_GUARD` references `hdds::codegen::REQUIRES_HDDS_1_5`.
///   On an `hdds` release older than 1.5.0 the `codegen` module does not
///   exist, so rustc reports `could not find codegen in hdds` (name
///   resolution). That error does NOT name the symbol or the fix, and rustc
///   reports the `use hdds::{...}` import errors before it, so the guard is
///   not the first error a user sees. It only tells the user which module is
///   missing. A `compile_error!` cannot be made conditional on the runtime's
///   version from generated code, so no clearer message is possible here.
///   The version the `--example` Cargo.toml requests (see
///   [`REQUIRED_HDDS_VERSION`]) is what keeps a stale runtime out.
/// - The `assert!` compares `hdds::codegen::CODEGEN_ABI` with `>=`. It is
///   reached only when `codegen` exists with a lower ABI, and then it names
///   the exact required version. A FUTURE incompatible bump on both sides
///   (see [`REQUIRED_CODEGEN_ABI`]) is just two numbers to update.
/// - Both are compile-time only (`const _: ...`): zero runtime cost, and
///   they do not appear in the generated file's public API.
pub fn compat_guard_block() -> String {
    let abi = REQUIRED_CODEGEN_ABI;
    let ver = REQUIRED_HDDS_VERSION;
    format!(
        "// hdds <-> hddsgen compatibility guard (see `hdds::codegen` docs).\n\
         // Do not remove: this file requires hdds::codegen::CODEGEN_ABI >= {abi}\n\
         // (hdds >= {ver}). An hdds older than {ver} has no `codegen` module,\n\
         // so rustc reports `could not find codegen in hdds`: upgrade the\n\
         // hdds dependency to >= {ver}. The assert below names the required\n\
         // version when `codegen` exists with a lower CODEGEN_ABI.\n\
         #[doc(hidden)]\n\
         #[allow(dead_code)]\n\
         const _HDDS_CODEGEN_GUARD: u32 = hdds::codegen::REQUIRES_HDDS_1_5;\n\
         const _: () = assert!(\n    \
             hdds::codegen::CODEGEN_ABI >= {abi},\n    \
             \"this file was generated by hddsgen for hdds::codegen::CODEGEN_ABI >= {abi} \
(hdds >= {ver}); the linked `hdds` crate is older or incompatible - upgrade the `hdds` dependency to >= {ver}\",\n\
         );\n\n"
    )
}

#[cfg(test)]
mod tests {
    use super::compat_guard_block;

    #[test]
    fn block_names_the_required_version() {
        let block = compat_guard_block();
        assert!(block.contains("REQUIRES_HDDS_1_5"));
        assert!(block.contains("CODEGEN_ABI"));
        assert!(block.contains("1.5.0"));
    }
}
