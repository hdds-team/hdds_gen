/// Serde rename style for JSON serialization
#[derive(Clone, Copy, Debug, Default)]
pub enum SerdeRename {
    /// No rename (native Rust style)
    #[default]
    None,
    /// camelCase (JavaScript/TypeScript)
    Camel,
    /// `PascalCase` (C#/.NET)
    Pascal,
    /// kebab-case
    Kebab,
}

/// Generates Rust binding code with CDR2 serialization helpers.
pub struct RustGenerator {
    indent_level: usize,
    /// Add serde derives to generated types
    pub(crate) serde: bool,
    /// Serde rename style
    pub(crate) serde_rename: SerdeRename,
}

impl RustGenerator {
    /// Creates a new Rust generator.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            indent_level: 0,
            serde: false,
            serde_rename: SerdeRename::None,
        }
    }

    /// Creates a new Rust generator with serde support.
    #[must_use]
    pub const fn with_serde(serde_rename: SerdeRename) -> Self {
        Self {
            indent_level: 0,
            serde: true,
            serde_rename,
        }
    }

    fn indent(&self) -> String {
        "    ".repeat(self.indent_level)
    }
}

impl Default for RustGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl RustGenerator {
    /// Returns the serde derive string if serde is enabled
    pub(crate) const fn serde_derive(&self) -> &'static str {
        if self.serde {
            ", serde::Serialize, serde::Deserialize"
        } else {
            ""
        }
    }

    /// Returns the serde `rename_all` attribute for enums
    pub(crate) const fn serde_rename_attr(&self) -> &'static str {
        if !self.serde {
            return "";
        }
        match self.serde_rename {
            SerdeRename::None => "",
            SerdeRename::Camel => "#[serde(rename_all = \"camelCase\")]\n",
            SerdeRename::Pascal => "#[serde(rename_all = \"PascalCase\")]\n",
            SerdeRename::Kebab => "#[serde(rename_all = \"kebab-case\")]\n",
        }
    }
}

impl CodeGenerator for RustGenerator {
    fn generate(&self, ast: &IdlFile) -> Result<String> {
        // References whose spelling a scope-less lookup would misread are
        // written as their absolute global name (IDL 4.2 7.5), and module
        // `@autoid` is carried by each type.
        let ast = &crate::scope::merge_reopened_modules(&crate::scope::for_codegen(ast));
        let mut output = String::new();

        // Type index of the file: the codec, the TypeObjects and the
        // KeyHolder of keyed types all resolve names through it.
        key_hash::set_index(crate::codegen::key_holder::TypeIndex::new(ast));

        // Header
        output.push_str("// Generated by hddsgen v");
        output.push_str(env!("HDDS_VERSION"));
        output.push('\n');
        output.push_str("// DO NOT EDIT\n");
        output.push_str("// Compatible with include!() macro\n\n");

        // hdds <-> hddsgen runtime compatibility guard, once per generated
        // file (not per type): see compat_guard module docs.
        output.push_str(&compat_guard::compat_guard_block());

        // Phase 7a: Import CDR2 traits from hdds crate
        output.push_str("use hdds::{Cdr2Encode, Cdr2Decode, CdrError};\n\n");

        output.push_str(&codec::cdr_module());
        output.push_str(&crate::codegen::rust_paths::root_module());

        if key_hash::file_needs_payload_writer(ast) {
            output.push_str(&key_hash::payload_writer_module());
        }

        // NOTE: Vec/HashMap/Array trait impls are in hdds crate, not generated here
        // This avoids orphan rule violations (E0117)

        // Prelude if certain features are used
        if uses_fixed(ast) {
            Self::emit_fixed_support(&mut output);
            output.push('\n');
        }

        // Generate definitions (recursive for nested modules)
        self.generate_definitions(&mut output, &ast.definitions, &[], "");

        Ok(output)
    }
}

impl RustGenerator {
    /// Recursively generate code for a list of definitions.
    ///
    /// `module_path` tracks the current module nesting (e.g., `["my_mod", "inner"]`)
    /// for FQN generation. `indent` is the current indentation prefix.
    fn generate_definitions(
        &self,
        output: &mut String,
        definitions: &[Definition],
        module_path: &[&str],
        indent: &str,
    ) {
        // Build FQN prefix for struct type names (e.g., "my_mod::inner::")
        let module_name = if module_path.is_empty() {
            None
        } else {
            Some(module_path.join("::"))
        };

        // Fully qualified IDL name, the `TypeObject` type name.
        let fqn = |name: &str| crate::codegen::idl_qualified_name(module_path, name);

        for def in definitions {
            match def {
                Definition::Module(m) => {
                    push_fmt(
                        output,
                        format_args!(
                            "{indent}#[allow(non_snake_case, clippy::module_inception)]\n\
                             {indent}pub mod {name} {{\n",
                            name = m.name
                        ),
                    );
                    push_fmt(output, format_args!("{indent}    use super::*;\n\n"));
                    // Recurse into nested module
                    let mut nested_path: Vec<&str> = module_path.to_vec();
                    nested_path.push(&m.name);
                    let nested_indent = format!("{indent}    ");
                    self.generate_definitions(output, &m.definitions, &nested_path, &nested_indent);
                    push_fmt(output, format_args!("{indent}}}\n\n"));
                }
                Definition::Struct(s) => {
                    let mut code = self.generate_struct_with_module(s, module_name.as_deref());
                    code.push_str(&key_hash::with_index(|idx| {
                        type_object::emit_struct(idx, s, &fqn(&s.name))
                    }));
                    push_indented(output, indent, &code);
                }
                Definition::Enum(e) => {
                    let mut code = self.generate_enum(e);
                    code.push_str(&type_object::emit_enum(e, &fqn(&e.name)));
                    push_indented(output, indent, &code);
                }
                Definition::Typedef(t) => {
                    let mut code = self.generate_typedef(t);
                    code.push_str(&key_hash::with_index(|idx| {
                        type_object::emit_alias(idx, t, &fqn(&t.name))
                    }));
                    push_indented(output, indent, &code);
                }
                Definition::Union(u) => {
                    let mut code = self.generate_union(u);
                    code.push_str(&key_hash::with_index(|idx| {
                        type_object::emit_union(idx, u, &fqn(&u.name))
                    }));
                    push_indented(output, indent, &code);
                }
                Definition::Bitset(b) => {
                    let code = self.generate_bitset(b);
                    push_indented(output, indent, &code);
                }
                Definition::Const(c) => {
                    let ty = match &c.const_type {
                        IdlType::Primitive(PrimitiveType::String | PrimitiveType::WString)
                        | IdlType::BoundedString { .. } => "&str".to_string(),
                        other => Self::type_to_rust(other),
                    };
                    let value = crate::codegen::const_literal::literal(
                        c,
                        crate::codegen::const_literal::Lang::Rust,
                    );
                    push_fmt(
                        output,
                        format_args!("{indent}pub const {}: {ty} = {value};\n\n", c.name),
                    );
                }
                Definition::Bitmask(bm) => {
                    let mut code = self.generate_bitmask(bm);
                    code.push_str(&type_object::emit_bitmask(bm, &fqn(&bm.name)));
                    push_indented(output, indent, &code);
                }
                _ => {}
            }
        }
    }
}

/// Appends `code` to `output`, every line indented by `indent`.
fn push_indented(output: &mut String, indent: &str, code: &str) {
    if indent.is_empty() {
        output.push_str(code);
    } else {
        push_fmt(
            output,
            format_args!("{indent}{}", code.replace('\n', &format!("\n{indent}"))),
        );
    }
}
