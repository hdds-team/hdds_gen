/// `has_key`, `write_key_holder` and `encode_key` of the `DDS` impl of `s`.
pub(super) fn emit_dds_key_methods(s: &Struct) -> String {
    let mut out = String::new();
    let keyed = with_index(|idx| idx.is_keyed(s));
    out.push_str("\n        /// Returns true if this type has @key fields\n");
    let _ = writeln!(out, "        fn has_key() -> bool {{ {keyed} }}");
    if !keyed {
        return out;
    }
    let kh = match with_index(|idx| idx.key_holder(s)) {
        Ok(Some(kh)) => kh,
        Ok(None) => return out,
        Err(reason) => {
            let reason = reason.replace(['\n', '\r'], " ");
            out.push_str(
                "\n        // No KeyHolder generated: the key of this type is not covered by\n",
            );
            let _ = writeln!(out, "        // hddsgen's KeyHash model ({reason}).");
            out.push_str(
                "        // The runtime gives every sample the all-zero KeyHash and warns once.\n",
            );
            return out;
        }
    };
    let max = kh.max_size().map_or_else(
        || "::hdds::core::key_hash::KeyMaxSize::Unbounded".to_string(),
        |n| format!("::hdds::core::key_hash::KeyMaxSize::Bounded({n})"),
    );
    let mut hash = Emit::new();
    hash_struct(&mut hash, 3, &kh, "self");
    let mut payload = Emit::new();
    payload_struct(&mut payload, 3, &kh, "self", None);

    out.push_str(
        "\n        /// `encode_key` and `key_hash_of_key_payload` travel together:\n        \
         /// the key-only payload one writes is the one the other reads back.\n",
    );
    out.push_str("        fn keys_round_trip() -> bool { true }\n");

    out.push_str(
        "\n        /// The KeyHolder of this sample (RTPS 2.5 9.6.4.8): the key members in\n        \
         /// member-id order, and the `KeyHolder`'s maximum serialized size, which\n        \
         /// selects the padded or the MD5 form of the `KeyHash`.\n",
    );
    out.push_str("        #[allow(clippy::all, clippy::pedantic)]\n");
    out.push_str(
        "        fn write_key_holder(\n            &self,\n            w: &mut ::hdds::core::key_hash::KeyHolderWriter,\n        ) -> ::core::option::Option<::hdds::core::key_hash::KeyMaxSize> {\n",
    );
    out.push_str(&hash.out);
    let _ = writeln!(out, "            ::core::option::Option::Some({max})");
    out.push_str("        }\n");

    out.push_str(
        "\n        /// The key-only payload of a dispose or unregister (RTPS 2.5 9.4.5.3,\n        \
         /// K=1): the key members in declaration order, little endian, at the\n        \
         /// writer's version, framed as this type's data is announced.\n",
    );
    out.push_str("        #[allow(clippy::all, clippy::pedantic)]\n");
    out.push_str(
        "        fn encode_key(&self, version: ::hdds::CdrVersion) -> ::std::vec::Vec<u8> {\n",
    );
    let _ = writeln!(
        out,
        "            let mut k = {PAYLOAD_MOD}::W::new(version);"
    );
    out.push_str("            let k = &mut k;\n");
    out.push_str(&payload.out);
    out.push_str("            ::std::mem::take(&mut k.buf)\n");
    out.push_str("        }\n");

    let mut e = Emit::new();
    let mut decls = String::new();
    let root = alloc_slot(&mut e, &mut decls, &KhNode::Struct(kh.clone()));
    emit_read_struct(&mut e, 3, &kh, &root, None);
    let reads = std::mem::take(&mut e.out);
    hash_slot(&mut e, 3, &root);
    let hashes = std::mem::take(&mut e.out);

    out.push_str(
        "\n        /// The instance a key-only payload names: its key members read\n        \
         /// back from what `encode_key` writes (any CDR version, either byte\n        \
         /// order), then hashed as `write_key_holder` hashes a sample's.\n",
    );
    out.push_str(
        "        #[allow(unused_assignments, unused_mut, clippy::all, clippy::pedantic)]\n",
    );
    out.push_str(
        "        fn key_hash_of_key_payload(payload: &[u8]) -> ::core::option::Option<[u8; 16]> {\n",
    );
    out.push_str(
        "            let mut r = ::hdds::core::key_hash::KeyPayloadReader::new(payload)?;\n",
    );
    out.push_str(&decls);
    out.push_str(&reads);
    // Nothing but the sample's 4-byte padding may follow the key: a payload
    // carrying anything else is not the one `encode_key` writes.
    out.push_str("            r.finish()?;\n");
    out.push_str("            let mut w = ::hdds::core::key_hash::KeyHolderWriter::new();\n");
    out.push_str(&hashes);
    let _ = writeln!(
        out,
        "            ::core::option::Option::Some(w.finish({max}))"
    );
    out.push_str("        }\n");
    out
}

#[cfg(test)]
mod tests {
    #![allow(clippy::expect_used)]

    use crate::codegen::CodeGenerator;
    use crate::parser::Parser;

    fn gen(idl: &str) -> String {
        let mut p = Parser::try_new(idl).expect("lexer");
        let ast = p.parse().expect("parse");
        super::RustGenerator::new().generate(&ast).expect("codegen")
    }

    #[test]
    fn spec_example_3_writes_in_member_id_order_with_maximum_21() {
        let out = gen(
            "@mutable struct Nested { @key long m_long; long u; long w; };
             @mutable struct Foo { @id(40) @key string<12> label; @id(30) @key Nested m_nested;
                                   @id(20) long x; @id(10) long y; };",
        );
        let hook = out
            .split("impl ::hdds::api::DDS for Foo")
            .nth(1)
            .expect("Foo impl");
        let nested = hook
            .find("w.write_i32(self.m_nested.m_long);")
            .expect("nested key");
        let label = hook.find("w.write_string(&self.label);").expect("label");
        assert!(nested < label, "member-id order: {hook}");
        assert!(hook.contains("KeyMaxSize::Bounded(21)"), "{hook}");
        assert!(!hook.contains("w.write_i32(self.m_nested.u)"), "{hook}");
        assert!(!out.contains("FNV-1a hash of @key"), "no FNV KeyHash left");
        assert!(out.contains("pub mod __hdds_key_payload"));
    }

    #[test]
    fn a_keyless_type_keeps_the_trait_defaults() {
        let out = gen("struct P { long x; };");
        assert!(out.contains("fn has_key() -> bool { false }"));
        assert!(!out.contains("fn write_key_holder"));
        assert!(!out.contains("fn encode_key"));
        assert!(!out.contains("__hdds_key_payload"));
    }

    #[test]
    fn an_uncovered_key_says_why_and_emits_no_hook() {
        let out = gen("struct S { @key sequence<string> names; long x; };");
        assert!(out.contains("fn has_key() -> bool { true }"));
        assert!(out.contains("No KeyHolder generated"), "{out}");
        assert!(!out.contains("fn write_key_holder"));
    }

    #[test]
    fn unbounded_and_padded_forms_follow_the_type() {
        let unbounded = gen("struct S { @key string l; };");
        assert!(unbounded.contains("KeyMaxSize::Unbounded"));
        let padded = gen("struct S { @key string<11> l; };");
        assert!(padded.contains("KeyMaxSize::Bounded(16)"));
    }

    #[test]
    fn a_keyed_type_reads_its_key_payload_back() {
        let out = gen("struct S { @key long id; long x; };");
        let hook = out
            .split("fn key_hash_of_key_payload")
            .nth(1)
            .expect("the payload hook");
        assert!(hook.contains("KeyPayloadReader::new(payload)?"), "{hook}");
        assert!(hook.contains("r.read_i32()?"), "{hook}");
        assert!(hook.contains("KeyHolderWriter::new()"), "{hook}");
        assert!(hook.contains("w.write_i32(__k0);"), "{hook}");
    }

    /// The reader refuses what its writer never writes: bytes left after the
    /// key. `KeyPayloadReader::finish` allows the sample's at most three
    /// padding zeroes and nothing else, and it must run once every key member
    /// is read -- before the hash is produced, so an over-long payload names
    /// no instance at all.
    #[test]
    fn a_keyed_type_refuses_a_payload_that_does_not_end_after_its_key() {
        let out = gen("struct S { @key long id; long x; };");
        let hook = out
            .split("fn key_hash_of_key_payload")
            .nth(1)
            .expect("the payload hook");
        let read = hook.find("r.read_i32()?").expect("the key read");
        let finish = hook.find("r.finish()?").expect("the end of the payload");
        let hash = hook.find("w.finish(").expect("the hash");
        assert!(read < finish, "after the key members: {hook}");
        assert!(finish < hash, "before the hash is produced: {hook}");
    }

    #[test]
    fn a_keyless_type_reads_no_key_payload() {
        let out = gen("struct P { long x; };");
        assert!(!out.contains("key_hash_of_key_payload"));
        assert!(!out.contains("KeyPayloadReader"));
    }

    #[test]
    fn the_read_follows_declaration_order_and_the_hash_member_id_order() {
        // `@id` puts `a` after `b` in the KeyHash, never in the payload.
        let out = gen("@mutable struct S { @id(2) @key long a; @id(1) @key long b; };");
        let hook = out
            .split("fn key_hash_of_key_payload")
            .nth(1)
            .expect("the payload hook");
        let read_a = hook.find("__k0 = r.read_i32()?").expect("read a");
        let read_b = hook.find("__k1 = r.read_i32()?").expect("read b");
        let hash_a = hook.find("w.write_i32(__k0);").expect("hash a");
        let hash_b = hook.find("w.write_i32(__k1);").expect("hash b");
        assert!(read_a < read_b, "declaration order in the payload: {hook}");
        assert!(hash_b < hash_a, "member-id order in the KeyHash: {hook}");
    }

    #[test]
    fn a_mutable_key_reads_the_framing_it_writes() {
        let out = gen("@mutable struct S { @key long id; @key string s; };");
        let hook = out
            .split("fn key_hash_of_key_payload")
            .nth(1)
            .expect("the payload hook");
        assert!(hook.contains("if r.is_xcdr2() {"), "{hook}");
        assert!(hook.contains("r.read_emheader()?"), "{hook}");
        assert!(hook.contains("r.read_parameter()?"), "{hook}");
        assert!(hook.contains("r.close_member("), "{hook}");
        assert!(hook.contains("r.leave("), "{hook}");
    }

    #[test]
    fn an_uncovered_key_reads_no_key_payload() {
        let out = gen("struct S { @key sequence<string> names; long x; };");
        assert!(!out.contains("key_hash_of_key_payload"));
    }

    #[test]
    fn a_key_discriminator_writes_the_discriminator_alone() {
        let out = gen("enum K { A, B };
             union C switch (@key K) { case A: long a; case B: double b; };
             struct S { @key C c; };");
        let method = out
            .split("fn __hdds_write_key_holder")
            .nth(1)
            .expect("union method");
        let method = method
            .split("fn __hdds_encode_key_payload")
            .next()
            .unwrap_or("");
        assert!(method.contains("Self::A(_) =>"), "{method}");
        assert!(!method.contains("w.write_f64"), "{method}");
    }
}
