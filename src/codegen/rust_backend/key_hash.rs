//! Instance key hooks of the generated `DDS` impl.
//!
//! A keyed type gets, in its `impl ::hdds::api::DDS`:
//!
//! - `has_key() -> true`;
//! - `write_key_holder`, which writes the `KeyHolder` members in member-id
//!   order through `::hdds::core::key_hash::KeyHolderWriter` and returns the
//!   `KeyHolder`'s maximum serialized size computed here, at generation time.
//!   The runtime's default `compute_key` turns that into the `KeyHash` of
//!   DDSI-RTPS 2.5 9.6.4.8 (padded when the maximum is at most 16, MD5
//!   otherwise);
//! - `encode_key`, the key-only payload of a dispose or unregister: the
//!   `KeyHolder` (key members only, declaration order) little endian at the
//!   writer's version, framed by the extensibility the type's `TypeObject`
//!   announces (which selects the encapsulation identifier of the DATA):
//!   no header for a FINAL type, DHEADER plus `EMHEADER1` (and NEXTINT) per
//!   member for a MUTABLE type under XCDR2, a parameter list closed by
//!   `PID_SENTINEL` under XCDR1 (`XTypes` 1.3 7.4.3.5.3 rules 17, 21-25);
//! - `key_hash_of_key_payload`, the inverse of `encode_key`: it reads the
//!   key members back from a key-only payload (either byte order, any CDR
//!   version) and hashes them exactly as `write_key_holder` hashes a
//!   sample's. Without it a `DataReader` cannot name the instance a protected
//!   dispose points at.
//!
//! A keyed type whose key the `KeyHolder` model does not cover gets
//! `has_key() -> true` and neither hook: the runtime then gives every sample
//! the all-zero `KeyHash` and logs it once, and the generated code says why.

