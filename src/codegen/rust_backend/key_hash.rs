thread_local! {
    /// Type index of the file being generated, for `KeyHolder` resolution.
    // @audit-ok: thread_local! RefCell is inherently thread-safe (one instance per thread)
    static INDEX: RefCell<TypeIndex> = RefCell::new(TypeIndex::default());
}

/// Install the type index of the file about to be generated.
pub(super) fn set_index(index: TypeIndex) {
    INDEX.with(|cell| *cell.borrow_mut() = index);
}

pub(super) fn with_index<R>(f: impl FnOnce(&TypeIndex) -> R) -> R {
    INDEX.with(|cell| f(&cell.borrow()))
}

/// Name of the generated module holding the key-only payload writer.
const PAYLOAD_MOD: &str = "__hdds_key_payload";

/// The key-only payload writer, emitted once at the top of a generated file
/// that has a keyed type. Nested IDL modules reach it through their
/// `use super::*`.
pub(super) fn payload_writer_module() -> String {
    format!(
        r"/// Writer of the key-only payload `encode_key` returns (generated by
/// hddsgen). Little endian, alignment relative to the payload start (XCDR2
/// caps it at 4, XCDR1 at 8), zero padding.
#[doc(hidden)]
#[allow(dead_code, clippy::all, clippy::pedantic)]
pub mod {m} {{
    pub struct W {{
        pub buf: ::std::vec::Vec<u8>,
        pub xcdr2: bool,
        origin: usize,
        max_align: usize,
    }}

    impl W {{
        pub fn new(version: ::hdds::CdrVersion) -> Self {{
            let xcdr2 = matches!(version, ::hdds::CdrVersion::Xcdr2);
            Self {{
                buf: ::std::vec::Vec::new(),
                xcdr2,
                origin: 0,
                max_align: if xcdr2 {{ 4 }} else {{ 8 }},
            }}
        }}

        pub fn align(&mut self, size: usize) {{
            let a = size.min(self.max_align);
            if a > 1 {{
                while (self.buf.len() - self.origin) % a != 0 {{
                    self.buf.push(0);
                }}
            }}
        }}

        /// A primitive: aligned to its size, then its bytes.
        pub fn put(&mut self, bytes: &[u8]) {{
            self.align(bytes.len());
            self.buf.extend_from_slice(bytes);
        }}

        /// Bytes with no alignment.
        pub fn raw(&mut self, bytes: &[u8]) {{
            self.buf.extend_from_slice(bytes);
        }}

        pub fn len_u32(&mut self, n: usize) {{
            self.put(&u32::try_from(n).unwrap_or(u32::MAX).to_le_bytes());
        }}

        /// `string`: length counting the NUL, the bytes, the NUL.
        pub fn string(&mut self, s: &str) {{
            self.len_u32(s.len().saturating_add(1));
            self.raw(s.as_bytes());
            self.raw(&[0]);
        }}

        /// `wstring`: length in bytes, UTF-16 code units, no NUL.
        pub fn wstring(&mut self, s: &str) {{
            self.len_u32(s.encode_utf16().count().saturating_mul(2));
            for unit in s.encode_utf16() {{
                self.raw(&unit.to_le_bytes());
            }}
        }}

        /// Reserve a length word (DHEADER or NEXTINT), aligned at 4.
        pub fn reserve_len(&mut self) -> usize {{
            self.align(4);
            let at = self.buf.len();
            self.raw(&[0; 4]);
            at
        }}

        /// Fill a reserved length word with the bytes written after it.
        pub fn patch_len(&mut self, at: usize) {{
            let n = u32::try_from(self.buf.len() - at - 4).unwrap_or(u32::MAX);
            self.buf[at..at + 4].copy_from_slice(&n.to_le_bytes());
        }}

        /// XCDR2 `EMHEADER1` (`XTypes` 1.3 7.4.3.4.8).
        pub fn emheader(&mut self, id: u32, must_understand: bool, lc: u32) {{
            let word = (u32::from(must_understand) << 31) | (lc << 28) | (id & 0x0fff_ffff);
            self.put(&word.to_le_bytes());
        }}

        /// XCDR1 parameter header, long form (XTypes 1.3 7.4.3.5.3 rule 25,
        /// 7.4.1.2.2): PID_EXTENDED with its must-understand flag, always
        /// 0x7F01; the member's own must-understand flag goes in the 32-bit
        /// member header (FLAG_2, 0x4000_0000), never in the 16-bit PID.
        /// The member is aligned from its first byte.
        pub fn pl1_begin(&mut self, id: u32, must_understand: bool) -> (usize, usize) {{
            self.align(4);
            self.raw(&0x7f01u16.to_le_bytes());
            self.raw(&8u16.to_le_bytes());
            let header = (u32::from(must_understand) << 30) | (id & 0x0fff_ffff);
            self.raw(&header.to_le_bytes());
            let at = self.buf.len();
            self.raw(&[0; 4]);
            let previous = self.origin;
            self.origin = self.buf.len();
            (at, previous)
        }}

        pub fn pl1_end(&mut self, header: (usize, usize)) {{
            let (at, previous) = header;
            self.origin = previous;
            self.patch_len(at);
        }}

        /// PID_LIST_END with its must-understand flag (0x7F02, XTypes 1.3
        /// Table 34), closing an XCDR1 parameter list, as Cyclone DDS writes it.
        pub fn pl1_sentinel(&mut self) {{
            self.align(4);
            self.raw(&0x7f02u16.to_le_bytes());
            self.raw(&0u16.to_le_bytes());
        }}
    }}
}}

",
        m = PAYLOAD_MOD
    )
}

/// Whether the generated file needs the payload writer: some structure has
/// a `KeyHolder` the model covers, or some union gets the hidden methods of
/// [`emit_union_key_methods`], which name the writer whether or not a keyed
/// type reaches them.
pub(super) fn file_needs_payload_writer(ast: &crate::ast::IdlFile) -> bool {
    fn walk(defs: &[crate::ast::Definition], idx: &TypeIndex) -> bool {
        defs.iter().any(|d| match d {
            crate::ast::Definition::Struct(s) => matches!(idx.key_holder(s), Ok(Some(_))),
            crate::ast::Definition::Union(u) => idx.union_key_holder(u).is_ok(),
            crate::ast::Definition::Module(m) => walk(&m.definitions, idx),
            _ => false,
        })
    }
    with_index(|idx| walk(&ast.definitions, idx))
}

/// Rust integer type of a `KeyHolder` primitive (the cast target).
const fn rust_int(p: KhPrim) -> &'static str {
    match p {
        KhPrim::Bool => "bool",
        KhPrim::Octet | KhPrim::Char => "u8",
        KhPrim::I8 => "i8",
        KhPrim::I16 => "i16",
        KhPrim::U16 | KhPrim::WChar => "u16",
        KhPrim::I32 => "i32",
        KhPrim::U32 => "u32",
        KhPrim::I64 => "i64",
        KhPrim::U64 => "u64",
        KhPrim::F32 => "f32",
        KhPrim::F64 => "f64",
    }
}

/// `KeyHolderWriter` method of a `KeyHolder` primitive.
const fn writer_method(p: KhPrim) -> &'static str {
    match p {
        KhPrim::Bool => "write_bool",
        KhPrim::Octet | KhPrim::Char => "write_u8",
        KhPrim::I8 => "write_i8",
        KhPrim::I16 => "write_i16",
        KhPrim::U16 | KhPrim::WChar => "write_u16",
        KhPrim::I32 => "write_i32",
        KhPrim::U32 => "write_u32",
        KhPrim::I64 => "write_i64",
        KhPrim::U64 => "write_u64",
        KhPrim::F32 => "write_f32",
        KhPrim::F64 => "write_f64",
    }
}

/// The value of a scalar at `place`, converted to the primitive's Rust type,
/// with no enclosing parentheses (a cast is parenthesized by the caller that
/// needs it, so that the generated code has no `unused_parens`).
fn scalar_value(s: &KhScalar, place: &str) -> String {
    let p = s.prim();
    // `(*__u)` is a place for member access; as a whole value, `*__u`.
    let place = place
        .strip_prefix("(*")
        .and_then(|rest| rest.strip_suffix(')'))
        .filter(|inner| !inner.contains(['(', ')']))
        .map_or_else(|| place.to_string(), |inner| format!("*{inner}"));
    match s {
        KhScalar::Prim(KhPrim::Char) => format!("{place} as u8"),
        KhScalar::Prim(KhPrim::WChar) => format!("{place} as u32 as u16"),
        KhScalar::Prim(_) => place,
        KhScalar::Enum { .. } | KhScalar::Bitmask { .. } => {
            format!("{place} as {}", rust_int(p))
        }
    }
}

/// Place expression of a `KeyHolder` member, from the place of its parent.
/// `boxed_external`: an `@external` member is a `Box` (Rust backend) to
/// dereference, rather than a plain field (micro backend).
fn member_place(
    parent: &str,
    m: &super::super::key_holder::KhMember,
    boxed_external: bool,
) -> String {
    let mut place = parent.to_string();
    for _ in 0..m.base_depth {
        place.push_str(".base");
    }
    let ident = rust_ident(&m.field.name);
    if boxed_external && m.field.is_external() {
        format!("(*{place}.{ident})")
    } else {
        format!("{place}.{ident}")
    }
}

/// Emitter state: indentation and a counter for unique binding names.
struct Emit {
    out: String,
    next_var: usize,
    /// See [`member_place`].
    boxed_external: bool,
}

impl Emit {
    /// An emitter for the Rust backend's types.
    const fn new() -> Self {
        Self::with_external(true)
    }

    const fn with_external(boxed_external: bool) -> Self {
        Self {
            out: String::new(),
            next_var: 0,
            boxed_external,
        }
    }

    fn var(&mut self, prefix: &str) -> String {
        let v = format!("__{prefix}{}", self.next_var);
        self.next_var += 1;
        v
    }

    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }
}

// ---------------------------------------------------------------------------
// KeyHash: KeyHolderWriter calls, member-id order.
// ---------------------------------------------------------------------------

fn hash_scalar(e: &mut Emit, ind: usize, s: &KhScalar, place: &str) {
    let call = format!("w.{}({});", writer_method(s.prim()), scalar_value(s, place));
    e.line(ind, &call);
}

fn hash_node(e: &mut Emit, ind: usize, node: &KhNode, place: &str) {
    match node {
        KhNode::Scalar(s) => hash_scalar(e, ind, s, place),
        KhNode::String { .. } => e.line(ind, &format!("w.write_string(&{place});")),
        KhNode::WString { .. } => e.line(ind, &format!("w.write_wstring(&{place}[..]);")),
        KhNode::Sequence { elem, .. } => {
            e.line(
                ind,
                &format!("w.write_u32(u32::try_from({place}.len()).unwrap_or(u32::MAX));"),
            );
            if elem.prim() == KhPrim::Octet {
                e.line(ind, &format!("w.write_octets(&{place});"));
            } else {
                let v = e.var("e");
                e.line(ind, &format!("for {v} in {place}.iter() {{"));
                hash_scalar(e, ind + 1, elem, &format!("(*{v})"));
                e.line(ind, "}");
            }
        }
        KhNode::Array { elem, dims } => {
            if dims.len() == 1 && elem.prim() == KhPrim::Octet {
                e.line(ind, &format!("w.write_octets(&{place});"));
                return;
            }
            let mut cur = place.to_string();
            let mut depth = ind;
            for _ in dims {
                let v = e.var("e");
                e.line(depth, &format!("for {v} in {cur}.iter() {{"));
                cur = format!("(*{v})");
                depth += 1;
            }
            hash_scalar(e, depth, elem, &cur);
            for _ in dims {
                depth -= 1;
                e.line(depth, "}");
            }
        }
        KhNode::Struct(s) => hash_struct(e, ind, s, place),
        KhNode::Union(_) => e.line(ind, &format!("{place}.__hdds_write_key_holder(w);")),
    }
}

fn hash_struct(e: &mut Emit, ind: usize, s: &KhStruct, place: &str) {
    for m in s.hash_order() {
        let p = member_place(place, m, e.boxed_external);
        hash_node(e, ind, &m.node, &p);
    }
}

// ---------------------------------------------------------------------------
// encode_key: the key-only payload, declaration order, wire framing.
// ---------------------------------------------------------------------------

fn payload_scalar(e: &mut Emit, ind: usize, s: &KhScalar, place: &str) {
    let value = scalar_value(s, place);
    let line = match s.prim() {
        KhPrim::Bool => format!("k.put(&[u8::from({value})]);"),
        _ if value.contains(" as ") || value.starts_with('*') => {
            format!("k.put(&({value}).to_le_bytes());")
        }
        _ => format!("k.put(&{value}.to_le_bytes());"),
    };
    e.line(ind, &line);
}

fn payload_node(e: &mut Emit, ind: usize, node: &KhNode, place: &str, v2: Option<bool>) {
    match node {
        KhNode::Scalar(s) => payload_scalar(e, ind, s, place),
        KhNode::String { .. } => e.line(ind, &format!("k.string(&{place});")),
        KhNode::WString { .. } => e.line(ind, &format!("k.wstring(&{place});")),
        KhNode::Sequence { elem, .. } => {
            e.line(ind, &format!("k.len_u32({place}.len());"));
            if elem.prim() == KhPrim::Octet {
                e.line(ind, &format!("k.raw(&{place});"));
            } else {
                let v = e.var("e");
                e.line(ind, &format!("for {v} in {place}.iter() {{"));
                payload_scalar(e, ind + 1, elem, &format!("(*{v})"));
                e.line(ind, "}");
            }
        }
        KhNode::Array { elem, dims } => {
            let mut cur = place.to_string();
            let mut depth = ind;
            for _ in dims {
                let v = e.var("e");
                e.line(depth, &format!("for {v} in {cur}.iter() {{"));
                cur = format!("(*{v})");
                depth += 1;
            }
            payload_scalar(e, depth, elem, &cur);
            for _ in dims {
                depth -= 1;
                e.line(depth, "}");
            }
        }
        KhNode::Struct(s) => payload_struct(e, ind, s, place, v2),
        KhNode::Union(_) => e.line(ind, &format!("{place}.__hdds_encode_key_payload(k);")),
    }
}

/// The key-only payload of a `KeyHolder` struct at `place`. `v2` is the
/// version when the enclosing code already branched on it.
fn payload_struct(e: &mut Emit, ind: usize, s: &KhStruct, place: &str, v2: Option<bool>) {
    // The extensibility the TypeObject announces, which selects the
    // encapsulation identifier of the writer's DATA (`XTypes` 1.3
    // 7.4.3.5.3: FINAL rule 17, APPENDABLE rules 29-30, MUTABLE 21-25).
    let ext = with_index(|idx| {
        idx.struct_def(&format!("::{}", s.global))
            .map_or(data_model::Ext::Final, data_model::struct_ext)
    });
    match ext {
        data_model::Ext::Final => {
            for m in &s.members {
                let p = member_place(place, m, true);
                payload_node(e, ind, &m.node, &p, v2);
            }
            return;
        }
        data_model::Ext::Appendable => {
            match v2 {
                Some(true) => appendable_v2(e, ind, s, place),
                Some(false) => {
                    for m in &s.members {
                        let p = member_place(place, m, true);
                        payload_node(e, ind, &m.node, &p, Some(false));
                    }
                }
                None => {
                    e.line(ind, "if k.xcdr2 {");
                    appendable_v2(e, ind + 1, s, place);
                    e.line(ind, "} else {");
                    for m in &s.members {
                        let p = member_place(place, m, true);
                        payload_node(e, ind + 1, &m.node, &p, Some(false));
                    }
                    e.line(ind, "}");
                }
            }
            return;
        }
        data_model::Ext::Mutable => {}
    }
    let members: Vec<(u32, bool, u32, String, &KhNode)> = s
        .members
        .iter()
        .map(|m| {
            let lc = with_index(|idx| data_model::length_code(idx, &m.field.field_type));
            let mu = data_model::must_understand(&m.field);
            (m.member_id, mu, lc, member_place(place, m, true), &m.node)
        })
        .collect();
    match v2 {
        Some(true) => mutable_v2(e, ind, &members),
        Some(false) => mutable_v1(e, ind, &members),
        None => {
            e.line(ind, "if k.xcdr2 {");
            mutable_v2(e, ind + 1, &members);
            e.line(ind, "} else {");
            mutable_v1(e, ind + 1, &members);
            e.line(ind, "}");
        }
    }
}

/// An APPENDABLE struct under XCDR2: DHEADER, then the members (rule 30).
fn appendable_v2(e: &mut Emit, ind: usize, s: &KhStruct, place: &str) {
    let d = e.var("d");
    e.line(ind, &format!("let {d} = k.reserve_len();"));
    for m in &s.members {
        let p = member_place(place, m, true);
        payload_node(e, ind, &m.node, &p, Some(true));
    }
    e.line(ind, &format!("k.patch_len({d});"));
}

/// A MUTABLE struct under XCDR2: DHEADER, then `EMHEADER1` per member with
/// the length code the data path uses (rules 21-22).
fn mutable_v2(e: &mut Emit, ind: usize, members: &[(u32, bool, u32, String, &KhNode)]) {
    let d = e.var("d");
    e.line(ind, &format!("let {d} = k.reserve_len();"));
    for (id, mu, lc, p, node) in members {
        e.line(ind, &format!("k.emheader({id:#010x}, {mu}, {lc});"));
        if *lc == 4 {
            let n = e.var("n");
            e.line(ind, &format!("let {n} = k.reserve_len();"));
            payload_node(e, ind, node, p, Some(true));
            e.line(ind, &format!("k.patch_len({n});"));
        } else {
            // LC 0-3: the value alone; LC 5-7: the value's own leading
            // length word is the NEXTINT.
            payload_node(e, ind, node, p, Some(true));
        }
    }
    e.line(ind, &format!("k.patch_len({d});"));
}

/// A MUTABLE struct under XCDR1: a parameter list closed by `PID_SENTINEL`
/// (`XTypes` 1.3 7.4.3.5.3 rules 23 and 25).
fn mutable_v1(e: &mut Emit, ind: usize, members: &[(u32, bool, u32, String, &KhNode)]) {
    for (id, mu, _, p, node) in members {
        let h = e.var("h");
        e.line(ind, &format!("let {h} = k.pl1_begin({id:#010x}, {mu});"));
        payload_node(e, ind, node, p, Some(false));
        e.line(ind, &format!("k.pl1_end({h});"));
    }
    e.line(ind, "k.pl1_sentinel();");
}

