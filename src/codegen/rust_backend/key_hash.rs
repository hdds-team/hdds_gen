/// `KeyHolderWriter` call writing a union discriminator whose Rust value
/// is `expr`.
/// The Rust expression of the discriminator value of case `case_index`
/// of `u`, the value its `encode` writes (`data_model::union_case_disc`: the
/// label's value, whatever its form, or the smallest free value for the
/// `default` case), as an `i64` literal the key-hash writes cast to the
/// holder type. Shared with the micro backend.
pub fn union_disc_literal(idx: &TypeIndex, u: &Union, case_index: usize) -> String {
    data_model::union_case_disc(idx, u, case_index).map_or_else(
        || {
            format!(
                "compile_error!(\"hddsgen: the label of case `{}` of `{}` is not a value hddsgen can compute\")",
                u.cases[case_index].field.name, u.name
            )
        },
        |v| format!("({v}i64)"),
    )
}

fn union_disc_hash(kh: &KhUnion, expr: &str) -> String {
    let p = kh.disc.prim();
    let value = match p {
        KhPrim::Bool => format!("{expr} as u8 != 0"),
        _ => format!("{expr} as {}", rust_int(p)),
    };
    format!("w.{}({value});", writer_method(p))
}

fn union_disc_payload(kh: &KhUnion, expr: &str) -> String {
    match kh.disc.prim() {
        KhPrim::Bool => format!("k.put(&[({expr} as u8) & 1]);"),
        p => format!("k.put(&({expr} as {}).to_le_bytes());", rust_int(p)),
    }
}

/// The `KeyHolder` writes of `kh` read from `place`, one statement per line
/// at `indent` levels of four spaces, through a writer bound to `w` with the
/// `KeyHolderWriter` method names; `boxed_external` as in [`member_place`].
/// Shared with the micro backend.
pub fn key_holder_writes(
    kh: &KhStruct,
    place: &str,
    indent: usize,
    boxed_external: bool,
) -> String {
    let mut e = Emit::with_external(boxed_external);
    hash_struct(&mut e, indent, kh, place);
    e.out
}

/// The hidden `__hdds_write_key_holder` method of a union, in its own
/// `impl` block. `writer` is the path of the writer type; `variant` names
/// the Rust variant of a case (field name, case index); `disc` gives the
/// Rust expression of a case's discriminator value (case index). Shared with
/// the micro backend.
pub fn union_key_holder_method(
    union_name: &str,
    kh: &KhUnion,
    writer: &str,
    variant: &dyn Fn(&str, usize) -> String,
    disc: &dyn Fn(usize) -> String,
    boxed_external: bool,
) -> String {
    let mut hash = Emit::with_external(boxed_external);
    hash.line(2, "match self {");
    for case in &kh.cases {
        let name = variant(&case.field.name, case.index);
        let binding = match &case.node {
            Some(_) if !kh.disc_is_key => "__u",
            _ => "_",
        };
        hash.line(3, &format!("Self::{name}({binding}) => {{"));
        hash.line(4, &union_disc_hash(kh, &disc(case.index)));
        if let (Some(node), false) = (&case.node, kh.disc_is_key) {
            hash_node(&mut hash, 4, node, "(*__u)");
        }
        hash.line(3, "}");
    }
    hash.line(2, "}");
    let mut out = String::new();
    let _ = writeln!(out, "impl {union_name} {{");
    out.push_str(
        "    /// This union's part of a KeyHolder (RTPS 2.5 9.6.4.8): the\n    \
         /// discriminator, then the selected member unless the discriminator\n    \
         /// is a key. Generated by hddsgen.\n",
    );
    out.push_str("    #[doc(hidden)]\n");
    out.push_str("    #[allow(unused_variables, clippy::all, clippy::pedantic)]\n");
    let _ = writeln!(
        out,
        "    pub fn __hdds_write_key_holder(&self, w: &mut {writer}) {{"
    );
    out.push_str(&hash.out);
    out.push_str("    }\n}\n\n");
    out
}

/// Hidden inherent methods of a union that a `KeyHolder` may hold; empty when
/// the model does not cover the union.
pub(super) fn emit_union_key_methods(u: &Union) -> String {
    let Ok(kh) = with_index(|idx| idx.union_key_holder(u)) else {
        return String::new();
    };
    let disc = |i: usize| with_index(|idx| union_disc_literal(idx, u, i));
    let mut out = union_key_holder_method(
        &u.name,
        &kh,
        "::hdds::core::key_hash::KeyHolderWriter",
        &RustGenerator::union_variant_name,
        &disc,
        true,
    );
    // The union's own extensibility frames its part of the payload, as it
    // frames the union in a sample (`codec::emit_union_codec`): FINAL as is,
    // APPENDABLE behind a DHEADER under XCDR2 (`XTypes` 1.3 7.4.3.5.3 rules
    // 29-30), MUTABLE as members 0 (the discriminator, must understand) and
    // the case id (rules 27-28).
    let ext = data_model::union_ext(u);
    let mutable = with_index(|idx| {
        (
            data_model::discriminator_length_code(idx, &u.discriminator),
            data_model::union_case_ids(idx, u),
        )
    });
    let mut payload = Emit::new();
    if ext == data_model::Ext::Appendable {
        payload.line(
            2,
            "let __dh = if k.xcdr2 { Some(k.reserve_len()) } else { None };",
        );
    }
    payload.line(2, "match self {");
    for case in &kh.cases {
        let variant = RustGenerator::union_variant_name(&case.field.name, case.index);
        let binding = match &case.node {
            Some(_) if !kh.disc_is_key => "__u",
            _ => "_",
        };
        payload.line(3, &format!("Self::{variant}({binding}) => {{"));
        let disc_put = union_disc_payload(&kh, &disc(case.index));
        let node = match (&case.node, kh.disc_is_key) {
            (Some(node), false) => Some(node),
            _ => None,
        };
        if ext == data_model::Ext::Mutable {
            let (disc_lc, ids) = &mutable;
            let id = ids[case.index];
            let mu = data_model::must_understand(&case.field);
            let lc = with_index(|idx| data_model::length_code(idx, &case.field.field_type));
            payload.line(4, "if k.xcdr2 {");
            payload.line(5, "let __d = k.reserve_len();");
            payload.line(5, &format!("k.emheader(0, true, {disc_lc});"));
            payload.line(5, &disc_put);
            if let Some(node) = node {
                payload.line(5, &format!("k.emheader({id:#010x}, {mu}, {lc});"));
                if lc == 4 {
                    payload.line(5, "let __n = k.reserve_len();");
                    payload_node(&mut payload, 5, node, "(*__u)", Some(true));
                    payload.line(5, "k.patch_len(__n);");
                } else {
                    payload_node(&mut payload, 5, node, "(*__u)", Some(true));
                }
            }
            payload.line(5, "k.patch_len(__d);");
            payload.line(4, "} else {");
            payload.line(5, "let __h = k.pl1_begin(0, true);");
            payload.line(5, &disc_put);
            payload.line(5, "k.pl1_end(__h);");
            if let Some(node) = node {
                payload.line(5, &format!("let __h = k.pl1_begin({id:#010x}, {mu});"));
                payload_node(&mut payload, 5, node, "(*__u)", Some(false));
                payload.line(5, "k.pl1_end(__h);");
            }
            payload.line(5, "k.pl1_sentinel();");
            payload.line(4, "}");
        } else {
            payload.line(4, &disc_put);
            if let Some(node) = node {
                payload_node(&mut payload, 4, node, "(*__u)", None);
            }
        }
        payload.line(3, "}");
    }
    payload.line(2, "}");
    if ext == data_model::Ext::Appendable {
        payload.line(2, "if let Some(__dh) = __dh { k.patch_len(__dh); }");
    }
    let _ = writeln!(out, "impl {} {{", u.name);
    out.push_str("    /// This union's part of a key-only payload. Generated by hddsgen.\n");
    out.push_str("    #[doc(hidden)]\n");
    out.push_str("    #[allow(unused_variables, clippy::all, clippy::pedantic)]\n");
    let _ = writeln!(
        out,
        "    pub fn __hdds_encode_key_payload(&self, k: &mut {PAYLOAD_MOD}::W) {{"
    );
    out.push_str(&payload.out);
    out.push_str("    }\n}\n\n");
    out
}

// ---------------------------------------------------------------------------
// key_hash_of_key_payload: reading a key-only payload back.
//
// The payload lists the key members in DECLARATION order (that is how
// `encode_key` writes them), the KeyHash hashes them in MEMBER-ID order. The
// generated code therefore reads every member into a local variable first,
// then hashes the variables in the other order. A union case only exists on
// one branch of its discriminator, so its variables are declared up front and
// written by the matching branch of the read, then read by the matching
// branch of the hash.
// ---------------------------------------------------------------------------

/// The `KeyPayloadReader` method of a `KeyHolder` primitive.
const fn reader_method(p: KhPrim) -> &'static str {
    match p {
        KhPrim::Bool => "read_bool",
        KhPrim::Octet | KhPrim::Char => "read_u8",
        KhPrim::I8 => "read_i8",
        KhPrim::I16 => "read_i16",
        KhPrim::U16 | KhPrim::WChar => "read_u16",
        KhPrim::I32 => "read_i32",
        KhPrim::U32 => "read_u32",
        KhPrim::I64 => "read_i64",
        KhPrim::U64 => "read_u64",
        KhPrim::F32 => "read_f32",
        KhPrim::F64 => "read_f64",
    }
}

/// A `Option<u32>` bound as a Rust expression.
fn opt_u32(bound: Option<u32>) -> String {
    bound.map_or_else(
        || "::core::option::Option::None".to_string(),
        |n| format!("::core::option::Option::Some({n}u32)"),
    )
}

/// Where a value read from a key-only payload lives, and how to write it
/// into the `KeyHash` afterwards.
enum Slot {
    /// A scalar in one variable, of the primitive's Rust type.
    Scalar {
        /// `KeyHolderWriter` method of the value.
        method: &'static str,
        var: String,
    },
    /// A `String`.
    Text {
        /// The payload holds UTF-16 code units.
        wstring: bool,
        var: String,
    },
    /// A flat `Vec<T>` in declaration order; `len` when the payload and the
    /// `KeyHash` both carry its element count (a sequence, not an array).
    List {
        /// `KeyHolderWriter` method of one element.
        method: &'static str,
        var: String,
        len: bool,
    },
    /// A structure: one slot per `KhStruct::members` entry, and the order
    /// the members are hashed in.
    Struct {
        slots: Vec<Self>,
        /// Indices into `slots`, in ascending member-id order.
        order: Vec<usize>,
    },
    /// A union.
    Union(Box<UnionSlot>),
}

/// A union read back from a key-only payload.
struct UnionSlot {
    /// The discriminator, as read.
    disc_var: String,
    disc: KhScalar,
    cases: Vec<UnionCaseSlot>,
}

/// One case of [`UnionSlot`].
struct UnionCaseSlot {
    /// The discriminator values that select this case.
    patterns: Vec<i64>,
    /// The case's value, `None` for a `void` case and when the
    /// discriminator is a key (the payload holds the discriminator alone).
    value: Option<Slot>,
}

/// A local variable declaration at the top of the generated method.
fn declare(decls: &mut String, text: &str) {
    decls.push_str("            ");
    decls.push_str(text);
    decls.push('\n');
}

/// Allocate the variables of `node`, declaring them all at the top of the
/// generated method.
fn alloc_slot(e: &mut Emit, decls: &mut String, node: &KhNode) -> Slot {
    match node {
        KhNode::Scalar(s) => {
            let var = e.var("k");
            declare(
                decls,
                &format!(
                    "let mut {var}: {} = ::core::default::Default::default();",
                    rust_int(s.prim())
                ),
            );
            Slot::Scalar {
                method: writer_method(s.prim()),
                var,
            }
        }
        KhNode::String { .. } | KhNode::WString { .. } => {
            let var = e.var("k");
            declare(
                decls,
                &format!(
                    "let mut {var}: ::std::string::String = ::core::default::Default::default();"
                ),
            );
            Slot::Text {
                wstring: matches!(node, KhNode::WString { .. }),
                var,
            }
        }
        KhNode::Sequence { elem, .. } | KhNode::Array { elem, .. } => {
            let var = e.var("k");
            declare(
                decls,
                &format!(
                    "let mut {var}: ::std::vec::Vec<{}> = ::core::default::Default::default();",
                    rust_int(elem.prim())
                ),
            );
            Slot::List {
                method: writer_method(elem.prim()),
                var,
                len: matches!(node, KhNode::Sequence { .. }),
            }
        }
        KhNode::Struct(s) => {
            let mut slots = Vec::with_capacity(s.members.len());
            for m in &s.members {
                slots.push(alloc_slot(e, decls, &m.node));
            }
            let mut order: Vec<usize> = (0..s.members.len()).collect();
            order.sort_by_key(|&i| s.members[i].member_id);
            Slot::Struct { slots, order }
        }
        KhNode::Union(kh) => Slot::Union(Box::new(alloc_union(e, decls, kh))),
    }
}

fn alloc_union(e: &mut Emit, decls: &mut String, kh: &KhUnion) -> UnionSlot {
    let disc_var = e.var("kd");
    declare(
        decls,
        &format!(
            "let mut {disc_var}: {} = ::core::default::Default::default();",
            rust_int(kh.disc.prim())
        ),
    );
    let cases = kh
        .cases
        .iter()
        .map(|case| UnionCaseSlot {
            patterns: union_case_patterns(kh, case),
            value: case.node.as_ref().map(|node| alloc_slot(e, decls, node)),
        })
        .collect();
    UnionSlot {
        disc_var,
        disc: kh.disc.clone(),
        cases,
    }
}

/// The discriminator values that select `case` in a key-only payload: every
/// label's value, plus, for the `default` case, the smallest non-negative
/// value no label uses (`data_model::union_case_disc`).
fn union_case_patterns(kh: &KhUnion, case: &super::super::key_holder::KhCase) -> Vec<i64> {
    with_index(|idx| {
        let value_of = |l: &crate::ast::UnionLabel| match l {
            crate::ast::UnionLabel::Value(v) => {
                data_model::union_label_value(idx, &kh.disc_type, v)
            }
            crate::ast::UnionLabel::Default => None,
        };
        let mut values: Vec<i64> = case.labels.iter().filter_map(value_of).collect();
        if values.is_empty() {
            let used: Vec<i64> = kh
                .cases
                .iter()
                .flat_map(|c| c.labels.iter())
                .filter_map(value_of)
                .collect();
            if let Some(v) = (0..=i64::from(u32::MAX)).find(|v| !used.contains(v)) {
                values.push(v);
            }
        }
        values
    })
}

/// Emit the reads of `node` into the variables `slot` names, at `ind`.
/// `v2` is the encoding version when the enclosing code already branched.
fn emit_read(e: &mut Emit, ind: usize, node: &KhNode, slot: &Slot, v2: Option<bool>) {
    match slot {
        Slot::Scalar { var, .. } => {
            let KhNode::Scalar(s) = node else { return };
            let call = format!("{var} = r.{}()?;", reader_method(s.prim()));
            e.line(ind, &call);
        }
        Slot::Text { var, wstring } => {
            let call = match (node, wstring) {
                (KhNode::String { bound }, false) => {
                    format!("r.read_string({})?", opt_u32(*bound))
                }
                (KhNode::WString { bound }, true) => {
                    format!("r.read_wstring({})?", opt_u32(*bound))
                }
                _ => return,
            };
            e.line(ind, &format!("{var} = {call};"));
        }
        Slot::List { var, .. } => match node {
            KhNode::Sequence { elem, bound } => {
                let n = e.var("n");
                e.line(
                    ind,
                    &format!(
                        "let {n} = r.read_len({}, {})?;",
                        opt_u32(*bound),
                        elem.prim().size()
                    ),
                );
                e.line(ind, &format!("{var}.reserve({n});"));
                e.line(
                    ind,
                    &format!(
                        "for _ in 0..{n} {{ {var}.push(r.{}()?); }}",
                        reader_method(elem.prim())
                    ),
                );
            }
            KhNode::Array { elem, dims } => {
                let count: u64 = dims.iter().map(|d| u64::from(*d)).product();
                e.line(
                    ind,
                    &format!(
                        "for _ in 0..{count} {{ {var}.push(r.{}()?); }}",
                        reader_method(elem.prim())
                    ),
                );
            }
            _ => {}
        },
        Slot::Struct { .. } => {
            let KhNode::Struct(s) = node else { return };
            emit_read_struct(e, ind, s, slot, v2);
        }
        Slot::Union(u) => {
            let KhNode::Union(kh) = node else { return };
            emit_read_union(e, ind, kh, u);
        }
    }
}

fn read_members(e: &mut Emit, ind: usize, s: &KhStruct, slots: &[Slot], v2: Option<bool>) {
    for (i, m) in s.members.iter().enumerate() {
        emit_read(e, ind, &m.node, &slots[i], v2);
    }
}

/// The body of a structure that is read in the payload's framing.
fn emit_read_struct(e: &mut Emit, ind: usize, s: &KhStruct, slot: &Slot, v2: Option<bool>) {
    let Slot::Struct { slots, .. } = slot else {
        return;
    };
    let ext = with_index(|idx| {
        idx.struct_def(&format!("::{}", s.global))
            .map_or(data_model::Ext::Final, data_model::struct_ext)
    });
    match ext {
        data_model::Ext::Final => read_members(e, ind, s, slots, v2),
        data_model::Ext::Appendable => match v2 {
            Some(true) => read_appendable_v2(e, ind, s, slots),
            Some(false) => read_members(e, ind, s, slots, Some(false)),
            None => {
                e.line(ind, "if r.is_xcdr2() {");
                read_appendable_v2(e, ind + 1, s, slots);
                e.line(ind, "} else {");
                read_members(e, ind + 1, s, slots, Some(false));
                e.line(ind, "}");
            }
        },
        data_model::Ext::Mutable => match v2 {
            Some(true) => read_mutable_v2(e, ind, s, slots),
            Some(false) => read_mutable_v1(e, ind, s, slots),
            None => {
                e.line(ind, "if r.is_xcdr2() {");
                read_mutable_v2(e, ind + 1, s, slots);
                e.line(ind, "} else {");
                read_mutable_v1(e, ind + 1, s, slots);
                e.line(ind, "}");
            }
        },
    }
}

fn read_appendable_v2(e: &mut Emit, ind: usize, s: &KhStruct, slots: &[Slot]) {
    let end = e.var("e");
    e.line(ind, &format!("let {end} = r.read_dheader()?;"));
    read_members(e, ind, s, slots, Some(true));
    e.line(ind, &format!("r.close({end})?;"));
}

fn read_mutable_v2(e: &mut Emit, ind: usize, s: &KhStruct, slots: &[Slot]) {
    let end = e.var("e");
    let m = e.var("m");
    e.line(ind, &format!("let {end} = r.read_dheader()?;"));
    e.line(ind, &format!("while r.before({end}) {{"));
    e.line(ind + 1, "match r.read_emheader()? {");
    for (i, member) in s.members.iter().enumerate() {
        e.line(ind + 2, &format!("({}u32, {m}) => {{", member.member_id));
        emit_read(e, ind + 3, &member.node, &slots[i], Some(true));
        e.line(ind + 3, &format!("r.close_member({m})?;"));
        e.line(ind + 2, "}");
    }
    e.line(ind + 2, &format!("(_, {m}) => {{ r.close_member({m})?; }}"));
    e.line(ind + 1, "}");
    e.line(ind, "}");
    e.line(ind, &format!("r.close({end})?;"));
}

fn read_mutable_v1(e: &mut Emit, ind: usize, s: &KhStruct, slots: &[Slot]) {
    let id = e.var("i");
    let p = e.var("p");
    e.line(ind, "loop {");
    e.line(
        ind + 1,
        &format!("let ({id}, {p}) = match r.read_parameter()? {{"),
    );
    e.line(
        ind + 2,
        "::core::option::Option::Some(__hdds_member) => __hdds_member,",
    );
    e.line(ind + 2, "::core::option::Option::None => break,");
    e.line(ind + 1, "};");
    e.line(ind + 1, &format!("match {id} {{"));
    for (i, member) in s.members.iter().enumerate() {
        e.line(ind + 2, &format!("{}u32 => {{", member.member_id));
        emit_read(e, ind + 3, &member.node, &slots[i], Some(false));
        e.line(ind + 3, &format!("r.leave({p})?;"));
        e.line(ind + 2, "}");
    }
    e.line(ind + 2, &format!("_ => {{ r.leave({p})?; }}"));
    e.line(ind + 1, "}");
    e.line(ind, "}");
}

/// The read of a union: its discriminator first, then the selected case's
/// value, in the framing its extensibility gives (`XTypes` 1.3 7.4.3.5.3
/// rules 27-30). The case is chosen by the discriminator, so a peer that
/// writes the case member before the discriminator under MUTABLE makes the
/// payload unreadable here: `None`, never a guess.
#[allow(clippy::too_many_lines)]
fn emit_read_union(e: &mut Emit, ind: usize, kh: &KhUnion, u: &UnionSlot) {
    let read_disc = |e: &mut Emit, ind: usize| {
        e.line(
            ind,
            &format!("{} = r.{}()?;", u.disc_var, reader_method(kh.disc.prim())),
        );
    };
    let read_case = |e: &mut Emit, ind: usize| {
        e.line(ind, &format!("match {} as i64 {{", u.disc_var));
        for (case, slot) in kh.cases.iter().zip(&u.cases) {
            let patterns: Vec<String> = slot.patterns.iter().map(|v| format!("{v}i64")).collect();
            e.line(ind + 1, &format!("{} => {{", patterns.join(" | ")));
            if let (Some(node), Some(value)) = (&case.node, &slot.value) {
                emit_read(e, ind + 2, node, value, None);
            }
            e.line(ind + 1, "}");
        }
        e.line(ind + 1, "_ => return ::core::option::Option::None,");
        e.line(ind, "}");
    };
    match kh.ext {
        data_model::Ext::Final => {
            read_disc(e, ind);
            read_case(e, ind);
        }
        data_model::Ext::Appendable => {
            let end = e.var("e");
            e.line(
                ind,
                &format!("let {end} = if r.is_xcdr2() {{ ::core::option::Option::Some(r.read_dheader()?) }} else {{ ::core::option::Option::None }};"),
            );
            read_disc(e, ind);
            read_case(e, ind);
            e.line(
                ind,
                &format!(
                    "if let ::core::option::Option::Some({end}) = {end} {{ r.close({end})?; }}"
                ),
            );
        }
        data_model::Ext::Mutable => {
            e.line(ind, "if r.is_xcdr2() {");
            let end = e.var("e");
            let m = e.var("m");
            let id = e.var("i");
            e.line(ind + 1, &format!("let {end} = r.read_dheader()?;"));
            e.line(ind + 1, &format!("let ({id}, {m}) = r.read_emheader()?;"));
            e.line(
                ind + 1,
                &format!("if {id} != 0 {{ return ::core::option::Option::None; }}"),
            );
            read_disc(e, ind + 1);
            e.line(ind + 1, &format!("r.close_member({m})?;"));
            e.line(ind + 1, &format!("if r.before({end}) {{"));
            e.line(ind + 2, &format!("let ({id}, {m}) = r.read_emheader()?;"));
            e.line(
                ind + 2,
                &format!("if {id} == 0 {{ return ::core::option::Option::None; }}"),
            );
            read_case(e, ind + 2);
            e.line(ind + 2, &format!("r.close_member({m})?;"));
            e.line(ind + 1, "}");
            e.line(ind + 1, &format!("r.close({end})?;"));
            e.line(ind, "} else {");
            // XCDR1: the discriminator parameter, then the case's, then
            // PID_LIST_END (`XTypes` 1.3 7.4.3.5.3 rules 27-28).
            let p = e.var("p");
            let id = e.var("i");
            e.line(
                ind + 1,
                &format!("let ({id}, {p}) = match r.read_parameter()? {{"),
            );
            e.line(
                ind + 2,
                "::core::option::Option::Some(__hdds_member) => __hdds_member,",
            );
            e.line(
                ind + 2,
                "::core::option::Option::None => return ::core::option::Option::None,",
            );
            e.line(ind + 1, "};");
            e.line(
                ind + 1,
                &format!("if {id} != 0 {{ return ::core::option::Option::None; }}"),
            );
            read_disc(e, ind + 1);
            e.line(ind + 1, &format!("r.leave({p})?;"));
            e.line(
                ind + 1,
                &format!("let ({id}, {p}) = match r.read_parameter()? {{"),
            );
            e.line(
                ind + 2,
                "::core::option::Option::Some(__hdds_member) => __hdds_member,",
            );
            e.line(
                ind + 2,
                "::core::option::Option::None => return ::core::option::Option::None,",
            );
            e.line(ind + 1, "};");
            e.line(
                ind + 1,
                &format!("if {id} == 0 {{ return ::core::option::Option::None; }}"),
            );
            read_case(e, ind + 1);
            e.line(ind + 1, &format!("r.leave({p})?;"));
            e.line(ind + 1, "match r.read_parameter()? {");
            e.line(ind + 2, "::core::option::Option::None => {}");
            e.line(
                ind + 2,
                "::core::option::Option::Some(_) => return ::core::option::Option::None,",
            );
            e.line(ind + 1, "}");
            e.line(ind, "}");
        }
    }
}

/// Write the values in `slot` into the `KeyHash` (`KeyHolderWriter` in `w`),
/// in member-id order as `hash_struct` does.
fn hash_slot(e: &mut Emit, ind: usize, slot: &Slot) {
    match slot {
        Slot::Scalar { method, var } => e.line(ind, &format!("w.{method}({var});")),
        Slot::Text {
            wstring: false,
            var,
        } => e.line(ind, &format!("w.write_string(&{var});")),
        Slot::Text { wstring: true, var } => e.line(ind, &format!("w.write_wstring(&{var});")),
        Slot::List { method, var, len } => {
            if *len {
                e.line(
                    ind,
                    &format!("w.write_u32(u32::try_from({var}.len()).unwrap_or(u32::MAX));"),
                );
            }
            let v = e.var("x");
            e.line(
                ind,
                &format!("for {v} in {var}.iter() {{ w.{method}(*{v}); }}"),
            );
        }
        Slot::Struct { slots, order } => {
            for &i in order {
                hash_slot(e, ind, &slots[i]);
            }
        }
        Slot::Union(u) => {
            e.line(ind, &format!("match {} as i64 {{", u.disc_var));
            for case in &u.cases {
                let patterns: Vec<String> =
                    case.patterns.iter().map(|v| format!("{v}i64")).collect();
                e.line(ind + 1, &format!("{} => {{", patterns.join(" | ")));
                e.line(
                    ind + 2,
                    &format!("w.{}({});", writer_method(u.disc.prim()), u.disc_var),
                );
                if let Some(value) = &case.value {
                    hash_slot(e, ind + 2, value);
                }
                e.line(ind + 1, "}");
            }
            e.line(ind + 1, "_ => return ::core::option::Option::None,");
            e.line(ind, "}");
        }
    }
}

