//! Instance `KeyHash` of generated C types (RTPS 2.5 9.6.4.8).
//!
//! A header with a keyed type carries a guarded runtime (`hdds_key_holder`,
//! `hdds_kh_*`): the `KeyHolder` writer, `PLAIN_CDR2` big endian with
//! alignment capped at 4, keeping the first 16 bytes and streaming every
//! byte through an RFC 1321 MD5, with no allocation. The C, C++ and C-micro
//! backends share it. `<name>_compute_key()` writes the `KeyHolder` members
//! in member-id order, as the shared model (`codegen::key_holder`) orders
//! them, and passes the padded-or-MD5 choice computed at generation time.

use std::fmt::Write as _;

use super::super::key_holder::{
    is_default_case, KhCase, KhNode, KhPrim, KhScalar, KhStruct, KhUnion, MD5_K, MD5_S,
};
use crate::ast::UnionLabel;
use crate::types::IdlType;

const RUNTIME: &str = r"#ifndef HDDS_KEY_HOLDER_RUNTIME
#define HDDS_KEY_HOLDER_RUNTIME
#include <stddef.h>
#include <stdint.h>
#include <string.h>
/* Instance KeyHash of RTPS 2.5 9.6.4.8 (generated by hddsgen): the
 * KeyHolder serialized as PLAIN_CDR2 big endian, alignment capped at 4,
 * zero padding. The first 16 bytes are kept and every byte is streamed
 * through MD5 (RFC 1321); no allocation. */
typedef struct hdds_key_holder {
    uint32_t md5_state[4];
    uint8_t md5_block[64];
    uint32_t md5_used;
    uint32_t md5_total_lo;
    uint32_t md5_total_hi;
    uint32_t len;
    uint8_t head[16];
    uint32_t max_align;
} hdds_key_holder;

static const uint32_t hdds_kh_md5_k[64] = {
@K@
};

static const uint32_t hdds_kh_md5_init[4] = {0x67452301u, 0xefcdab89u, 0x98badcfeu, 0x10325476u};

static const uint8_t hdds_kh_md5_s[64] = {
@S@
};

static inline void hdds_kh_md5_compress(uint32_t state[4], const uint8_t block[64]) {
    uint32_t m[16];
    uint32_t a, b, c, d, f, g, t, i;
    for (i = 0u; i < 16u; ++i) {
        m[i] = (uint32_t)block[4u * i] | ((uint32_t)block[4u * i + 1u] << 8)
            | ((uint32_t)block[4u * i + 2u] << 16) | ((uint32_t)block[4u * i + 3u] << 24);
    }
    a = state[0];
    b = state[1];
    c = state[2];
    d = state[3];
    for (i = 0u; i < 64u; ++i) {
        if (i < 16u) {
            f = (b & c) | (~b & d);
            g = i;
        } else if (i < 32u) {
            f = (d & b) | (~d & c);
            g = (5u * i + 1u) % 16u;
        } else if (i < 48u) {
            f = b ^ c ^ d;
            g = (3u * i + 5u) % 16u;
        } else {
            f = c ^ (b | ~d);
            g = (7u * i) % 16u;
        }
        f = f + a + hdds_kh_md5_k[i] + m[g];
        a = d;
        d = c;
        c = b;
        t = (uint32_t)hdds_kh_md5_s[i];
        b = b + ((f << t) | (f >> (32u - t)));
    }
    state[0] += a;
    state[1] += b;
    state[2] += c;
    state[3] += d;
}

static inline void hdds_kh_md5_byte(hdds_key_holder* w, uint8_t v) {
    w->md5_block[w->md5_used] = v;
    w->md5_used += 1u;
    if (w->md5_used == 64u) {
        hdds_kh_md5_compress(w->md5_state, w->md5_block);
        w->md5_used = 0u;
    }
}

static inline void hdds_kh_init(hdds_key_holder* w) {
    memset(w, 0, sizeof(*w));
    memcpy(w->md5_state, hdds_kh_md5_init, sizeof(w->md5_state));
}

static inline void hdds_kh_byte(hdds_key_holder* w, uint8_t v) {
    if (w->len < 16u) {
        w->head[w->len] = v;
    }
    if (w->len != UINT32_MAX) {
        w->len += 1u;
    }
    w->md5_total_lo += 1u;
    if (w->md5_total_lo == 0u) {
        w->md5_total_hi += 1u;
    }
    hdds_kh_md5_byte(w, v);
}

static inline void hdds_kh_bytes(hdds_key_holder* w, const uint8_t* p, size_t n) {
    size_t i;
    for (i = 0u; i < n; ++i) {
        hdds_kh_byte(w, p[i]);
    }
}

/* A big-endian value of `size` bytes, aligned to its size capped at 4. */
static inline void hdds_kh_be(hdds_key_holder* w, uint64_t v, uint32_t size) {
    uint32_t cap = w->max_align ? w->max_align : 4u;
    uint32_t align = size < cap ? size : cap;
    uint32_t i;
    while (align > 1u && (w->md5_total_lo % align) != 0u) {
        hdds_kh_byte(w, 0u);
    }
    for (i = size; i > 0u; --i) {
        hdds_kh_byte(w, (uint8_t)(v >> (8u * (i - 1u))));
    }
}

static inline void hdds_kh_f32(hdds_key_holder* w, float v) {
    uint32_t u;
    memcpy(&u, &v, sizeof(u));
    hdds_kh_be(w, u, 4u);
}

static inline void hdds_kh_f64(hdds_key_holder* w, double v) {
    uint64_t u;
    memcpy(&u, &v, sizeof(u));
    hdds_kh_be(w, u, 8u);
}

/* `string`: length counting the NUL, the bytes, the NUL. */
static inline void hdds_kh_string_n(hdds_key_holder* w, const char* s, size_t n) {
    hdds_kh_be(w, (uint64_t)n + 1u, 4u);
    if (s != NULL) {
        hdds_kh_bytes(w, (const uint8_t*)s, n);
    }
    hdds_kh_byte(w, 0u);
}

static inline void hdds_kh_string(hdds_key_holder* w, const char* s) {
    hdds_kh_string_n(w, s, s != NULL ? strlen(s) : 0u);
}

/* `wstring`: length in bytes of UTF-16, then the code units, no NUL. A
 * wchar_t above 0xFFFF (UTF-32 platforms) becomes a surrogate pair. */
static inline void hdds_kh_wstring_n(hdds_key_holder* w, const wchar_t* s, size_t n) {
    size_t i;
    uint64_t units = 0u;
    uint32_t c;
    for (i = 0u; s != NULL && i < n; ++i) {
        units += ((uint32_t)s[i] > 0xFFFFu) ? 2u : 1u;
    }
    hdds_kh_be(w, units * 2u, 4u);
    for (i = 0u; s != NULL && i < n; ++i) {
        c = (uint32_t)s[i];
        if (c > 0xFFFFu) {
            c -= 0x10000u;
            hdds_kh_byte(w, (uint8_t)((0xD800u + (c >> 10)) >> 8));
            hdds_kh_byte(w, (uint8_t)(0xD800u + (c >> 10)));
            hdds_kh_byte(w, (uint8_t)((0xDC00u + (c & 0x3FFu)) >> 8));
            hdds_kh_byte(w, (uint8_t)(0xDC00u + (c & 0x3FFu)));
        } else {
            hdds_kh_byte(w, (uint8_t)(c >> 8));
            hdds_kh_byte(w, (uint8_t)c);
        }
    }
}

/* Characters before the first NUL, at most `max` (a bounded string held
 * in a fixed array). */
static inline size_t hdds_kh_strnlen(const char* s, size_t max) {
    size_t n = 0u;
    while (s != NULL && n < max && s[n] != 0) {
        n += 1u;
    }
    return n;
}

static inline size_t hdds_kh_wcsnlen(const wchar_t* s, size_t max) {
    size_t n = 0u;
    while (s != NULL && n < max && s[n] != 0) {
        n += 1u;
    }
    return n;
}

/* A `wstring` held as UTF-16 code units in a fixed array (C-micro). */
static inline size_t hdds_kh_u16nlen(const uint16_t* s, size_t max) {
    size_t n = 0u;
    while (s != NULL && n < max && s[n] != 0u) {
        n += 1u;
    }
    return n;
}

static inline void hdds_kh_u16string_n(hdds_key_holder* w, const uint16_t* s, size_t n) {
    size_t i;
    hdds_kh_be(w, (uint64_t)n * 2u, 4u);
    for (i = 0u; s != NULL && i < n; ++i) {
        hdds_kh_byte(w, (uint8_t)(s[i] >> 8));
        hdds_kh_byte(w, (uint8_t)s[i]);
    }
}

static inline void hdds_kh_wstring(hdds_key_holder* w, const wchar_t* s) {
    hdds_kh_wstring_n(w, s, hdds_kh_wcsnlen(s, (size_t)-1));
}

/* The KeyHash: the zero-extended serialization when `padded` (the
 * KeyHolder's maximum serialized size is at most 16) and it fits, the MD5
 * of the serialization otherwise. */
static inline void hdds_kh_finish(hdds_key_holder* w, int padded, uint8_t out[16]) {
    uint32_t i;
    uint32_t lo = w->md5_total_lo << 3;
    uint32_t hi = (w->md5_total_hi << 3) | (w->md5_total_lo >> 29);
    if (padded && w->len <= 16u) {
        memcpy(out, w->head, 16u);
        return;
    }
    hdds_kh_md5_byte(w, 0x80u);
    while (w->md5_used != 56u) {
        hdds_kh_md5_byte(w, 0u);
    }
    for (i = 0u; i < 4u; ++i) {
        hdds_kh_md5_byte(w, (uint8_t)(lo >> (8u * i)));
    }
    for (i = 0u; i < 4u; ++i) {
        hdds_kh_md5_byte(w, (uint8_t)(hi >> (8u * i)));
    }
    for (i = 0u; i < 16u; ++i) {
        out[i] = (uint8_t)(w->md5_state[i / 4u] >> (8u * (i % 4u)));
    }
}
#endif /* HDDS_KEY_HOLDER_RUNTIME */
";

/// The C runtime, with the MD5 tables of [`MD5_K`] and [`MD5_S`].
#[must_use]
pub fn runtime() -> String {
    let mut k = String::new();
    for (i, v) in MD5_K.iter().enumerate() {
        let sep = if i % 4 == 0 { "\n    " } else { " " };
        let _ = write!(k, "{sep}0x{v:08x}u,");
    }
    let mut s = String::new();
    for (i, v) in MD5_S.iter().enumerate() {
        let sep = if i % 16 == 0 { "\n    " } else { " " };
        let _ = write!(s, "{sep}{v}u,");
    }
    RUNTIME
        .replace("@K@", k.trim_start_matches('\n'))
        .replace("@S@", s.trim_start_matches('\n'))
}

/// How a backend's C or C++ types hold the values a `KeyHolder` reads.
pub trait CFlavor {
    /// Place of a member read from the place of its parent; `None` when the
    /// backend's types do not hold it (a base member the backend drops).
    fn member(&self, parent: &str, base_depth: usize, name: &str) -> Option<String>;
    /// Writer calls for a string (`wide`: `wstring`) at `place`; `None`
    /// when the backend's type cannot hold the IDL value.
    fn string(&self, place: &str, bounded: bool, wide: bool) -> Option<String>;
    /// Element count and element place (index `i`) of a sequence.
    fn sequence(&self, place: &str, bounded: bool, i: &str) -> (String, String);
    /// The discriminator place of a union at `place`.
    fn union_disc(&self, place: &str) -> String;
    /// The place of the member of case `name` of union `union_name` at
    /// `place`.
    fn union_member(&self, place: &str, union_name: &str, name: &str) -> String;
    /// The C expression of a case label of a discriminator of type `disc`.
    fn label(&self, disc: &IdlType, label: &str) -> String;
}

/// Emitter: statements at an indentation, the loop counters to declare.
pub struct Emit<'a> {
    flavor: &'a dyn CFlavor,
    out: String,
    counters: usize,
}

impl<'a> Emit<'a> {
    /// A new emitter for `flavor`.
    #[must_use]
    pub fn new(flavor: &'a dyn CFlavor) -> Self {
        Self {
            flavor,
            out: String::new(),
            counters: 0,
        }
    }

    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn counter(&mut self) -> String {
        let v = format!("hdds_i{}", self.counters);
        self.counters += 1;
        v
    }

    /// `uint32_t hdds_i0, ...;` for the loop counters the statements use
    /// (declared first, as C89 requires), or nothing.
    #[must_use]
    pub fn declarations(&self) -> String {
        if self.counters == 0 {
            return String::new();
        }
        let names: Vec<String> = (0..self.counters).map(|i| format!("hdds_i{i}")).collect();
        format!("uint32_t {};", names.join(", "))
    }

    /// The statements.
    #[must_use]
    pub fn statements(&self) -> &str {
        &self.out
    }

    fn scalar(&mut self, ind: usize, s: &KhScalar, place: &str) {
        let call = match s.prim() {
            KhPrim::Bool => format!("hdds_kh_be(w, ({place}) ? 1u : 0u, 1u);"),
            KhPrim::Octet | KhPrim::Char | KhPrim::I8 => {
                format!("hdds_kh_be(w, (uint8_t)({place}), 1u);")
            }
            KhPrim::I16 | KhPrim::U16 | KhPrim::WChar => {
                format!("hdds_kh_be(w, (uint16_t)({place}), 2u);")
            }
            KhPrim::I32 | KhPrim::U32 => format!("hdds_kh_be(w, (uint32_t)({place}), 4u);"),
            KhPrim::I64 | KhPrim::U64 => format!("hdds_kh_be(w, (uint64_t)({place}), 8u);"),
            KhPrim::F32 => format!("hdds_kh_f32(w, (float)({place}));"),
            KhPrim::F64 => format!("hdds_kh_f64(w, (double)({place}));"),
        };
        self.line(ind, &call);
    }

    fn node(&mut self, ind: usize, n: &KhNode, place: &str) -> Result<(), String> {
        match n {
            KhNode::Scalar(s) => self.scalar(ind, s, place),
            KhNode::String { bound } => {
                let call = self
                    .flavor
                    .string(place, bound.is_some(), false)
                    .ok_or_else(|| "this backend's string type cannot hold the key".to_string())?;
                self.line(ind, &call);
            }
            KhNode::WString { bound } => {
                let call = self
                    .flavor
                    .string(place, bound.is_some(), true)
                    .ok_or_else(|| "this backend's wstring type cannot hold the key".to_string())?;
                self.line(ind, &call);
            }
            KhNode::Sequence { elem, bound } => {
                let i = self.counter();
                let (count, item) = self.flavor.sequence(place, bound.is_some(), &i);
                self.line(ind, &format!("hdds_kh_be(w, (uint32_t)({count}), 4u);"));
                self.line(
                    ind,
                    &format!("for ({i} = 0u; {i} < (uint32_t)({count}); ++{i}) {{"),
                );
                self.scalar(ind + 1, elem, &item);
                self.line(ind, "}");
            }
            KhNode::Array { elem, dims } => {
                let mut cur = place.to_string();
                let mut depth = ind;
                for d in dims {
                    let i = self.counter();
                    self.line(depth, &format!("for ({i} = 0u; {i} < {d}u; ++{i}) {{"));
                    cur = format!("{cur}[{i}]");
                    depth += 1;
                }
                self.scalar(depth, elem, &cur);
                for _ in dims {
                    depth -= 1;
                    self.line(depth, "}");
                }
            }
            KhNode::Struct(s) => self.structure(ind, s, place)?,
            KhNode::Union(u) => self.union(ind, u, place)?,
        }
        Ok(())
    }

    /// The writes of a `KeyHolder` struct read from `place`, in member-id
    /// order.
    ///
    /// # Errors
    ///
    /// Returns why the backend's types cannot hold a member.
    pub fn structure(&mut self, ind: usize, s: &KhStruct, place: &str) -> Result<(), String> {
        for m in s.hash_order() {
            let p = self
                .flavor
                .member(place, m.base_depth, &m.field.name)
                .ok_or_else(|| {
                    format!(
                        "member `{}` of base `{}` is not generated by this backend",
                        m.field.name, m.owner
                    )
                })?;
            self.node(ind, &m.node, &p)?;
        }
        Ok(())
    }

    fn case_body(
        &mut self,
        ind: usize,
        union_name: &str,
        case: &KhCase,
        place: &str,
    ) -> Result<(), String> {
        if let Some(n) = &case.node {
            let p = self
                .flavor
                .union_member(place, union_name, &case.field.name);
            self.node(ind, n, &p)?;
        }
        Ok(())
    }

    fn union(&mut self, ind: usize, u: &KhUnion, place: &str) -> Result<(), String> {
        let d = self.flavor.union_disc(place);
        self.scalar(ind, &u.disc, &d);
        if u.disc_is_key {
            return Ok(());
        }
        let mut first = true;
        let mut default: Option<&KhCase> = None;
        for case in &u.cases {
            if is_default_case(&case.labels) {
                default = Some(case);
                continue;
            }
            let conds: Vec<String> = case
                .labels
                .iter()
                .filter_map(|l| match l {
                    UnionLabel::Value(v) => {
                        Some(format!("({d}) == ({})", self.flavor.label(&u.disc_type, v)))
                    }
                    UnionLabel::Default => None,
                })
                .collect();
            if conds.is_empty() {
                continue;
            }
            let kw = if first { "if" } else { "} else if" };
            first = false;
            self.line(ind, &format!("{kw} ({}) {{", conds.join(" || ")));
            self.case_body(ind + 1, &u.name, case, place)?;
        }
        if let Some(case) = default {
            self.line(ind, if first { "{" } else { "} else {" });
            self.case_body(ind + 1, &u.name, case, place)?;
            self.line(ind, "}");
        } else if !first {
            self.line(ind, "}");
        }
        Ok(())
    }
}
