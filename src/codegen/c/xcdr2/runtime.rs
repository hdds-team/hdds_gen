//! The XCDR2 little-endian cursor runtime of the generated C and C-micro
//! headers (DDS-`XTypes` 1.3 7.4.3).
//!
//! One text serves both backends; the cursor types, the position type, the
//! error codes and the function prefix are substituted. Scalars are written
//! and read byte by byte in little-endian order (no host-endianness
//! assumption), aligned to `min(size, 4)` from the start of the buffer the
//! public entry point received (the alignment origin of XCDR2: never the
//! first byte of a nested value). Padding bytes are zero. A write cursor
//! whose buffer is `NULL` only counts (the C backend's exact size). The text
//! is C89 with `<stdint.h>`.

use super::Flavor;

/// Functions both backends use.
const COMMON: &str = r"
#ifndef @G@
#define @G@
/* XCDR2 little-endian cursors (generated by hddsgen; DDS-XTypes 1.3
 * 7.4.3). Alignment min(size, 4) from the start of the buffer; zero
 * padding. A write cursor with a NULL buffer only counts bytes. */
#define @M@TRY(e) do { int @p@rc_ = (int)(e); if (@p@rc_ != 0) { return @p@rc_; } } while (0)

static @INL@ int @p@reserve(@W@* c, @POS@ n, @POS@* at) {
    if (c->pos > c->size || n > c->size - c->pos) { return @EW@; }
    *at = c->pos;
    c->pos += n;
    return 0;
}

static @INL@ int @p@raw(@W@* c, const void* p, @POS@ n) {
    @POS@ at;
    int rc = @p@reserve(c, n, &at);
    if (rc != 0) { return rc; }
    if (c->buf != NULL && n > 0) { memcpy(c->buf + at, p, (size_t)n); }
    return 0;
}

static @INL@ int @p@pad(@W@* c, @POS@ a) {
    @POS@ n = (@POS@)((a - (c->pos % a)) % a);
    @POS@ at;
    int rc;
    if (n == 0) { return 0; }
    rc = @p@reserve(c, n, &at);
    if (rc != 0) { return rc; }
    if (c->buf != NULL) { memset(c->buf + at, 0, (size_t)n); }
    return 0;
}

static @INL@ int @p@w8(@W@* c, uint8_t v) {
    return @p@raw(c, &v, 1);
}

static @INL@ int @p@w16(@W@* c, uint16_t v) {
    uint8_t b[2];
    @M@TRY(@p@pad(c, 2));
    b[0] = (uint8_t)(v & 0xFFu);
    b[1] = (uint8_t)((v >> 8) & 0xFFu);
    return @p@raw(c, b, 2);
}

static @INL@ int @p@w32(@W@* c, uint32_t v) {
    uint8_t b[4];
    int i;
    @M@TRY(@p@pad(c, 4));
    for (i = 0; i < 4; ++i) { b[i] = (uint8_t)((v >> (8 * i)) & 0xFFu); }
    return @p@raw(c, b, 4);
}

/* 8-byte primitives align at 4 under XCDR2 (7.4.3.5.3, rule 2). */
static @INL@ int @p@w64(@W@* c, uint64_t v) {
    uint8_t b[8];
    int i;
    @M@TRY(@p@pad(c, 4));
    for (i = 0; i < 8; ++i) { b[i] = (uint8_t)((v >> (8 * i)) & 0xFFu); }
    return @p@raw(c, b, 8);
}

static @INL@ int @p@wf32(@W@* c, float f) {
    uint32_t u;
    memcpy(&u, &f, 4);
    return @p@w32(c, u);
}

static @INL@ int @p@wf64(@W@* c, double d) {
    uint64_t u;
    memcpy(&u, &d, 8);
    return @p@w64(c, u);
}

/* A length word (DHEADER, NEXTINT), aligned at 4, filled by wend. */
static @INL@ int @p@wbegin(@W@* c, @POS@* at) {
    @M@TRY(@p@pad(c, 4));
    return @p@reserve(c, 4, at);
}

static @INL@ int @p@wend(@W@* c, @POS@ at) {
    uint32_t n = (uint32_t)(c->pos - at - 4);
    int i;
    if (c->buf != NULL) {
        for (i = 0; i < 4; ++i) { c->buf[at + (@POS@)i] = (uint8_t)((n >> (8 * i)) & 0xFFu); }
    }
    return 0;
}

/* string: length counting the NUL, the bytes, the NUL; `bound` 0: none. */
static @INL@ int @p@wstr(@W@* c, const char* s, @POS@ bound) {
    @POS@ n = 0;
    if (s == NULL) { return @EI@; }
    if (bound == 0) {
        n = (@POS@)strlen(s);
    } else {
        while (n <= bound && s[n] != 0) { ++n; }
        if (n > bound) { return @EI@; }
    }
    @M@TRY(@p@w32(c, (uint32_t)(n + 1)));
    return @p@raw(c, s, n + 1);
}

static @INL@ int @p@take(@R@* c, @POS@ n, @POS@* at) {
    if (c->pos > c->size || n > c->size - c->pos) { return @ER@; }
    *at = c->pos;
    c->pos += n;
    return 0;
}

static @INL@ int @p@rraw(@R@* c, void* p, @POS@ n) {
    @POS@ at;
    @M@TRY(@p@take(c, n, &at));
    if (n > 0) { memcpy(p, c->buf + at, (size_t)n); }
    return 0;
}

static @INL@ int @p@rpad(@R@* c, @POS@ a) {
    @POS@ n = (@POS@)((a - (c->pos % a)) % a);
    @POS@ at;
    return @p@take(c, n, &at);
}

static @INL@ int @p@r8(@R@* c, uint8_t* v) {
    @POS@ at;
    @M@TRY(@p@take(c, 1, &at));
    *v = c->buf[at];
    return 0;
}

static @INL@ int @p@r16(@R@* c, uint16_t* v) {
    @POS@ at;
    @M@TRY(@p@rpad(c, 2));
    @M@TRY(@p@take(c, 2, &at));
    *v = (uint16_t)((uint16_t)c->buf[at] | (uint16_t)((uint16_t)c->buf[at + 1] << 8));
    return 0;
}

static @INL@ int @p@r32(@R@* c, uint32_t* v) {
    @POS@ at;
    uint32_t x = 0;
    int i;
    @M@TRY(@p@rpad(c, 4));
    @M@TRY(@p@take(c, 4, &at));
    for (i = 3; i >= 0; --i) { x = (x << 8) | (uint32_t)c->buf[at + (@POS@)i]; }
    *v = x;
    return 0;
}

static @INL@ int @p@r64(@R@* c, uint64_t* v) {
    @POS@ at;
    uint64_t x = 0;
    int i;
    @M@TRY(@p@rpad(c, 4));
    @M@TRY(@p@take(c, 8, &at));
    for (i = 7; i >= 0; --i) { x = (x << 8) | (uint64_t)c->buf[at + (@POS@)i]; }
    *v = x;
    return 0;
}

static @INL@ int @p@rf32(@R@* c, float* f) {
    uint32_t u;
    @M@TRY(@p@r32(c, &u));
    memcpy(f, &u, 4);
    return 0;
}

static @INL@ int @p@rf64(@R@* c, double* d) {
    uint64_t u;
    @M@TRY(@p@r64(c, &u));
    memcpy(d, &u, 8);
    return 0;
}

/* A length word (DHEADER): the end of the bytes it delimits. */
static @INL@ int @p@rbegin(@R@* c, @POS@* end) {
    uint32_t n;
    @M@TRY(@p@r32(c, &n));
    if ((@POS@)n > c->size - c->pos) { return @ER@; }
    *end = c->pos + (@POS@)n;
    return 0;
}

/* Move to `end`, skipping what a newer writer appended; an `end` behind
 * the cursor means the value overran its delimiter. Every `end` comes from
 * rbegin or remh, which bound it by the buffer (the one place that bound
 * is checked). */
static @INL@ int @p@rskip(@R@* c, @POS@ end) {
    if (end < c->pos) { return @EI@; }
    c->pos = end;
    return 0;
}

/* EMHEADER1 and its NEXTINT (7.4.3.4.2): must-understand flag, member id
 * and member end; the cursor at the value (on the NEXTINT for LC 5-7). */
static const uint32_t @p@id_mask = 0x0FFFFFFFu;

static @INL@ int @p@remh(@R@* c, @POS@ end, int* mu, uint32_t* id, @POS@* mend) {
    uint32_t h;
    uint32_t n;
    @POS@ size;
    @POS@ unit;
    @M@TRY(@p@r32(c, &h));
    *mu = (int)(h >> 31);
    *id = h & @p@id_mask;
    switch ((h >> 28) & 7u) {
    case 0: size = 1; break;
    case 1: size = 2; break;
    case 2: size = 4; break;
    case 3: size = 8; break;
    default:
        @M@TRY(@p@r32(c, &n));
        if (((h >> 28) & 7u) == 4u) {
            size = (@POS@)n;
        } else {
            c->pos -= 4;
            unit = ((h >> 28) & 7u) == 5u ? 1 : (((h >> 28) & 7u) == 6u ? 4 : 8);
            if ((@POS@)n > (@POS@)(((@POS@)-1 - 4) / unit)) { return @EI@; }
            size = 4 + (@POS@)n * unit;
        }
        break;
    }
    if (c->pos > end || size > end - c->pos) { return @EI@; }
    *mend = c->pos + size;
    return 0;
}

/* string into the array `dst` of `cap` (at least 1) bytes, NUL included. */
static @INL@ int @p@rstr(@R@* c, char* dst, @POS@ cap) {
    uint32_t n;
    @POS@ at;
    @M@TRY(@p@r32(c, &n));
    if (dst == NULL || (@POS@)n > cap) { return @EI@; }
    if (n == 0) { dst[0] = 0; return 0; }
    @M@TRY(@p@take(c, (@POS@)n, &at));
    if (c->buf[at + (@POS@)n - 1] != 0) { return @EI@; }
    memcpy(dst, c->buf + at, (size_t)n);
    return 0;
}
";

/// UTF-16 strings held as `uint16_t` arrays (C-micro).
const UTF16: &str = r"
/* wstring held as UTF-16 code units: byte length, units, no NUL. */
static @INL@ int @p@wstr16(@W@* c, const uint16_t* s, @POS@ bound) {
    @POS@ n = 0;
    @POS@ i;
    if (s == NULL) { return @EI@; }
    while (n <= bound && s[n] != 0) { ++n; }
    if (n > bound) { return @EI@; }
    @M@TRY(@p@w32(c, (uint32_t)(n * 2)));
    for (i = 0; i < n; ++i) {
        uint8_t b[2];
        b[0] = (uint8_t)(s[i] & 0xFFu);
        b[1] = (uint8_t)((s[i] >> 8) & 0xFFu);
        @M@TRY(@p@raw(c, b, 2));
    }
    return 0;
}

static @INL@ int @p@rstr16(@R@* c, uint16_t* dst, @POS@ cap) {
    uint32_t n;
    @POS@ at;
    @POS@ i;
    @M@TRY(@p@r32(c, &n));
    if (dst == NULL || (n % 2u) != 0 || (@POS@)(n / 2u) >= cap) { return @EI@; }
    @M@TRY(@p@take(c, (@POS@)n, &at));
    for (i = 0; i < (@POS@)(n / 2u); ++i) {
        dst[i] = (uint16_t)((uint16_t)c->buf[at + 2 * i] | (uint16_t)((uint16_t)c->buf[at + 2 * i + 1] << 8));
    }
    dst[n / 2u] = 0;
    return 0;
}
";

/// Wide characters and strings held as `wchar_t` (C): UTF-16 on the wire.
const WCHAR_T: &str = r"
/* wchar: one UTF-16 code unit (a surrogate or a code point beyond the BMP
 * is refused). */
static @INL@ int @p@wwchar(@W@* c, wchar_t ch) {
    unsigned long cp = (unsigned long)ch;
    if (cp > 0xFFFFul || (cp >= 0xD800ul && cp <= 0xDFFFul)) { return @EI@; }
    return @p@w16(c, (uint16_t)cp);
}

static @INL@ int @p@rwchar(@R@* c, wchar_t* ch) {
    uint16_t u;
    @M@TRY(@p@r16(c, &u));
    if (u >= 0xD800u && u <= 0xDFFFu) { return @EI@; }
#if WCHAR_MAX < 0xFFFF
    if ((unsigned long)u > (unsigned long)WCHAR_MAX) { return @EI@; }
#endif
    *ch = (wchar_t)u;
    return 0;
}

static @INL@ int @p@unit(@W@* c, unsigned long u) {
    uint8_t b[2];
    b[0] = (uint8_t)(u & 0xFFu);
    b[1] = (uint8_t)((u >> 8) & 0xFFu);
    return @p@raw(c, b, 2);
}

/* wstring: byte length of its UTF-16 form, the code units, no NUL;
 * `bound` (0: none) in characters of the `wchar_t` string. */
static @INL@ int @p@wwstr(@W@* c, const wchar_t* s, @POS@ bound) {
    @POS@ n = 0;
    @POS@ units = 0;
    @POS@ i;
    if (s == NULL) { return @EI@; }
    while ((bound == 0 || n <= bound) && s[n] != 0) {
        unsigned long cp = (unsigned long)s[n];
        if (WCHAR_MAX > 0xFFFF && (cp > 0x10FFFFul || (cp >= 0xD800ul && cp <= 0xDFFFul))) { return @EI@; }
        units += (cp > 0xFFFFul) ? 2 : 1;
        ++n;
    }
    if (bound != 0 && n > bound) { return @EI@; }
    @M@TRY(@p@w32(c, (uint32_t)(units * 2)));
    for (i = 0; i < n; ++i) {
        unsigned long cp = (unsigned long)s[i];
        if (cp > 0xFFFFul) {
            cp -= 0x10000ul;
            @M@TRY(@p@unit(c, 0xD800ul + (cp >> 10)));
            @M@TRY(@p@unit(c, 0xDC00ul + (cp & 0x3FFul)));
        } else {
            @M@TRY(@p@unit(c, cp));
        }
    }
    return 0;
}

/* The `units` UTF-16 code units at `at` into `dst` (room for `units`
 * wchar_t and the NUL): a surrogate pair is one wchar_t when wchar_t holds
 * code points beyond the BMP. */
static @INL@ int @p@runits(@R@* c, @POS@ at, @POS@ units, wchar_t* dst) {
    @POS@ i;
    @POS@ k = 0;
    for (i = 0; i < units; ++i) {
        unsigned long u = (unsigned long)c->buf[at + 2 * i] | ((unsigned long)c->buf[at + 2 * i + 1] << 8);
        if (u >= 0xD800ul && u <= 0xDBFFul && WCHAR_MAX > 0xFFFF) {
            unsigned long lo;
            if (i + 1 >= units) { return @EI@; }
            lo = (unsigned long)c->buf[at + 2 * i + 2] | ((unsigned long)c->buf[at + 2 * i + 3] << 8);
            if (lo < 0xDC00ul || lo > 0xDFFFul) { return @EI@; }
            u = 0x10000ul + ((u - 0xD800ul) << 10) + (lo - 0xDC00ul);
            ++i;
        } else if (u >= 0xDC00ul && u <= 0xDFFFul && WCHAR_MAX > 0xFFFF) {
            return @EI@;
        }
        dst[k++] = (wchar_t)u;
    }
    dst[k] = 0;
    return 0;
}

/* wstring into the array `dst` of `cap` wchar_t, NUL included, at most
 * `bound` code units. */
static @INL@ int @p@rwstr(@R@* c, wchar_t* dst, @POS@ cap, @POS@ bound) {
    uint32_t n;
    @POS@ at;
    @M@TRY(@p@r32(c, &n));
    if (dst == NULL || (n % 2u) != 0) { return @EI@; }
    if ((@POS@)(n / 2u) > bound || (@POS@)(n / 2u) >= cap) { return @EI@; }
    @M@TRY(@p@take(c, (@POS@)n, &at));
    return @p@runits(c, at, (@POS@)(n / 2u), dst);
}
";

/// Storage of the C backend's pointer holders (unbounded strings, every
/// sequence and map), obtained by the decoder from the reader's allocator
/// and charged to the budget of the decode.
const C_ALLOC: &str = r"
/* CDR_MAX_ZERO_WIRE_ELEMENTS and CDR_MAX_ALLOC_RATIO through objects (see
 * max_string below). */
static const uint32_t @p@max_zero_wire = (uint32_t)CDR_MAX_ZERO_WIRE_ELEMENTS;
static const @POS@ @p@max_alloc_ratio = (@POS@)CDR_MAX_ALLOC_RATIO;

/* A read cursor over the `size` bytes at `buf`, at `pos`, and the budget
 * of one decode: the storage it may request in all is the larger of
 * CDR_MAX_ZERO_WIRE_ELEMENTS bytes and CDR_MAX_ALLOC_RATIO times the bytes
 * of the body (`size - pos`), of which CDR_MAX_ZERO_WIRE_ELEMENTS bytes at
 * most for elements that take no byte on the wire. Every nested value is
 * decoded through the same cursor, so the bounds hold for the whole
 * decode, however the collections nest. */
static @INL@ void @p@rinit(@R@* c, const uint8_t* buf, @POS@ size, @POS@ pos, hdds_x2c_alloc_fn alloc, void* actx) {
    @POS@ body = pos > size ? 0 : size - pos;
    c->buf = buf;
    c->size = size;
    c->pos = pos;
    c->alloc = alloc;
    c->actx = actx;
    c->budget = (@POS@)@p@max_zero_wire;
    if (body > ((@POS@)-1) / @p@max_alloc_ratio) {
        c->budget = (@POS@)-1;
    } else if (body * @p@max_alloc_ratio > c->budget) {
        c->budget = body * @p@max_alloc_ratio;
    }
    c->zero_wire = (@POS@)@p@max_zero_wire;
}

/* Storage for `n` elements of `elem` bytes from the reader's allocator
 * (`*out` NULL for n = 0), charged to the budget of the decode: refused
 * (-CDR_OUT_OF_MEMORY, before the allocator is called) beyond what is
 * left of it. A count is bounded by the bytes left over the least wire
 * size of an element first, but a C element can be much larger than that
 * least wire form (an absent optional array, a union's large unselected
 * branch, nested empty structures), and collections nest: the budget
 * bounds the storage of the whole decode, and the work of filling it. The
 * decoder computes every size from bytes it has already bounded, so it
 * never writes past what it obtained. */
static @INL@ int @p@ralloc(@R@* c, @POS@ n, @POS@ elem, void** out) {
    void* p;
    *out = NULL;
    if (n == 0) { return 0; }
    if (c->alloc == NULL) { return (-CDR_OUT_OF_MEMORY); }
    if (elem != 0 && n > ((@POS@)-1) / elem) { return (-CDR_OUT_OF_MEMORY); }
    if (n * elem > c->budget) { return (-CDR_OUT_OF_MEMORY); }
    p = c->alloc(c->actx, n * elem);
    if (p == NULL) { return (-CDR_OUT_OF_MEMORY); }
    c->budget -= n * elem;
    *out = p;
    return 0;
}

/* The `n` elements of `elem` bytes (at least 1) of a sequence or map
 * whose elements take no byte on the wire (an empty FINAL structure, one
 * byte; empty structures nested in one another, more): the bytes left
 * cannot bound them, so their storage is charged to the
 * CDR_MAX_ZERO_WIRE_ELEMENTS bytes of the whole decode and refused beyond
 * them (-CDR_INVALID_DATA), before ralloc charges it again to the budget.
 * A CPU and storage sink otherwise: 4 billion elements decoded from 4
 * bytes, or inner sequences of such elements nested in a sequence, each
 * within a per-collection cap. */
static @INL@ int @p@rzcount(@R@* c, uint32_t n, @POS@ elem) {
    if (elem == 0) { elem = 1; }
    if ((@POS@)n > c->zero_wire / elem) { return @EI@; }
    c->zero_wire -= (@POS@)n * elem;
    return 0;
}

/* CDR_MAX_STRING through an object: a definition of UINT32_MAX or more
 * must not make the comparison constant. */
static const @POS@ @p@max_string = (@POS@)@MAXSTR@;

/* An unbounded string: the bytes are bounded by the buffer (and by
 * CDR_MAX_STRING) before any storage is requested. */
static @INL@ int @p@rstra(@R@* c, char** dst) {
    uint32_t n;
    @POS@ at;
    void* p;
    @M@TRY(@p@r32(c, &n));
    if ((@POS@)n > @p@max_string) { return @EI@; }
    @M@TRY(@p@take(c, (@POS@)n, &at));
    if (n > 0 && c->buf[at + (@POS@)n - 1] != 0) { return @EI@; }
    @M@TRY(@p@ralloc(c, n == 0 ? 1 : (@POS@)n, 1, &p));
    if (n == 0) { ((char*)p)[0] = 0; } else { memcpy(p, c->buf + at, (size_t)n); }
    *dst = (char*)p;
    return 0;
}

/* An unbounded wstring, the code units bounded by the buffer first. */
static @INL@ int @p@rwstra(@R@* c, wchar_t** dst) {
    uint32_t n;
    @POS@ at;
    void* p;
    @M@TRY(@p@r32(c, &n));
    if ((n % 2u) != 0 || (@POS@)n > @p@max_string) { return @EI@; }
    @M@TRY(@p@take(c, (@POS@)n, &at));
    @M@TRY(@p@ralloc(c, (@POS@)(n / 2u) + 1, (@POS@)sizeof(wchar_t), &p));
    @M@TRY(@p@runits(c, at, (@POS@)(n / 2u), (wchar_t*)p));
    *dst = (wchar_t*)p;
    return 0;
}
";

/// The C backend's cursor types.
const C_TYPES: &str = r"
typedef struct hdds_x2c_w { uint8_t* buf; size_t size; size_t pos; } hdds_x2c_w;
/* Storage callback of the decoder: `size` bytes aligned for any object
 * (as malloc), or NULL. */
typedef void* (*hdds_x2c_alloc_fn)(void* ctx, size_t size);
typedef struct hdds_x2c_r {
    const uint8_t* buf;
    size_t size;
    size_t pos;
    hdds_x2c_alloc_fn alloc; /* NULL: no storage, pointer holders refused */
    void* actx;
    size_t budget; /* storage bytes this decode may still request */
    size_t zero_wire; /* of which for elements of no wire size */
} hdds_x2c_r;

/* A bump allocator over a caller buffer, for hdds_x2c_alloc_fn: no free,
 * reset `used` to reuse the buffer. */
#ifndef HDDS_X2C_ARENA_ALIGN
#define HDDS_X2C_ARENA_ALIGN 16u
#endif
typedef struct hdds_x2c_arena { uint8_t* buf; size_t size; size_t used; } hdds_x2c_arena;

static @INL@ void hdds_x2c_arena_init(hdds_x2c_arena* a, void* buf, size_t size) {
    a->buf = (uint8_t*)buf;
    a->size = buf == NULL ? 0 : size;
    a->used = 0;
}

static @INL@ void* hdds_x2c_arena_alloc(void* ctx, size_t n) {
    hdds_x2c_arena* a = (hdds_x2c_arena*)ctx;
    size_t mis;
    size_t at;
    if (a == NULL || a->buf == NULL || a->used > a->size) { return NULL; }
    mis = (size_t)((uintptr_t)(a->buf + a->used) % (uintptr_t)HDDS_X2C_ARENA_ALIGN);
    at = a->used + (mis == 0 ? 0 : (size_t)HDDS_X2C_ARENA_ALIGN - mis);
    if (at > a->size || n > a->size - at) { return NULL; }
    a->used = at + n;
    return a->buf + at;
}
";

/// The XCDR1 reads of the C backend (DDS-XTypes 1.3 7.4.1), under their own
/// include guard: a header generated by an earlier hddsgen keeps its older
/// runtime block, which this one only adds to.
const C_XCDR1: &str = r"
#ifndef HDDS_X1C_RUNTIME
#define HDDS_X1C_RUNTIME
/* XCDR1 little-endian reads (generated by hddsgen; DDS-XTypes 1.3 7.4.1),
 * on the read cursor of the XCDR2 runtime. Alignment is min(size, 8)
 * measured from the origin `o`: the start of the buffer, or the first byte
 * of the value of the parameter being read (7.4.1.2.2). Every origin is a
 * multiple of 4 bytes from the start of the buffer (a parameter header is
 * aligned at 4 and takes 4 or 12 bytes), so the XCDR2 reads of 1, 2 and 4
 * bytes align as XCDR1 does: only 8-byte values have reads of their own.
 * The generated decoders of this header read XCDR1 (`_decode_cdr1_le`). */
#define HDDSGEN_C_DECODES_XCDR1 1

static @INL@ int hdds_x1c_r64(hdds_x2c_r* c, size_t o, uint64_t* v) {
    size_t at;
    uint64_t x = 0;
    int i;
    if (o > c->pos) { return (-CDR_INVALID_DATA); }
    HDDS_X2C_TRY(hdds_x2c_take(c, (8 - ((c->pos - o) % 8)) % 8, &at));
    HDDS_X2C_TRY(hdds_x2c_take(c, 8, &at));
    for (i = 7; i >= 0; --i) { x = (x << 8) | (uint64_t)c->buf[at + (size_t)i]; }
    *v = x;
    return 0;
}

static @INL@ int hdds_x1c_rf64(hdds_x2c_r* c, size_t o, double* d) {
    uint64_t u;
    HDDS_X2C_TRY(hdds_x1c_r64(c, o, &u));
    memcpy(d, &u, 8);
    return 0;
}

/* The next parameter of an XCDR1 parameter list (7.4.1.2.2), aligned at 4:
 * `*last` set at PID_LIST_END (0x3F02); otherwise the member id and
 * must-understand flag (FLAG_2 of a PID_EXTENDED (0x3F01) header, FLAG_M
 * of a short one), the end of the value, bounded by the buffer, the cursor
 * on the value (whose first byte is the origin of its alignment).
 * PID_IGNORE (0x3F03) parameters are skipped. */
static @INL@ int hdds_x1c_rpl(hdds_x2c_r* c, int* last, uint32_t* id, int* mu, size_t* mend) {
    uint16_t pid;
    uint16_t plen;
    uint32_t h;
    uint32_t n;
    for (;;) {
        HDDS_X2C_TRY(hdds_x2c_rpad(c, 4));
        HDDS_X2C_TRY(hdds_x2c_r16(c, &pid));
        HDDS_X2C_TRY(hdds_x2c_r16(c, &plen));
        *last = 0;
        if ((pid & 0x3FFFu) == 0x3F02u) { *last = 1; return 0; }
        if ((pid & 0x3FFFu) == 0x3F01u) {
            HDDS_X2C_TRY(hdds_x2c_r32(c, &h));
            HDDS_X2C_TRY(hdds_x2c_r32(c, &n));
            *id = h & 0x0FFFFFFFu;
            *mu = (h & 0x40000000u) != 0;
        } else {
            *id = (uint32_t)(pid & 0x3FFFu);
            *mu = (pid & 0x4000u) != 0;
            n = (uint32_t)plen;
        }
        if ((size_t)n > c->size - c->pos) { return (-CDR_UNEXPECTED_EOF); }
        *mend = c->pos + (size_t)n;
        if ((pid & 0x3FFFu) != 0x3F03u) { return 0; }
        c->pos = *mend;
    }
}
#endif
";

/// The runtime text of `flavor`, its functions `static <inline>`.
#[must_use]
pub fn runtime(flavor: Flavor, inline: &str) -> String {
    let mut text = String::from(COMMON);
    let guard_end = "#endif\n";
    match flavor {
        Flavor::C => {
            text = text.replacen("#define @M@TRY", &format!("{C_TYPES}\n#define @M@TRY"), 1);
            text.push_str(WCHAR_T);
            text.push_str(C_ALLOC);
        }
        Flavor::Micro { .. } => text.push_str(UTF16),
    }
    text.push_str(guard_end);
    if flavor == Flavor::C {
        text.push_str(C_XCDR1);
    }
    let (w, r, pos, ew, er, ei, maxstr) = match flavor {
        Flavor::C => (
            "hdds_x2c_w",
            "hdds_x2c_r",
            "size_t",
            "(-CDR_BUFFER_TOO_SMALL)",
            "(-CDR_UNEXPECTED_EOF)",
            "(-CDR_INVALID_DATA)",
            "CDR_MAX_STRING",
        ),
        Flavor::Micro { .. } => (
            "hdds_cdr_t",
            "hdds_cdr_t",
            "uint32_t",
            "HDDS_CDR_ERR_OVERFLOW",
            "HDDS_CDR_ERR_UNDERFLOW",
            "HDDS_CDR_ERR_INVALID",
            "0xFFFFFFFFu",
        ),
    };
    let p = flavor.prefix();
    text.replace("@G@", &format!("{}RUNTIME", p.to_ascii_uppercase()))
        .replace("@M@", &p.to_ascii_uppercase())
        .replace("@p@", p)
        .replace("@INL@", inline)
        .replace("@W@", w)
        .replace("@R@", r)
        .replace("@POS@", pos)
        .replace("@EW@", ew)
        .replace("@ER@", er)
        .replace("@EI@", ei)
        .replace("@MAXSTR@", maxstr)
}
