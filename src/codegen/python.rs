//! Python code generator
//!
//! Generates idiomatic Python 3 (dataclasses + type hints).
//!
//! Note: uninlined_format_args allowed here due to extensive format!() usage
//! in code generation that would require significant refactoring.

#![allow(clippy::uninlined_format_args)]

use crate::ast::{Bitmask, Bitset, Const, Definition, Enum, IdlFile, Struct, Typedef, Union};
use crate::codegen::key_holder::TypeIndex;
use crate::codegen::keywords::python_ident;
use crate::codegen::CodeGenerator;
use crate::error::{ErrorKind, ParseError, Position, Result};
use crate::types::{Annotation, IdlType, PrimitiveType};
use std::collections::{HashMap, HashSet};
use std::fmt::Write;

use scope::{flat, idl_name, ModuleTree};

mod codec;
mod key_hash;
pub(in crate::codegen) mod scope;

fn push_fmt(dst: &mut String, args: std::fmt::Arguments<'_>) {
    let _ = dst.write_fmt(args);
}

/// Globals the generated module uses (its imports): a module view or an
/// unqualified alias never rebinds them.
const RUNTIME_NAMES: &[&str] = &[
    "dataclass",
    "field",
    "List",
    "Dict",
    "Optional",
    "UnionType",
    "Tuple",
    "IntEnum",
    "struct",
    "hashlib",
    "CDR_MAX_ALLOC_RATIO",
    "CDR_MAX_ZERO_WIRE_ELEMENTS",
    "HDDS_DECODES_XCDR1",
];

/// Python code generator producing dataclasses and serde helpers.
pub struct PythonGenerator {
    indent_level: usize,
}

impl PythonGenerator {
    /// Creates a new Python generator.
    #[must_use]
    pub const fn new() -> Self {
        // Indent by one level inside class bodies by default
        Self { indent_level: 1 }
    }

    fn indent(&self) -> String {
        "    ".repeat(self.indent_level)
    }

    fn type_to_python(t: &IdlType) -> String {
        match t {
            IdlType::BoundedString { .. } => "str".to_string(),
            IdlType::Primitive(p) => match p {
                PrimitiveType::Void => "None".to_string(),
                PrimitiveType::Boolean => "bool".to_string(),
                PrimitiveType::Char
                | PrimitiveType::WChar
                | PrimitiveType::Octet
                | PrimitiveType::Short
                | PrimitiveType::UnsignedShort
                | PrimitiveType::Long
                | PrimitiveType::UnsignedLong
                | PrimitiveType::LongLong
                | PrimitiveType::UnsignedLongLong
                | PrimitiveType::Int8
                | PrimitiveType::Int16
                | PrimitiveType::Int32
                | PrimitiveType::Int64
                | PrimitiveType::UInt8
                | PrimitiveType::UInt16
                | PrimitiveType::UInt32
                | PrimitiveType::UInt64 => "int".to_string(),
                PrimitiveType::Float | PrimitiveType::Double | PrimitiveType::LongDouble => {
                    "float".to_string()
                }
                PrimitiveType::String | PrimitiveType::WString => "str".to_string(),
                PrimitiveType::Fixed { .. } => "float".to_string(), // MVP: decimal later
            },
            IdlType::Named(n) => flat(n),
            IdlType::Sequence { inner, .. } | IdlType::Array { inner, .. } => {
                format!("List[{}]", Self::type_to_python(inner))
            }
            IdlType::Map { key, value, .. } => {
                format!(
                    "Dict[{}, {}]",
                    Self::type_to_python(key),
                    Self::type_to_python(value)
                )
            }
        }
    }

    fn emit_header() -> String {
        let mut out = String::new();
        out.push_str("\"\"\"\n");
        push_fmt(
            &mut out,
            format_args!("Generated by hddsgen v{}\n", env!("HDDS_VERSION")),
        );
        out.push_str("DO NOT EDIT\n\n");
        out.push_str("Python target (dataclasses + typing + CDR2 serialization)\n");
        out.push_str("\"\"\"\n\n");

        // Imports
        out.push_str("from dataclasses import dataclass, field\n");
        out.push_str("from typing import List, Dict, Optional, Union as UnionType, Tuple\n");
        out.push_str("from enum import IntEnum\n");
        out.push_str("import struct\n");
        out.push_str("import hashlib\n\n");
        out
    }

    fn emit_struct(&self, s: &Struct, idx: &TypeIndex) -> String {
        let mut out = String::new();
        let name = flat(&s.name);

        // Docstring with original IDL signature
        let mut idl_sig = String::new();
        push_fmt(
            &mut idl_sig,
            format_args!("struct {} {{ ", idl_name(&s.name)),
        );
        for (i, f) in s.fields.iter().enumerate() {
            if i > 0 {
                idl_sig.push(' ');
            }
            push_fmt(
                &mut idl_sig,
                format_args!("{} {};", f.field_type.to_idl_string(), f.name),
            );
        }
        push_fmt(&mut idl_sig, format_args!(" }}"));
        let idl_sig = idl_sig.replace('.', "::");

        // Class header (inheritance when present)
        if let Some(base) = &s.base_struct {
            push_fmt(
                &mut out,
                format_args!("@dataclass\nclass {}({}):\n", name, flat(base)),
            );
        } else {
            push_fmt(&mut out, format_args!("@dataclass\nclass {}:\n", name));
        }
        push_fmt(
            &mut out,
            format_args!("{}\"\"\"IDL: {}\"\"\"\n", self.indent(), idl_sig),
        );

        // Every member has a default (DDS-XTypes 1.3 Table 9, spec text
        // line 2311), so the dataclass keeps the IDL order (which the
        // serialization follows) without "non-default argument follows
        // default argument".
        for f in &s.fields {
            let mut ty = Self::type_to_python(&f.field_type);
            let default_suffix = if f.is_optional() {
                ty = format!("Optional[{ty}]");
                " = None".to_string()
            } else {
                codec::field_default(idx, &f.field_type)
            };
            let ident = python_ident(&f.name);
            push_fmt(
                &mut out,
                format_args!("{}{}: {}{}\n", self.indent(), ident, ty, default_suffix),
            );
        }

        if s.fields.is_empty() {
            push_fmt(&mut out, format_args!("{}pass\n", self.indent()));
        }
        out.push('\n');

        // XCDR2 codec (DDS-XTypes 1.3 7.4.3.5.3)
        out.push_str(&codec::struct_codec(idx, s, self.indent_level));
        out.push('\n');

        // Generate type_name() classmethod
        out.push_str(&self.emit_type_name_method(s));
        out.push('\n');

        let _ = writeln!(
            out,
            "{}HDDS_KEY_SUPPORTED = {}",
            self.indent(),
            if matches!(idx.key_holder(s), Ok(Some(_))) {
                "True"
            } else {
                "False"
            }
        );
        // Generate compute_key(): instance KeyHash, RTPS 2.5 9.6.4.8
        out.push_str(&key_hash::compute_key_method(s, idx, &self.indent()));
        out.push('\n');

        // Generate has_key() classmethod
        out.push_str(&self.emit_has_key_method(s, idx));
        out.push('\n');

        out
    }

    /// Generate `type_name()` classmethod
    fn emit_type_name_method(&self, s: &Struct) -> String {
        let mut out = String::new();
        let indent = self.indent();
        let indent2 = format!("{}    ", indent);

        push_fmt(&mut out, format_args!("{}@classmethod\n", indent));
        push_fmt(
            &mut out,
            format_args!("{}def type_name(cls) -> str:\n", indent),
        );
        push_fmt(
            &mut out,
            format_args!("{}\"\"\"Return the DDS type name.\"\"\"\n", indent2),
        );
        // The fully scoped IDL name (`a::b::T`), as DDS names the type.
        push_fmt(
            &mut out,
            format_args!("{}return \"{}\"\n", indent2, idl_name(&s.name)),
        );
        out
    }

    /// Generate `has_key()` classmethod
    fn emit_has_key_method(&self, s: &Struct, idx: &TypeIndex) -> String {
        let mut out = String::new();
        let indent = self.indent();
        let indent2 = format!("{}    ", indent);

        // A key member of a base type makes the derived type keyed too.
        let has_key = idx.is_keyed(s);

        push_fmt(&mut out, format_args!("{}@classmethod\n", indent));
        push_fmt(
            &mut out,
            format_args!("{}def has_key(cls) -> bool:\n", indent),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}\"\"\"Return True if this type has @key fields.\"\"\"\n",
                indent2
            ),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}return {}\n",
                indent2,
                if has_key { "True" } else { "False" }
            ),
        );
        out
    }

    fn emit_enum(&self, e: &Enum) -> String {
        let mut out = String::new();
        push_fmt(
            &mut out,
            format_args!("class {}(IntEnum):\n", flat(&e.name)),
        );
        if e.variants.is_empty() {
            push_fmt(&mut out, format_args!("{}pass\n\n", self.indent()));
            return out;
        }
        for (v, value) in e.variants.iter().zip(e.resolved_values()) {
            push_fmt(
                &mut out,
                format_args!("{}{} = {}\n", self.indent(), v.name, value),
            );
        }
        out.push('\n');
        out
    }

    fn emit_typedef(t: &Typedef) -> String {
        let mut out = String::new();
        push_fmt(
            &mut out,
            format_args!(
                "{} = {}\n\n",
                flat(&t.name),
                Self::type_to_python(&t.base_type)
            ),
        );
        out
    }

    fn emit_const(c: &Const) -> String {
        format!(
            "{} = {}\n\n",
            flat(&c.name),
            crate::codegen::const_literal::literal(c, crate::codegen::const_literal::Lang::Python)
        )
    }

    fn emit_union(&self, u: &Union, idx: &TypeIndex) -> Result<String> {
        let name = flat(&u.name);
        let labels = codec::label_values(idx, u).map_err(|e| {
            ParseError::new(
                ErrorKind::Other,
                Position::new(0, 0),
                format!("union {}: {e}", idl_name(&u.name)),
            )
        })?;
        let mut out = String::new();
        // Collect unique case types
        let mut types: Vec<String> = Vec::new();
        let mut seen: HashSet<String> = HashSet::new();
        for c in &u.cases {
            let t = Self::type_to_python(&c.field.field_type);
            if seen.insert(t.clone()) {
                types.push(t);
            }
        }
        let disc_ty = Self::type_to_python(&u.discriminator);
        let val_ann = if types.is_empty() {
            "object".to_string()
        } else if types.len() == 1 {
            types[0].clone()
        } else {
            format!("UnionType[{}]", types.join(", "))
        };
        push_fmt(&mut out, format_args!("@dataclass\nclass {}:\n", name));
        push_fmt(
            &mut out,
            format_args!(
                "{}\"\"\"Tagged union for {}\"\"\"\n",
                self.indent(),
                idl_name(&u.name)
            ),
        );
        // The default union (DDS-XTypes 1.3 Table 9, spec text line 2342):
        // the discriminator's default, and the default of the member it
        // selects, if any.
        let (disc_default, value_default) = codec::union_defaults(idx, u, &labels);
        push_fmt(
            &mut out,
            format_args!(
                "{}_discriminator: {} = {}\n",
                self.indent(),
                disc_ty,
                disc_default
            ),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}_value: Optional[{}]{}\n\n",
                self.indent(),
                val_ann,
                value_default
            ),
        );

        // One property per case: the value when the discriminator selects
        // that case, else None.
        let named: Vec<i64> = labels.iter().flatten().copied().collect();
        for (c, values) in u.cases.iter().zip(&labels) {
            let fname = python_ident(&c.field.name);
            let ann = Self::type_to_python(&c.field.field_type);
            push_fmt(
                &mut out,
                format_args!(
                    "{}@property\n{}def {}(self) -> Optional[{}]:\n",
                    self.indent(),
                    self.indent(),
                    fname,
                    ann
                ),
            );
            let is_default = c
                .labels
                .iter()
                .any(|l| matches!(l, crate::ast::UnionLabel::Default));
            let cond = if is_default {
                format!(
                    "{} not in {}",
                    "_hdds_disc(self._discriminator)",
                    codec::py_tuple(&named)
                )
            } else {
                format!(
                    "{} in {}",
                    "_hdds_disc(self._discriminator)",
                    codec::py_tuple(values)
                )
            };
            push_fmt(
                &mut out,
                format_args!(
                    "{}    return self._value if {} else None\n\n",
                    self.indent(),
                    cond
                ),
            );
        }

        // XCDR2 codec (DDS-XTypes 1.3 7.4.3.5.3)
        out.push_str(&codec::union_codec(idx, u, self.indent_level, &labels));
        out.push_str(&self.emit_union_key_methods(u, idx));

        Ok(out)
    }

    fn emit_union_key_methods(&self, u: &Union, idx: &TypeIndex) -> String {
        let mut out = String::new();
        let holder = crate::codegen::data_model::discriminator_holder(u, "_discriminator");
        let _ = writeln!(
            out,
            "{}HDDS_KEY_SUPPORTED = {}",
            self.indent(),
            if matches!(idx.key_holder(&holder), Ok(Some(_))) {
                "True"
            } else {
                "False"
            }
        );
        out.push_str(&key_hash::compute_key_method(&holder, idx, &self.indent()));
        out.push_str(&self.emit_has_key_method(&holder, idx));
        out.push('\n');
        out
    }

    #[allow(clippy::too_many_lines)]
    fn emit_bitset(&self, b: &Bitset) -> String {
        let mut out = String::new();
        let name = flat(&b.name);
        let indent = self.indent();

        // Class declaration
        push_fmt(&mut out, format_args!("@dataclass\nclass {}:\n", name));
        push_fmt(
            &mut out,
            format_args!(
                "{}\"\"\"Bitset {} - stores packed bit fields in a 64-bit integer.\"\"\"\n",
                indent, name
            ),
        );
        push_fmt(&mut out, format_args!("{}bits: int = 0\n\n", indent));

        // Compute field positions
        let mut next_pos: u32 = 0;
        for f in &b.fields {
            let mut pos = None;
            for ann in &f.annotations {
                if let Annotation::Position(p) = ann {
                    pos = Some(*p);
                    break;
                }
            }
            let start = pos.unwrap_or_else(|| {
                let p = next_pos;
                next_pos += f.width;
                p
            });
            let width = f.width;
            let mask = (1u64 << width) - 1;

            let field_id = python_ident(&f.name);
            // Getter property
            push_fmt(&mut out, format_args!("{}@property\n", indent));
            push_fmt(
                &mut out,
                format_args!("{}def {}(self) -> int:\n", indent, field_id),
            );
            push_fmt(
                &mut out,
                format_args!(
                    "{}    \"\"\"Get {} (width={}, position={}).\"\"\"\n",
                    indent, f.name, width, start
                ),
            );
            push_fmt(
                &mut out,
                format_args!(
                    "{}    return (self.bits >> {}) & {}\n\n",
                    indent, start, mask
                ),
            );

            // Setter property
            push_fmt(&mut out, format_args!("{}@{}.setter\n", indent, field_id));
            push_fmt(
                &mut out,
                format_args!("{}def {}(self, v: int) -> None:\n", indent, field_id),
            );
            push_fmt(
                &mut out,
                format_args!("{}    mask = {} << {}\n", indent, mask, start),
            );
            push_fmt(
                &mut out,
                format_args!(
                    "{}    self.bits = (self.bits & ~mask) | ((v & {}) << {})\n\n",
                    indent, mask, start
                ),
            );
        }

        // CDR2 encode method
        push_fmt(
            &mut out,
            format_args!("{}def encode_cdr2_le(self) -> bytes:\n", indent),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}    \"\"\"Encode to CDR2 little-endian format (8 bytes).\"\"\"\n",
                indent
            ),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}    return struct.pack('<Q', self.bits & 0xFFFFFFFFFFFFFFFF)\n\n",
                indent
            ),
        );

        // CDR2 decode method
        push_fmt(&mut out, format_args!("{}@classmethod\n", indent));
        push_fmt(
            &mut out,
            format_args!(
                "{}def decode_cdr2_le(cls, data: bytes) -> Tuple['{}', int]:\n",
                indent, name
            ),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}    \"\"\"Decode from CDR2 little-endian format. Returns (instance, bytes_read).\"\"\"\n",
                indent
            ),
        );
        push_fmt(&mut out, format_args!("{}    # Align to 8 bytes\n", indent));
        push_fmt(
            &mut out,
            format_args!("{}    bits, = struct.unpack_from('<Q', data, 0)\n", indent),
        );
        push_fmt(
            &mut out,
            format_args!("{}    return cls(bits=bits), 8\n\n", indent),
        );

        out
    }

    #[allow(clippy::too_many_lines)]
    fn emit_bitmask(&self, m: &Bitmask) -> String {
        let mut out = String::new();
        let name = flat(&m.name);
        let indent = self.indent();
        let width = super::data_model::bitmask_width(m.annotations.iter().find_map(|a| match a {
            Annotation::BitBound(n) => Some(*n),
            _ => None,
        }));
        let mask: u64 = if width >= 8 {
            u64::MAX
        } else {
            (1u64 << (8 * width)) - 1
        };

        // Generate a class that wraps an int with flag constants
        push_fmt(&mut out, format_args!("class {}(int):\n", name));
        push_fmt(
            &mut out,
            format_args!(
                "{}\"\"\"Bitmask {} - integer with named flag constants.\"\"\"\n\n",
                indent, name
            ),
        );

        // Compute flag positions and emit constants
        let mut next_pos: u32 = 0;
        for flag in &m.flags {
            let mut pos = None;
            for ann in &flag.annotations {
                if let Annotation::Position(p) = ann {
                    pos = Some(*p);
                    break;
                }
            }
            let bit = pos.unwrap_or_else(|| {
                let p = next_pos;
                next_pos += 1;
                p
            });
            push_fmt(
                &mut out,
                format_args!("{}{} = 1 << {}\n", indent, flag.name.to_uppercase(), bit),
            );
        }
        out.push('\n');

        // Constructor to ensure proper type
        push_fmt(
            &mut out,
            format_args!("{}def __new__(cls, value: int = 0):\n", indent),
        );
        push_fmt(
            &mut out,
            format_args!("{}    return super().__new__(cls, value)\n\n", indent),
        );

        // Bitwise operations that return the same type
        push_fmt(
            &mut out,
            format_args!("{}def __or__(self, other: int) -> '{}':\n", indent, name),
        );
        push_fmt(
            &mut out,
            format_args!("{}    return {}(int.__or__(self, other))\n\n", indent, name),
        );

        push_fmt(
            &mut out,
            format_args!("{}def __and__(self, other: int) -> '{}':\n", indent, name),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}    return {}(int.__and__(self, other))\n\n",
                indent, name
            ),
        );

        push_fmt(
            &mut out,
            format_args!("{}def __xor__(self, other: int) -> '{}':\n", indent, name),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}    return {}(int.__xor__(self, other))\n\n",
                indent, name
            ),
        );

        push_fmt(
            &mut out,
            format_args!("{}def __invert__(self) -> '{}':\n", indent, name),
        );
        push_fmt(
            &mut out,
            format_args!(
                "{}    return {}(int.__invert__(self) & {:#X})\n\n",
                indent, name, mask
            ),
        );

        // XCDR2: the value alone at its @bit_bound width (7.3.1.2.1.7)
        out.push_str(&codec::bitmask_codec(&name, width, &indent));

        out
    }

    fn emit_definitions(
        &self,
        defs: &[Definition],
        idx: &TypeIndex,
        out: &mut String,
    ) -> Result<()> {
        for def in defs {
            match def {
                Definition::Module(module) => {
                    self.emit_definitions(&module.definitions, idx, out)?;
                }
                Definition::Struct(s) => out.push_str(&self.emit_struct(s, idx)),
                Definition::Enum(e) => out.push_str(&self.emit_enum(e)),
                Definition::Typedef(t) => out.push_str(&Self::emit_typedef(t)),
                Definition::Const(c) => out.push_str(&Self::emit_const(c)),
                Definition::Union(u) => out.push_str(&self.emit_union(u, idx)?),
                Definition::Bitset(b) => out.push_str(&self.emit_bitset(b)),
                Definition::Bitmask(m) => out.push_str(&self.emit_bitmask(m)),
                Definition::AnnotationDecl(_) | Definition::ForwardDecl(_) => {}
                #[cfg(feature = "interfaces")]
                Definition::Interface(_) => {}
                #[cfg(feature = "interfaces")]
                Definition::Exception(_) => {}
            }
        }
        Ok(())
    }

    /// One class per IDL module, nested as the modules are, whose
    /// attributes are the types the module declares (`a.b.T` is the class
    /// `a_b_T`).
    fn emit_namespaces(tree: &ModuleTree, path: &str, ind: usize, out: &mut String) {
        for (name, sub) in &tree.modules {
            let full = if path.is_empty() {
                name.clone()
            } else {
                format!("{path}::{name}")
            };
            let pad = "    ".repeat(ind);
            if ind == 0 && RUNTIME_NAMES.contains(&name.as_str()) {
                // The generated code needs that global: the module's types
                // keep their flat names only.
                push_fmt(
                    out,
                    format_args!(
                        "# IDL module {full}: no view, `{name}` is used by this module.\n"
                    ),
                );
                continue;
            }
            push_fmt(out, format_args!("{pad}class {name}:\n"));
            push_fmt(
                out,
                format_args!("{pad}    \"\"\"IDL module {full} (generated by hddsgen).\"\"\"\n"),
            );
            for (simple, key, _) in &sub.items {
                push_fmt(out, format_args!("{pad}    {simple} = {}\n", flat(key)));
            }
            Self::emit_namespaces(sub, &full, ind + 1, out);
            if ind == 0 {
                out.push('\n');
            }
        }
    }

    /// The module views, then the unqualified name of each type declared in
    /// a module when no other declaration of the file has that name (the
    /// names of earlier releases, which flattened modules).
    fn emit_module_views(decls: &[scope::Decl], out: &mut String) {
        let tree = ModuleTree::new(decls);
        if tree.modules.is_empty() {
            return;
        }
        out.push_str("\n# IDL modules: a type `a::b::T` is the class `a_b_T`, also `a.b.T`.\n");
        Self::emit_namespaces(&tree, "", 0, out);
        let mut bound: HashSet<String> = decls.iter().map(|d| flat(&d.key)).collect();
        bound.extend(tree.modules.iter().map(|(n, _)| n.clone()));
        bound.extend(RUNTIME_NAMES.iter().map(ToString::to_string));
        let mut count: HashMap<&str, usize> = HashMap::new();
        for d in decls {
            *count.entry(scope::simple(&d.key)).or_default() += 1;
        }
        let mut aliases = String::new();
        for d in decls {
            let simple = scope::simple(&d.key);
            if simple != d.key && count.get(simple) == Some(&1) && !bound.contains(simple) {
                push_fmt(&mut aliases, format_args!("{simple} = {}\n", flat(&d.key)));
            }
        }
        if !aliases.is_empty() {
            out.push_str("# Unqualified names, for the types whose name is unique in the file.\n");
            out.push_str(&aliases);
        }
    }
}

impl Default for PythonGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl CodeGenerator for PythonGenerator {
    fn generate(&self, ast: &IdlFile) -> Result<String> {
        // Every name carries its module path (`scope`).
        let scoped = scope::qualify(ast);
        scope::check_flat_names(&scoped.decls)
            .map_err(|e| ParseError::new(ErrorKind::DuplicateDefinition, Position::new(0, 0), e))?;
        let ast = &scoped.ast;
        let mut out = String::new();
        out.push_str(&Self::emit_header());

        let idx = TypeIndex::new(ast);
        out.push_str(codec::RUNTIME);
        if key_hash::module_needs_writer(ast, &idx) {
            out.push_str(key_hash::WRITER_CLASS);
        }
        self.emit_definitions(&ast.definitions, &idx, &mut out)?;
        Self::emit_module_views(&scoped.decls, &mut out);
        Ok(out)
    }
}

