//! `PubSubType` class generation for C++
//!
//! Generates `TypeSupport` classes compatible with DDS implementations.

use crate::ast::Struct;
use crate::codegen::cpp::index::DefinitionIndex;
use crate::codegen::keywords::cpp_ident;
use crate::types::{IdlType, PrimitiveType};
use std::fmt::Write;

/// C++ expression for accessing field `fname` on `typed`.
///
/// Plain mode uses direct public member access. In fastdds-compat mode fields
/// are private with accessor methods: the call expression works for reads, and
/// for non-primitive fields the mutable-ref overload makes the same expression
/// usable as an lvalue (primitive non-optional fields only expose a by-value
/// getter plus a setter, so assignments to them must go through the setter).
fn field_access(fname: &str, fastdds_compat: bool) -> String {
    if fastdds_compat {
        format!("typed->{}()", cpp_ident(fname))
    } else {
        format!("typed->{}", cpp_ident(fname))
    }
}

fn generate_base_methods(out: &mut String, type_name: &str, idl_name: &str, class_name: &str) {
    let _ = writeln!(out, "// PubSubType for {type_name}");
    out.push_str("// Generated by hddsgen\n\n");

    let _ = writeln!(out, "/// TypeSupport class for {type_name}");
    out.push_str("/// Provides DDS-compatible serialization/deserialization interface\n");
    let _ = writeln!(out, "class {class_name} {{");
    out.push_str("public:\n");
    let _ = writeln!(out, "    using type = {type_name};\n");
    out.push_str("    /// DDS type name: the IDL qualified name, as hdds_type_name\n");
    let _ = writeln!(
        out,
        "    static constexpr const char* type_name() noexcept {{ return \"{idl_name}\"; }}\n"
    );

    out.push_str("    /// Serialize data to CDR2 little-endian format\n");
    let _ = writeln!(
        out,
        "    /// @param data Pointer to the {type_name} to serialize"
    );
    out.push_str("    /// @param buffer Output buffer\n");
    out.push_str("    /// @param buffer_size Size of output buffer\n");
    out.push_str("    /// @return Number of bytes written, or -1 on error\n");
    out.push_str(
        "    static int serialize(const void* data, std::uint8_t* buffer, std::size_t buffer_size) noexcept {\n",
    );
    out.push_str("        if (!data || !buffer) return -1;\n");
    let _ = writeln!(
        out,
        "        const auto* typed = static_cast<const {type_name}*>(data);"
    );
    out.push_str("        return typed->encode_cdr2_le(buffer, buffer_size);\n");
    out.push_str("    }\n\n");

    out.push_str("    /// Deserialize data from CDR2 little-endian format\n");
    out.push_str("    /// @param buffer Input buffer containing CDR2 data\n");
    out.push_str("    /// @param buffer_size Size of input buffer\n");
    let _ = writeln!(out, "    /// @param data Pointer to {type_name} to fill");
    out.push_str("    /// @return Number of bytes read, or -1 on error\n");
    out.push_str(
        "    static int deserialize(const std::uint8_t* buffer, std::size_t buffer_size, void* data) noexcept {\n",
    );
    out.push_str("        if (!buffer || !data) return -1;\n");
    let _ = writeln!(
        out,
        "        auto* typed = static_cast<{type_name}*>(data);"
    );
    out.push_str("        return typed->decode_cdr2_le(buffer, buffer_size);\n");
    out.push_str("    }\n\n");

    out.push_str("    /// Calculate serialized size of data\n");
    let _ = writeln!(out, "    /// @param data Pointer to the {type_name}");
    out.push_str("    /// @return Serialized size in bytes, or 0 on error\n");
    out.push_str("    static std::size_t calculate_serialized_size(const void* data) noexcept {\n");
    out.push_str("        if (!data) return 0;\n");
    let _ = writeln!(
        out,
        "        const auto* typed = static_cast<const {type_name}*>(data);"
    );
    out.push_str("        // Fast path: stack buffer for typical types\n");
    out.push_str("        std::uint8_t stack_buf[16384];\n");
    out.push_str("        int size = typed->encode_cdr2_le(stack_buf, sizeof(stack_buf));\n");
    out.push_str("        if (size > 0) return static_cast<std::size_t>(size);\n");
    out.push_str("        // Heap fallback for large types (up to 16 MB)\n");
    out.push_str("        for (std::size_t cap = 65536; cap <= 16777216; cap *= 4) {\n");
    out.push_str("            auto* p = static_cast<std::uint8_t*>(std::malloc(cap));\n");
    out.push_str("            if (!p) return 0;\n");
    out.push_str("            size = typed->encode_cdr2_le(p, cap);\n");
    out.push_str("            std::free(p);\n");
    out.push_str("            if (size > 0) return static_cast<std::size_t>(size);\n");
    out.push_str("        }\n");
    out.push_str("        return 0;\n");
    out.push_str("    }\n\n");

    let _ = writeln!(out, "    /// Create a new instance of {type_name}");
    let _ = writeln!(
        out,
        "    /// @return Pointer to newly allocated {type_name}, or nullptr on failure"
    );
    out.push_str("    static void* create_data() noexcept {\n");
    let _ = writeln!(out, "        return new (std::nothrow) {type_name}();");
    out.push_str("    }\n\n");

    let _ = writeln!(out, "    /// Delete an instance of {type_name}");
    let _ = writeln!(out, "    /// @param data Pointer to {type_name} to delete");
    out.push_str("    static void delete_data(void* data) noexcept {\n");
    let _ = writeln!(out, "        delete static_cast<{type_name}*>(data);");
    out.push_str("    }\n\n");
}

/// Generates a `PubSubType` header for a struct
#[allow(clippy::too_many_lines)] // Full class template generation
pub fn generate_pubsub_type_header(
    s: &Struct,
    idx: &DefinitionIndex,
    fastdds_compat: bool,
    idl_name: &str,
) -> String {
    let type_name = &s.name;
    let class_name = format!("{type_name}PubSubType");

    let mut out = String::new();
    generate_base_methods(&mut out, type_name, idl_name, &class_name);

    // compute_key / has_key: instance KeyHash, RTPS 2.5 9.6.4.8
    out.push_str(&super::super::key_hash::pubsub_key_methods(
        s,
        idx,
        fastdds_compat,
    ));

    // Type properties
    out.push_str("    /// Check if type has bounded size\n");
    let _ = writeln!(
        out,
        "    static constexpr bool is_bounded() noexcept {{ return {}; }}\n",
        is_type_bounded(s)
    );
    out.push_str("    /// Check if type is plain (no pointers/dynamic allocation)\n");
    let _ = writeln!(
        out,
        "    static constexpr bool is_plain() noexcept {{ return {}; }}",
        is_type_plain(s)
    );

    // populate_from_json method
    out.push_str("\n    /// Populate struct fields from a flat JSON string (key-value format)\n");
    out.push_str("    /// @param data Pointer to struct to populate\n");
    out.push_str("    /// @param json_str JSON string in format: {\"key\": value, ...}\n");
    out.push_str("    /// @return true on success, false on parse error\n");
    out.push_str(
        "    static bool populate_from_json(void* data, const char* json_str) noexcept {\n",
    );
    let _ = writeln!(out, "        auto* typed = static_cast<type*>(data);");
    out.push_str("        if (!typed || !json_str) return false;\n");
    out.push_str("        const char* p = json_str;\n");
    out.push_str("        // Skip to opening brace\n");
    out.push_str("        while (*p && *p != '{') p++;\n");
    out.push_str("        if (*p != '{') return false;\n");
    out.push_str("        p++;\n");
    out.push_str("        // Parse key-value pairs\n");
    out.push_str("        while (*p && *p != '}') {\n");
    out.push_str("            // Skip whitespace, commas\n");
    out.push_str("            while (*p && (*p == ' ' || *p == '\\t' || *p == '\\n' || *p == '\\r' || *p == ',')) p++;\n");
    out.push_str("            if (*p == '}' || *p == '\\0') break;\n");
    out.push_str("            // Parse string key\n");
    out.push_str("            if (*p != '\"') { p++; continue; }\n");
    out.push_str("            p++; // skip opening quote\n");
    out.push_str("            const char* ks = p;\n");
    out.push_str(
        "            while (*p && *p != '\"') { if (*p == '\\\\' && *(p+1)) p++; p++; }\n",
    );
    out.push_str("            if (*p != '\"') break;\n");
    // Unused when the structure has no member (an empty structure).
    out.push_str("            [[maybe_unused]] size_t klen = static_cast<size_t>(p - ks);\n");
    out.push_str("            [[maybe_unused]] const char* key = ks;\n");
    out.push_str("            p++; // skip closing quote\n");
    out.push_str("            // Skip colon\n");
    out.push_str("            while (*p && *p != ':') p++;\n");
    out.push_str("            if (*p == ':') p++;\n");
    out.push_str("            // Skip whitespace before value\n");
    out.push_str(
        "            while (*p && (*p == ' ' || *p == '\\t' || *p == '\\n' || *p == '\\r')) p++;\n",
    );
    out.push_str("            if (!*p) break;\n");
    out.push('\n');
    out.push_str("            // Save value start position\n");
    out.push_str("            [[maybe_unused]] const char* val_start = p;\n");
    out.push_str("            // Advance past value to find end\n");
    out.push_str("            if (*p == '\"') {\n");
    out.push_str("                p++; // skip opening quote\n");
    out.push_str("                while (*p && *p != '\"') {\n");
    out.push_str("                    if (*p == '\\\\' && *(p+1)) p++; // skip escaped char\n");
    out.push_str("                    p++;\n");
    out.push_str("                }\n");
    out.push_str("                if (*p == '\"') p++;\n");
    out.push_str("            } else if (*p == '[') {\n");
    out.push_str("                // Array: skip to matching ]\n");
    out.push_str("                int depth = 1;\n");
    out.push_str("                p++;\n");
    out.push_str("                while (*p && depth > 0) {\n");
    out.push_str("                    if (*p == '[') depth++;\n");
    out.push_str("                    else if (*p == ']') depth--;\n");
    out.push_str("                    else if (*p == '\"') {\n");
    out.push_str("                        p++;\n");
    out.push_str("                        while (*p && *p != '\"') { if (*p == '\\\\' && *(p+1)) p++; p++; }\n");
    out.push_str("                    }\n");
    out.push_str("                    p++;\n");
    out.push_str("                }\n");
    out.push_str("            } else if (*p == '{') {\n");
    out.push_str("                // Nested object: skip to matching }\n");
    out.push_str("                int depth = 1;\n");
    out.push_str("                p++;\n");
    out.push_str("                while (*p && depth > 0) {\n");
    out.push_str("                    if (*p == '{') depth++;\n");
    out.push_str("                    else if (*p == '}') depth--;\n");
    out.push_str("                    else if (*p == '\"') {\n");
    out.push_str("                        p++;\n");
    out.push_str("                        while (*p && *p != '\"') { if (*p == '\\\\' && *(p+1)) p++; p++; }\n");
    out.push_str("                    }\n");
    out.push_str("                    p++;\n");
    out.push_str("                }\n");
    out.push_str("            } else {\n");
    out.push_str("                // Number or keyword: advance past alphanumeric, ., -, +, x\n");
    out.push_str("                while (*p && *p != ',' && *p != '}' && *p != ' ' && *p != '\\t' && *p != '\\n' && *p != '\\r') p++;\n");
    out.push_str("            }\n");
    out.push_str("            const char* val_end = p;\n");
    out.push('\n');
    out.push_str("            // Match key to field and set value\n");
    out.push_str(
        "            [[maybe_unused]] size_t vlen = static_cast<size_t>(val_end - val_start);\n",
    );

    // Generate field match branches
    for field in &s.fields {
        let fname = &field.name;
        let fnamelen = fname.len();
        let _ = writeln!(out, "            if (klen == {fnamelen} && std::memcmp(key, \"{fname}\", {fnamelen}) == 0) {{");
        generate_field_setter(&mut out, field, 3, idx, fastdds_compat);
        out.push_str("                continue;\n");
        out.push_str("            }\n");
    }

    out.push_str("        }\n");
    out.push_str("        return true;\n");
    out.push_str("    }\n");

    // Private helpers
    out.push_str("\nprivate:\n");
    out.push_str(JSON_UNESCAPE_HELPER);

    // Close class
    out.push_str("};\n\n");

    out
}

/// C++ implementation of a JSON string unescape helper, emitted as a private
/// static method in each `PubSubType` class. Handles standard JSON escape sequences
/// including \\uXXXX with UTF-8 output; a surrogate pair is combined into one code point.
const JSON_UNESCAPE_HELPER: &str = r#"    /// Unescape a JSON string value. Supports \n, \r, \t, \b, \f, \\, \/, \" and \uXXXX.
    /// Lone or mismatched surrogates and invalid codepoints emit U+FFFD replacement character.
    static std::string json_unescape(const char* s, std::size_t len) noexcept {
        std::string out;
        out.reserve(len);
        for (std::size_t i = 0; i < len; ++i) {
            if (s[i] != '\\') {
                out += s[i];
                continue;
            }
            if (++i >= len) break;
            switch (s[i]) {
                case '"': out += '"'; break;
                case '\\': out += '\\'; break;
                case '/': out += '/'; break;
                case 'n': out += '\n'; break;
                case 'r': out += '\r'; break;
                case 't': out += '\t'; break;
                case 'b': out += '\b'; break;
                case 'f': out += '\f'; break;
                case 'u': {
                    if (i + 4 >= len) break;
                    char hex[5] = {s[i+1], s[i+2], s[i+3], s[i+4], '\0'};
                    char* end = nullptr;
                    unsigned long cp = std::strtoul(hex, &end, 16);
                    if (end != hex + 4) break;
                    i += 4;
                    if (cp >= 0xD800 && cp <= 0xDBFF && i + 6 < len && s[i+1] == '\\' && s[i+2] == 'u') {
                        // A high surrogate followed by \u and a low surrogate is one
                        // code point (RFC 8259 section 7).
                        char lo_hex[5] = {s[i+3], s[i+4], s[i+5], s[i+6], '\0'};
                        char* lo_end = nullptr;
                        unsigned long lo = std::strtoul(lo_hex, &lo_end, 16);
                        if (lo_end == lo_hex + 4 && lo >= 0xDC00 && lo <= 0xDFFF) {
                            cp = 0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00);
                            i += 6;
                        }
                    }
                    if (cp < 0x80) {
                        out += static_cast<char>(cp);
                    } else if (cp < 0x800) {
                        out += static_cast<char>(static_cast<unsigned char>(0xC0 | (cp >> 6)));
                        out += static_cast<char>(static_cast<unsigned char>(0x80 | (cp & 0x3F)));
                    } else if (cp < 0x10000) {
                        if (cp >= 0xD800 && cp <= 0xDFFF) {
                            out += "\xEF\xBF\xBD";
                        } else {
                            out += static_cast<char>(static_cast<unsigned char>(0xE0 | (cp >> 12)));
                            out += static_cast<char>(static_cast<unsigned char>(0x80 | ((cp >> 6) & 0x3F)));
                            out += static_cast<char>(static_cast<unsigned char>(0x80 | (cp & 0x3F)));
                        }
                    } else if (cp <= 0x10FFFF) {
                        out += static_cast<char>(static_cast<unsigned char>(0xF0 | (cp >> 18)));
                        out += static_cast<char>(static_cast<unsigned char>(0x80 | ((cp >> 12) & 0x3F)));
                        out += static_cast<char>(static_cast<unsigned char>(0x80 | ((cp >> 6) & 0x3F)));
                        out += static_cast<char>(static_cast<unsigned char>(0x80 | (cp & 0x3F)));
                    }
                    break;
                }
                default: out += s[i]; break;
            }
        }
        return out;
    }

    /// Convert UTF-8 string to wstring (wchar_t). On Linux (wchar_t = UTF-32) and
    /// Windows (wchar_t = UTF-16) this produces correct codepoints, unlike the
    /// zero-extend-per-byte that std::wstring(char_iter,char_iter) does.
    static std::wstring utf8_to_wstring(const std::string& utf8) noexcept {
        std::wstring out;
        out.reserve(utf8.size());
        for (std::size_t i = 0; i < utf8.size(); ) {
            unsigned char c = static_cast<unsigned char>(utf8[i]);
            unsigned long cp;
            if (c < 0x80) {
                cp = c; i += 1;
            } else if ((c & 0xE0) == 0xC0 && i + 1 < utf8.size()) {
                cp = static_cast<unsigned long>(c & 0x1F) << 6
                    | static_cast<unsigned long>(utf8[i + 1] & 0x3F);
                i += 2;
            } else if ((c & 0xF0) == 0xE0 && i + 2 < utf8.size()) {
                cp = static_cast<unsigned long>(c & 0x0F) << 12
                    | static_cast<unsigned long>(utf8[i + 1] & 0x3F) << 6
                    | static_cast<unsigned long>(utf8[i + 2] & 0x3F);
                i += 3;
            } else if ((c & 0xF8) == 0xF0 && i + 3 < utf8.size()) {
                cp = static_cast<unsigned long>(c & 0x07) << 18
                    | static_cast<unsigned long>(utf8[i + 1] & 0x3F) << 12
                    | static_cast<unsigned long>(utf8[i + 2] & 0x3F) << 6
                    | static_cast<unsigned long>(utf8[i + 3] & 0x3F);
                i += 4;
            } else {
                cp = 0xFFFD; i += 1;
            }
            out += static_cast<wchar_t>(cp);
        }
        return out;
    }

    /// Store a UTF-8 value in a bounded string (`string<N>` / `wstring<N>`,
    /// a `std::array` of `char` / `wchar_t`, NUL-filled after the value).
    /// False when the value has more than N characters.
    template <class A>
    static bool assign_bounded(A& a, const std::string& utf8) noexcept {
        using C = typename A::value_type;
        a.fill(C(0));
        if constexpr (sizeof(C) == 1) {
            if (utf8.size() > a.size()) return false;
            for (std::size_t i = 0; i < utf8.size(); ++i) a[i] = static_cast<C>(utf8[i]);
        } else {
            std::wstring w = utf8_to_wstring(utf8);
            if (w.size() > a.size()) return false;
            for (std::size_t i = 0; i < w.size(); ++i) a[i] = static_cast<C>(w[i]);
        }
        return true;
    }
"#;

/// Generate C++ code to populate an array or sequence field from a JSON array `[...]`.
/// `access` is the C++ expression for the container (see [`field_access`]),
/// `ind` is the base indent string, `is_sequence` controls `push_back` vs index assignment.
#[allow(clippy::too_many_lines)] // Type-directed C++ emission table
fn emit_array_field_population(
    out: &mut String,
    fname: &str,
    access: &str,
    inner: &IdlType,
    idx: &DefinitionIndex,
    ind: &str,
    is_sequence: bool,
) {
    let _ = writeln!(out, "{ind}// Array/sequence field \"{fname}\"");
    let _ = writeln!(
        out,
        "{ind}if (val_start[0] == '[' && val_end > val_start) {{"
    );
    let _ = writeln!(out, "{ind}    const char* ep = val_start + 1;");
    if is_sequence {
        let _ = writeln!(out, "{ind}    {access}.clear();");
    } else {
        let _ = writeln!(out, "{ind}    std::size_t elem_idx = 0;");
    }
    let _ = writeln!(out, "{ind}    while (ep < val_end && *ep != ']') {{");
    // Skip whitespace/commas
    let _ = writeln!(
        out,
        "{ind}        while (ep < val_end && (*ep == ' ' || *ep == '\\t' || *ep == '\\n' || *ep == '\\r' || *ep == ',')) ep++;"
    );
    let _ = writeln!(out, "{ind}        if (ep >= val_end || *ep == ']') break;");
    // Find element end
    let _ = writeln!(out, "{ind}        const char* elem_start = ep;");
    let _ = writeln!(out, "{ind}        if (*ep == '\"') {{");
    let _ = writeln!(out, "{ind}            ep++;");
    let _ = writeln!(
        out,
        "{ind}            while (ep < val_end && *ep != '\"') {{ if (*ep == '\\\\' && *(ep+1)) ep++; ep++; }}"
    );
    let _ = writeln!(
        out,
        "{ind}            if (ep < val_end && *ep == '\"') ep++;"
    );
    let _ = writeln!(out, "{ind}        }} else if (*ep == '{{') {{");
    let _ = writeln!(out, "{ind}            int depth = 1; ep++;");
    let _ = writeln!(
        out,
        "{ind}            while (ep < val_end && depth > 0) {{ if (*ep == '{{') depth++; else if (*ep == '}}') depth--; ep++; }}"
    );
    let _ = writeln!(out, "{ind}        }} else if (*ep == '[') {{");
    let _ = writeln!(out, "{ind}            int depth = 1; ep++;");
    let _ = writeln!(
        out,
        "{ind}            while (ep < val_end && depth > 0) {{ if (*ep == '[') depth++; else if (*ep == ']') depth--; ep++; }}"
    );
    let _ = writeln!(out, "{ind}        }} else {{");
    let _ = writeln!(
        out,
        "{ind}            while (ep < val_end && *ep != ',' && *ep != ']' && *ep != ' ' && *ep != '\\t' && *ep != '\\n' && *ep != '\\r') ep++;"
    );
    let _ = writeln!(out, "{ind}        }}");
    let _ = writeln!(out, "{ind}        if (ep == elem_start) break;");

    // Bounds guard for fixed-size arrays (prevent OOB if JSON has more elements)
    if !is_sequence {
        let _ = writeln!(out, "{ind}        if (elem_idx >= {access}.size()) break;");
    }

    // Generate the "assign or push" expression based on sequence vs array.
    // `open` is the LHS assignment, `close` is the suffix to end the statement.
    let (open, close) = if is_sequence {
        (format!("{ind}        {access}.push_back("), ");")
    } else {
        (format!("{ind}        {access}[elem_idx++] = "), ";")
    };

    // Type-specific element value generation (value expression must NOT include trailing `);` -
    // those come from `open` / `close` so the paren count is correct for both array and sequence).
    match inner {
        IdlType::BoundedString { .. } => {
            let _ = writeln!(
                out,
                "{ind}        if (*elem_start == '\"' && ep >= elem_start + 2) {{"
            );
            let _ = writeln!(
                out,
                "{ind}            std::string tmp = json_unescape(elem_start + 1, static_cast<std::size_t>(ep - elem_start - 2));"
            );
            if is_sequence {
                let _ = writeln!(out, "{ind}            {access}.emplace_back();");
                let _ = writeln!(
                    out,
                    "{ind}            if (!assign_bounded({access}.back(), tmp)) return false;"
                );
            } else {
                let _ = writeln!(
                    out,
                    "{ind}            if (!assign_bounded({access}[elem_idx++], tmp)) return false;"
                );
            }
            let _ = writeln!(out, "{ind}        }}");
        }
        IdlType::Primitive(pt) => match pt {
            PrimitiveType::Boolean => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<bool>(elem_start[0] == 't' || elem_start[0] == 'T'){close}",
                );
            }
            PrimitiveType::Char
            | PrimitiveType::WChar
            | PrimitiveType::Octet
            | PrimitiveType::UInt8 => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<uint8_t>(std::strtoul(elem_start, nullptr, 10) & 0xFF){close}",
                );
            }
            PrimitiveType::Int8 => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<int8_t>(std::strtol(elem_start, nullptr, 10)){close}",
                );
            }
            PrimitiveType::UInt16 | PrimitiveType::UnsignedShort => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<uint16_t>(std::strtoul(elem_start, nullptr, 10)){close}",
                );
            }
            PrimitiveType::Int16 | PrimitiveType::Short => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<int16_t>(std::strtol(elem_start, nullptr, 10)){close}",
                );
            }
            PrimitiveType::UInt32 | PrimitiveType::UnsignedLong => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<uint32_t>(std::strtoul(elem_start, nullptr, 10)){close}",
                );
            }
            PrimitiveType::Int32 | PrimitiveType::Long => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<int32_t>(std::strtol(elem_start, nullptr, 10)){close}",
                );
            }
            PrimitiveType::UInt64 | PrimitiveType::UnsignedLongLong => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<uint64_t>(std::strtoull(elem_start, nullptr, 10)){close}",
                );
            }
            PrimitiveType::Int64 | PrimitiveType::LongLong => {
                let _ = writeln!(
                    out,
                    "{open}static_cast<int64_t>(std::strtoll(elem_start, nullptr, 10)){close}",
                );
            }
            PrimitiveType::Float => {
                let _ = writeln!(out, "{open}std::strtof(elem_start, nullptr){close}",);
            }
            PrimitiveType::Double => {
                let _ = writeln!(out, "{open}std::strtod(elem_start, nullptr){close}",);
            }
            PrimitiveType::LongDouble | PrimitiveType::Fixed { .. } => {
                let _ = writeln!(out, "{open}std::strtold(elem_start, nullptr){close}",);
            }
            PrimitiveType::String => {
                let _ = writeln!(
                    out,
                    "{ind}        if (*elem_start == '\"' && ep > elem_start + 2) {{"
                );
                let _ = writeln!(
                    out,
                    "{ind}            std::size_t content_len = static_cast<std::size_t>(ep - elem_start - 2);"
                );
                if is_sequence {
                    let _ = writeln!(
                        out,
                        "{ind}            {access}.push_back(json_unescape(elem_start + 1, content_len));"
                    );
                } else {
                    let _ = writeln!(
                        out,
                        "{ind}            {access}[elem_idx++] = json_unescape(elem_start + 1, content_len);"
                    );
                }
                let _ = writeln!(out, "{ind}        }}");
            }
            PrimitiveType::WString => {
                let _ = writeln!(
                    out,
                    "{ind}        if (*elem_start == '\"' && ep > elem_start + 2) {{"
                );
                let _ = writeln!(
                    out,
                    "{ind}            std::size_t content_len = static_cast<std::size_t>(ep - elem_start - 2);"
                );
                let _ = writeln!(
                    out,
                    "{ind}            std::string tmp = json_unescape(elem_start + 1, content_len);"
                );
                if is_sequence {
                    let _ = writeln!(
                        out,
                        "{ind}            {access}.push_back(utf8_to_wstring(tmp));"
                    );
                } else {
                    let _ = writeln!(
                        out,
                        "{ind}            {access}[elem_idx++].assign(utf8_to_wstring(tmp));"
                    );
                }
                let _ = writeln!(out, "{ind}        }}");
            }
            PrimitiveType::Void => {
                let _ = writeln!(out, "{ind}        // void: skipped");
            }
        },
        IdlType::Named(named_type) => {
            if let Some(variants) = idx.enum_variants(named_type) {
                // Enum element: match string variant names
                let _ = writeln!(
                    out,
                    "{ind}        if (*elem_start == '\"' && ep > elem_start + 2) {{"
                );
                let _ = writeln!(out, "{ind}            const char* vs = elem_start + 1;");
                let _ = writeln!(
                    out,
                    "{ind}            std::size_t vl = static_cast<std::size_t>(ep - elem_start - 2);"
                );
                for (i, variant) in variants.iter().enumerate() {
                    let vname = variant;
                    let vlen = vname.len();
                    let kw = if i == 0 { "if" } else { "else if" };
                    let _ = writeln!(
                        out,
                        "{ind}            {kw} (vl == {vlen} && std::memcmp(vs, \"{vname}\", {vlen}) == 0) {{"
                    );
                    if is_sequence {
                        let _ = writeln!(
                            out,
                            "{ind}                {access}.push_back({named_type}::{vname});"
                        );
                    } else {
                        let _ = writeln!(
                            out,
                            "{ind}                {access}[elem_idx++] = {named_type}::{vname};"
                        );
                    }
                    let _ = writeln!(out, "{ind}            }}");
                }
                let _ = writeln!(out, "{ind}        }}");
            } else if idx.is_struct(named_type) {
                // Struct element: extract sub-object and call populate_from_json
                let pubsub_type = format!("{named_type}PubSubType");
                let _ = writeln!(
                    out,
                    "{ind}        if (*elem_start == '{{' && ep > elem_start) {{"
                );
                let _ = writeln!(
                    out,
                    "{ind}            std::string sub(elem_start, static_cast<std::size_t>(ep - elem_start));"
                );
                if is_sequence {
                    let _ = writeln!(out, "{ind}            {access}.emplace_back();");
                    let _ = writeln!(
                        out,
                        "{ind}            {pubsub_type}::populate_from_json(&{access}.back(), sub.c_str());"
                    );
                } else {
                    let _ = writeln!(
                        out,
                        "{ind}            {pubsub_type}::populate_from_json(&{access}[elem_idx++], sub.c_str());"
                    );
                }
                let _ = writeln!(out, "{ind}        }}");
            } else {
                let _ = writeln!(
                    out,
                    "{ind}        // Unsupported element type \"{named_type}\": skipped"
                );
            }
        }
        IdlType::Sequence { .. } | IdlType::Array { .. } => {
            let _ = writeln!(
                out,
                "{ind}        // Nested array/sequence: not yet supported"
            );
        }
        IdlType::Map { key, value, .. } => {
            if is_sequence {
                let _ = writeln!(out, "{ind}        {access}.emplace_back();");
                let target = format!("{access}.back()");
                emit_map_field_population(
                    out,
                    fname,
                    access,
                    "elem_start",
                    "ep",
                    &target,
                    key,
                    value,
                    idx,
                    ind,
                );
            } else {
                let target = format!("{access}[elem_idx]");
                emit_map_field_population(
                    out,
                    fname,
                    access,
                    "elem_start",
                    "ep",
                    &target,
                    key,
                    value,
                    idx,
                    ind,
                );
                let _ = writeln!(out, "{ind}        elem_idx++;");
            }
        }
    }

    let _ = writeln!(out, "{ind}    }}"); // end while
    let _ = writeln!(out, "{ind}}}"); // end if
}

/// Generate C++ code to populate a map field from a JSON object `{"k": v, ...}`.
/// Generate C++ code to populate a map field from a JSON object `{"k": v, ...}`.
/// `base_access` is the field-level access expression (see [`field_access`]),
/// used when composing nested-map assignment targets.
/// `source_start`/`source_end` are C++ pointer expressions for the JSON object boundaries
/// (e.g., `"val_start"` for a direct field, `"vs"`/`"ve"` for a nested map value).
/// `target` is the C++ expression for the map variable to populate
/// (e.g., `"typed->{fname}"` for a direct field, `"typed->{fname}[elem_idx]"` for array elements).
#[allow(clippy::too_many_arguments)] // Mirrors the field context it renders
fn emit_map_field_population(
    out: &mut String,
    fname: &str,
    base_access: &str,
    source_start: &str,
    source_end: &str,
    target: &str,
    key_ty: &IdlType,
    val_ty: &IdlType,
    idx: &DefinitionIndex,
    ind: &str,
) {
    let _ = writeln!(out, "{ind}// Map field \"{fname}\"");
    let _ = writeln!(
        out,
        "{ind}if ({source_start}[0] == '{{' && {source_end} > {source_start}) {{"
    );
    let _ = writeln!(out, "{ind}    const char* mp = {source_start} + 1;");
    let _ = writeln!(out, "{ind}    while (mp < {source_end} && *mp != '}}') {{");
    let _ = writeln!(
        out,
        "{ind}        while (mp < {source_end} && (*mp == ' ' || *mp == '\\t' || *mp == '\\n' || *mp == '\\r' || *mp == ',')) mp++;"
    );
    let _ = writeln!(
        out,
        "{ind}        if (mp >= {source_end} || *mp == '}}') break;"
    );
    let _ = writeln!(out, "{ind}        if (*mp != '\"') {{ mp++; continue; }}");
    let _ = writeln!(out, "{ind}        const char* ks = ++mp;");
    let _ = writeln!(
        out,
        "{ind}        while (mp < {source_end} && *mp != '\"') {{ if (*mp == '\\\\' && *(mp+1)) mp++; mp++; }}"
    );
    let _ = writeln!(out, "{ind}        if (mp >= {source_end}) break;");
    let _ = writeln!(
        out,
        "{ind}        std::string key_str = json_unescape(ks, static_cast<std::size_t>(mp - ks));"
    );
    let _ = writeln!(out, "{ind}        mp++;");
    let _ = writeln!(
        out,
        "{ind}        while (mp < {source_end} && *mp != ':') mp++;"
    );
    let _ = writeln!(out, "{ind}        if (*mp == ':') mp++;");
    let _ = writeln!(
        out,
        "{ind}        while (mp < {source_end} && (*mp == ' ' || *mp == '\\t' || *mp == '\\n' || *mp == '\\r')) mp++;"
    );
    let _ = writeln!(out, "{ind}        if (mp >= {source_end}) break;");
    let _ = writeln!(out, "{ind}        [[maybe_unused]] const char* vs = mp;");

    // Advance past value
    let _ = writeln!(out, "{ind}        if (*mp == '\"') {{");
    let _ = writeln!(
        out,
        "{ind}            mp++; while (mp < {source_end} && *mp != '\"') {{ if (*mp == '\\\\' && *(mp+1)) mp++; mp++; }}"
    );
    let _ = writeln!(
        out,
        "{ind}            if (mp < {source_end} && *mp == '\"') mp++;"
    );
    let _ = writeln!(out, "{ind}        }} else if (*mp == '{{') {{");
    let _ = writeln!(
        out,
        "{ind}            int depth = 1; mp++; while (mp < {source_end} && depth > 0) {{ if (*mp == '{{') depth++; else if (*mp == '}}') depth--; mp++; }}"
    );
    let _ = writeln!(out, "{ind}        }} else if (*mp == '[') {{");
    let _ = writeln!(
        out,
        "{ind}            int depth = 1; mp++; while (mp < {source_end} && depth > 0) {{ if (*mp == '[') depth++; else if (*mp == ']') depth--; mp++; }}"
    );
    let _ = writeln!(out, "{ind}        }} else {{");
    let _ = writeln!(
        out,
        "{ind}            while (mp < {source_end} && *mp != ',' && *mp != '}}' && *mp != ' ' && *mp != '\\t' && *mp != '\\n' && *mp != '\\r') mp++;"
    );
    let _ = writeln!(out, "{ind}        }}");
    let _ = writeln!(out, "{ind}        [[maybe_unused]] const char* ve = mp;");
    let _ = writeln!(
        out,
        "{ind}        [[maybe_unused]] std::size_t vlen = static_cast<std::size_t>(ve - vs);"
    );
    let _ = writeln!(out, "{ind}        if (vlen == 0) continue;");

    // Convert key_str to the map's key type
    emit_map_key_conversion(out, fname, key_ty, idx, ind);

    // Parse the value and set {target}[key] = value
    let tgt = format!("{target}[k]");
    emit_map_value_assignment(out, base_access, &tgt, val_ty, idx, ind);

    let _ = writeln!(out, "{ind}    }}");
    let _ = writeln!(out, "{ind}}}");
}

/// Generate C++ code to convert `key_str` (`std::string`) to the map's key type
/// and store in a local variable `k`.
#[allow(clippy::too_many_lines)] // Type-directed C++ emission table
fn emit_map_key_conversion(
    out: &mut String,
    _fname: &str,
    key_ty: &IdlType,
    idx: &DefinitionIndex,
    ind: &str,
) {
    match key_ty {
        IdlType::BoundedString { .. } => {
            let kt = crate::codegen::cpp::helpers::type_to_cpp(key_ty);
            let _ = writeln!(out, "{ind}        {kt} k{{}};");
            let _ = writeln!(
                out,
                "{ind}        if (!assign_bounded(k, key_str)) return false;"
            );
        }
        IdlType::Primitive(pt) => match pt {
            PrimitiveType::String => {
                let _ = writeln!(out, "{ind}        auto&& k = key_str;");
            }
            PrimitiveType::WString => {
                let _ = writeln!(out, "{ind}        auto k = utf8_to_wstring(key_str);");
            }
            PrimitiveType::Boolean => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = (key_str == \"true\" || key_str == \"1\");"
                );
            }
            PrimitiveType::Char
            | PrimitiveType::WChar
            | PrimitiveType::Octet
            | PrimitiveType::UInt8 => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<uint8_t>(std::strtoul(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::Int8 => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<int8_t>(std::strtol(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::UInt16 | PrimitiveType::UnsignedShort => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<uint16_t>(std::strtoul(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::Int16 | PrimitiveType::Short => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<int16_t>(std::strtol(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::UInt32 | PrimitiveType::UnsignedLong => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<uint32_t>(std::strtoul(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::Int32 | PrimitiveType::Long => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<int32_t>(std::strtol(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::UInt64 | PrimitiveType::UnsignedLongLong => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<uint64_t>(std::strtoull(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::Int64 | PrimitiveType::LongLong => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = static_cast<int64_t>(std::strtoll(key_str.c_str(), nullptr, 10));"
                );
            }
            PrimitiveType::Float => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = std::strtof(key_str.c_str(), nullptr);"
                );
            }
            PrimitiveType::Double => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = std::strtod(key_str.c_str(), nullptr);"
                );
            }
            PrimitiveType::LongDouble | PrimitiveType::Fixed { .. } => {
                let _ = writeln!(
                    out,
                    "{ind}        auto k = std::strtold(key_str.c_str(), nullptr);"
                );
            }
            PrimitiveType::Void => {
                let _ = writeln!(out, "{ind}        (void)key_str; continue;");
            }
        },
        IdlType::Named(named_type) => {
            if let Some(variants) = idx.enum_variants(named_type) {
                // Enum key: match variant name
                let _ = writeln!(
                    out,
                    "{ind}        {named_type} k = static_cast<{named_type}>(0);"
                );
                let _ = writeln!(out, "{ind}        bool k_found = false;");
                for (i, variant) in variants.iter().enumerate() {
                    let vname = variant;
                    let vlen = vname.len();
                    let kw = if i == 0 { "if" } else { "else if" };
                    let _ = writeln!(
                        out,
                        "{ind}        {kw} (key_str.size() == {vlen} && std::memcmp(key_str.data(), \"{vname}\", {vlen}) == 0) {{ k = {named_type}::{vname}; k_found = true; }}"
                    );
                }
                let _ = writeln!(out, "{ind}        if (!k_found) continue;");
            } else {
                // Unsupported key type
                let _ = writeln!(
                    out,
                    "{ind}        // Unsupported map key type \"{named_type}\": skip entry"
                );
                let _ = writeln!(out, "{ind}        continue;");
            }
        }
        IdlType::Array { .. } | IdlType::Sequence { .. } => {
            let _ = writeln!(
                out,
                "{ind}        // Array/sequence as map key: not supported in IDL (illegal), skip entry"
            );
            let _ = writeln!(out, "{ind}        continue;");
        }
        IdlType::Map { .. } => {
            let _ = writeln!(out, "{ind}        // Map as key type: illegal in IDL, skip");
            let _ = writeln!(out, "{ind}        continue;");
        }
    }
}

/// Generate C++ code to parse a map value from JSON and assign to key.
/// `base_access` is the field-level access expression (see [`field_access`]),
/// `target` is the C++ expression for the map element.
#[allow(clippy::too_many_lines)] // Type-directed C++ emission table
fn emit_map_value_assignment(
    out: &mut String,
    base_access: &str,
    target: &str,
    val_ty: &IdlType,
    idx: &DefinitionIndex,
    ind: &str,
) {
    match val_ty {
        IdlType::BoundedString { .. } => {
            let _ = writeln!(out, "{ind}        if (*vs == '\"' && vlen >= 2) {{");
            let _ = writeln!(
                out,
                "{ind}            if (!assign_bounded({target}, json_unescape(vs + 1, vlen - 2))) return false;"
            );
            let _ = writeln!(out, "{ind}        }}");
        }
        IdlType::Primitive(pt) => match pt {
            PrimitiveType::Boolean => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = (vlen >= 4 && (vs[0] == 't' || vs[0] == 'T'));"
                );
            }
            PrimitiveType::Char
            | PrimitiveType::WChar
            | PrimitiveType::Octet
            | PrimitiveType::UInt8 => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<uint8_t>(std::strtoul(vs, nullptr, 10));"
                );
            }
            PrimitiveType::Int8 => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<int8_t>(std::strtol(vs, nullptr, 10));"
                );
            }
            PrimitiveType::UInt16 | PrimitiveType::UnsignedShort => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<uint16_t>(std::strtoul(vs, nullptr, 10));"
                );
            }
            PrimitiveType::Int16 | PrimitiveType::Short => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<int16_t>(std::strtol(vs, nullptr, 10));"
                );
            }
            PrimitiveType::UInt32 | PrimitiveType::UnsignedLong => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<uint32_t>(std::strtoul(vs, nullptr, 10));"
                );
            }
            PrimitiveType::Int32 | PrimitiveType::Long => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<int32_t>(std::strtol(vs, nullptr, 10));"
                );
            }
            PrimitiveType::UInt64 | PrimitiveType::UnsignedLongLong => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<uint64_t>(std::strtoull(vs, nullptr, 10));"
                );
            }
            PrimitiveType::Int64 | PrimitiveType::LongLong => {
                let _ = writeln!(
                    out,
                    "{ind}        {target} = static_cast<int64_t>(std::strtoll(vs, nullptr, 10));"
                );
            }
            PrimitiveType::Float => {
                let _ = writeln!(out, "{ind}        {target} = std::strtof(vs, nullptr);");
            }
            PrimitiveType::Double => {
                let _ = writeln!(out, "{ind}        {target} = std::strtod(vs, nullptr);");
            }
            PrimitiveType::LongDouble | PrimitiveType::Fixed { .. } => {
                let _ = writeln!(out, "{ind}        {target} = std::strtold(vs, nullptr);");
            }
            PrimitiveType::String => {
                let _ = writeln!(out, "{ind}        if (*vs == '\"' && vlen >= 2) {{");
                let _ = writeln!(
                    out,
                    "{ind}            {target} = json_unescape(vs + 1, vlen - 2);"
                );
                let _ = writeln!(out, "{ind}        }}");
            }
            PrimitiveType::WString => {
                let _ = writeln!(out, "{ind}        if (*vs == '\"' && vlen >= 2) {{");
                let _ = writeln!(
                    out,
                    "{ind}            std::string tmp = json_unescape(vs + 1, vlen - 2);"
                );
                let _ = writeln!(out, "{ind}            {target} = utf8_to_wstring(tmp);");
                let _ = writeln!(out, "{ind}        }}");
            }
            PrimitiveType::Void => {
                let _ = writeln!(out, "{ind}        // void value: skipped");
            }
        },
        IdlType::Named(named_type) => {
            if let Some(variants) = idx.enum_variants(named_type) {
                // Enum value: match string variant name
                let _ = writeln!(out, "{ind}        if (*vs == '\"' && vlen >= 2) {{");
                let _ = writeln!(out, "{ind}            const char* evs = vs + 1;");
                let _ = writeln!(out, "{ind}            std::size_t evl = vlen - 2;");
                for (i, variant) in variants.iter().enumerate() {
                    let vname = variant;
                    let vlen = vname.len();
                    let kw = if i == 0 { "if" } else { "else if" };
                    let _ = writeln!(
                        out,
                        "{ind}            {kw} (evl == {vlen} && std::memcmp(evs, \"{vname}\", {vlen}) == 0) {{ {target} = {named_type}::{vname}; }}"
                    );
                }
                let _ = writeln!(out, "{ind}        }}");
            } else if idx.is_struct(named_type) {
                let pubsub_type = format!("{named_type}PubSubType");
                let _ = writeln!(out, "{ind}        if (*vs == '{{' && ve > vs) {{");
                let _ = writeln!(out, "{ind}            {target} = {{}};");
                let _ = writeln!(
                    out,
                    "{ind}            std::string sub(vs, static_cast<std::size_t>(ve - vs));"
                );
                let _ = writeln!(
                    out,
                    "{ind}            {pubsub_type}::populate_from_json(&{target}, sub.c_str());"
                );
                let _ = writeln!(out, "{ind}        }}");
            } else {
                let _ = writeln!(
                    out,
                    "{ind}        // Unsupported value type \"{named_type}\": skip"
                );
            }
        }
        IdlType::Array { inner, .. } | IdlType::Sequence { inner, .. } => {
            // An array of characters is read as a string; every sequence
            // (`sequence<char>` included) is a `std::vector`.
            let is_bounded_str = matches!(val_ty, IdlType::Array { inner, .. } if matches!(**inner, IdlType::Primitive(PrimitiveType::Char | PrimitiveType::Octet)));
            if is_bounded_str {
                // Bounded string as map value: treat as string copy, not array iteration
                let _ = writeln!(out, "{ind}        if (*vs == '\"' && vlen >= 2) {{");
                let _ = writeln!(
                    out,
                    "{ind}            std::string tmp = json_unescape(vs + 1, vlen - 2);"
                );
                let _ = writeln!(
                    out,
                    "{ind}            std::size_t copy_len = std::min(tmp.size(), sizeof({target}) / sizeof({target}[0]) - 1);"
                );
                let _ = writeln!(
                    out,
                    "{ind}            std::memcpy({target}.data(), tmp.data(), copy_len);"
                );
                let _ = writeln!(out, "{ind}            {target}[copy_len] = '\\0';");
                let _ = writeln!(out, "{ind}        }}");
            } else {
                // For map values that are arrays/sequences, we treat them like
                // array/sequence population but targeting map[key].
                // Simple case: push elements into a temp sequence, then assign.
                let _ = writeln!(out, "{ind}        if (*vs == '[' && ve > vs) {{");
                let _ = writeln!(out, "{ind}            const char* ep = vs + 1;");
                let _ = writeln!(out, "{ind}            while (ep < ve && *ep != ']') {{");
                let _ = writeln!(
                out,
                "{ind}                while (ep < ve && (*ep == ' ' || *ep == '\\t' || *ep == '\\n' || *ep == '\\r' || *ep == ',')) ep++;"
            );
                let _ = writeln!(
                    out,
                    "{ind}                if (ep >= ve || *ep == ']') break;"
                );
                let _ = writeln!(out, "{ind}                const char* es = ep;");
                let _ = writeln!(out, "{ind}                if (*ep == '\"') {{");
                let _ = writeln!(
                out,
                "{ind}                    ep++; while (ep < ve && *ep != '\"') {{ if (*ep == '\\\\' && *(ep+1)) ep++; ep++; }}"
            );
                let _ = writeln!(
                    out,
                    "{ind}                    if (ep < ve && *ep == '\"') ep++;"
                );
                let _ = writeln!(out, "{ind}                }} else if (*ep == '{{') {{");
                let _ = writeln!(
                out,
                "{ind}                    int depth = 1; ep++; while (ep < ve && depth > 0) {{ if (*ep == '{{') depth++; else if (*ep == '}}') depth--; ep++; }}"
            );
                let _ = writeln!(out, "{ind}                }} else {{");
                let _ = writeln!(
                out,
                "{ind}                    while (ep < ve && *ep != ',' && *ep != ']' && *ep != ' ' && *ep != '\\t' && *ep != '\\n' && *ep != '\\r') ep++;"
            );
                let _ = writeln!(out, "{ind}                }}");
                let _ = writeln!(out, "{ind}                if (ep == es) break;");

                // Element assignment via push_back on the sequence value
                emit_map_seq_element_push(out, base_access, target, inner, idx, ind);

                let _ = writeln!(out, "{ind}            }}");
            }
            let _ = writeln!(out, "{ind}        }}");
        }
        IdlType::Map {
            key: inner_key_ty,
            value: inner_val_ty,
            ..
        } => {
            // Nested map value: parse inner JSON object from vs/ve
            let _ = writeln!(out, "{ind}        {{");
            let _ = writeln!(out, "{ind}            auto _ok = k;");
            let _ = writeln!(out, "{ind}            if (vs[0] == '{{' && ve > vs) {{");
            let _ = writeln!(out, "{ind}                const char* imp = vs + 1;");
            let _ = writeln!(
                out,
                "{ind}                while (imp < ve && *imp != '}}') {{"
            );
            let _ = writeln!(
                out,
                "{ind}                    while (imp < ve && (*imp == ' ' || *imp == '\\t' || *imp == '\\n' || *imp == '\\r' || *imp == ',')) imp++;"
            );
            let _ = writeln!(
                out,
                "{ind}                    if (imp >= ve || *imp == '}}') break;"
            );
            let _ = writeln!(
                out,
                "{ind}                    if (*imp != '\"') {{ imp++; continue; }}"
            );
            let _ = writeln!(out, "{ind}                    const char* iks = ++imp;");
            let _ = writeln!(
                out,
                "{ind}                    while (imp < ve && *imp != '\"') {{ if (*imp == '\\\\' && *(imp+1)) imp++; imp++; }}"
            );
            let _ = writeln!(out, "{ind}                    if (imp >= ve) break;");
            let _ = writeln!(
                out,
                "{ind}                    std::string ikey_str = json_unescape(iks, static_cast<std::size_t>(imp - iks));"
            );
            let _ = writeln!(out, "{ind}                    imp++;");
            let _ = writeln!(
                out,
                "{ind}                    while (imp < ve && *imp != ':') imp++;"
            );
            let _ = writeln!(out, "{ind}                    if (*imp == ':') imp++;");
            let _ = writeln!(
                out,
                "{ind}                    while (imp < ve && (*imp == ' ' || *imp == '\\t' || *imp == '\\n' || *imp == '\\r')) imp++;"
            );
            let _ = writeln!(out, "{ind}                    if (imp >= ve) break;");
            let _ = writeln!(out, "{ind}                    const char* ivs = imp;");
            // Advance past inner value
            let _ = writeln!(out, "{ind}                    if (*imp == '\"') {{");
            let _ = writeln!(
                out,
                "{ind}                        imp++; while (imp < ve && *imp != '\"') {{ if (*imp == '\\\\' && *(imp+1)) imp++; imp++; }}"
            );
            let _ = writeln!(
                out,
                "{ind}                        if (imp < ve && *imp == '\"') imp++;"
            );
            let _ = writeln!(out, "{ind}                    }} else if (*imp == '{{') {{");
            let _ = writeln!(
                out,
                "{ind}                        int depth = 1; imp++; while (imp < ve && depth > 0) {{ if (*imp == '{{') depth++; else if (*imp == '}}') depth--; imp++; }}"
            );
            let _ = writeln!(out, "{ind}                    }} else if (*imp == '[') {{");
            let _ = writeln!(
                out,
                "{ind}                        int depth = 1; imp++; while (imp < ve && depth > 0) {{ if (*imp == '[') depth++; else if (*imp == ']') depth--; imp++; }}"
            );
            let _ = writeln!(out, "{ind}                    }} else {{");
            let _ = writeln!(
                out,
                "{ind}                        while (imp < ve && *imp != ',' && *imp != '}}' && *imp != ' ' && *imp != '\\t' && *imp != '\\n' && *imp != '\\r') imp++;"
            );
            let _ = writeln!(out, "{ind}                    }}");
            let _ = writeln!(out, "{ind}                    const char* ive = imp;");
            let _ = writeln!(
                out,
                "{ind}                    std::size_t ivlen = static_cast<std::size_t>(ive - ivs);"
            );
            let _ = writeln!(out, "{ind}                    if (ivlen == 0) continue;");
            // Convert inner key_str to key type (reuse emit_map_key_convention)
            let _ = writeln!(
                out,
                "{ind}                    std::string key_str = std::move(ikey_str);"
            );
            emit_map_key_conversion(out, base_access, inner_key_ty, idx, ind);
            // Assign inner value: redirect vs/vlen to inner value and recurse.
            // Note: ve is intentionally NOT redirected - it remains as the outer
            // bound (end of the inner JSON object) so the inner while-loop
            // condition `imp < ve` continues to work for subsequent entries.
            let _ = writeln!(out, "{ind}                    vs = ivs;");
            let _ = writeln!(out, "{ind}                    vlen = ivlen;");
            // Target includes [k] where k is the inner key (shadows outer k inside this scope)
            let nested_target = format!("{base_access}[_ok][k]");
            emit_map_value_assignment(out, base_access, &nested_target, inner_val_ty, idx, ind);
            let _ = writeln!(out, "{ind}                }}");
            let _ = writeln!(out, "{ind}            }}");
            let _ = writeln!(out, "{ind}        }}");
        }
    }
}

/// Generate C++ code to push an element from `es..ep` into the sequence map value.
#[allow(clippy::too_many_lines)] // Type-directed C++ emission table
fn emit_map_seq_element_push(
    out: &mut String,
    _fname: &str,
    target: &str,
    inner: &IdlType,
    idx: &DefinitionIndex,
    ind: &str,
) {
    match inner {
        IdlType::BoundedString { .. } => {
            let _ = writeln!(
                out,
                "{ind}                if (*es == '\"' && ep >= es + 2) {{"
            );
            let _ = writeln!(out, "{ind}                    {target}.emplace_back();");
            let _ = writeln!(
                out,
                "{ind}                    if (!assign_bounded({target}.back(), json_unescape(es + 1, static_cast<std::size_t>(ep - es - 2)))) return false;"
            );
            let _ = writeln!(out, "{ind}                }}");
        }
        IdlType::Primitive(pt) => match pt {
            PrimitiveType::Boolean => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(es[0] == 't' || es[0] == 'T');"
                );
            }
            PrimitiveType::Char
            | PrimitiveType::WChar
            | PrimitiveType::Octet
            | PrimitiveType::UInt8 => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<uint8_t>(std::strtoul(es, nullptr, 10)));"
                );
            }
            PrimitiveType::Int8 => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<int8_t>(std::strtol(es, nullptr, 10)));"
                );
            }
            PrimitiveType::UInt16 | PrimitiveType::UnsignedShort => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<uint16_t>(std::strtoul(es, nullptr, 10)));"
                );
            }
            PrimitiveType::Int16 | PrimitiveType::Short => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<int16_t>(std::strtol(es, nullptr, 10)));"
                );
            }
            PrimitiveType::UInt32 | PrimitiveType::UnsignedLong => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<uint32_t>(std::strtoul(es, nullptr, 10)));"
                );
            }
            PrimitiveType::Int32 | PrimitiveType::Long => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<int32_t>(std::strtol(es, nullptr, 10)));"
                );
            }
            PrimitiveType::UInt64 | PrimitiveType::UnsignedLongLong => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<uint64_t>(std::strtoull(es, nullptr, 10)));"
                );
            }
            PrimitiveType::Int64 | PrimitiveType::LongLong => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(static_cast<int64_t>(std::strtoll(es, nullptr, 10)));"
                );
            }
            PrimitiveType::Float => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(std::strtof(es, nullptr));"
                );
            }
            PrimitiveType::Double => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(std::strtod(es, nullptr));"
                );
            }
            PrimitiveType::LongDouble | PrimitiveType::Fixed { .. } => {
                let _ = writeln!(
                    out,
                    "{ind}                {target}.push_back(std::strtold(es, nullptr));"
                );
            }
            PrimitiveType::String => {
                let _ = writeln!(
                    out,
                    "{ind}                if (*es == '\"' && ep > es + 2) {{"
                );
                let _ = writeln!(
                    out,
                    "{ind}                    std::size_t cl = static_cast<std::size_t>(ep - es - 2);"
                );
                let _ = writeln!(
                    out,
                    "{ind}                    {target}.push_back(json_unescape(es + 1, cl));"
                );
                let _ = writeln!(out, "{ind}                }}");
            }
            PrimitiveType::WString => {
                let _ = writeln!(
                    out,
                    "{ind}                if (*es == '\"' && ep > es + 2) {{"
                );
                let _ = writeln!(
                    out,
                    "{ind}                    std::size_t cl = static_cast<std::size_t>(ep - es - 2);"
                );
                let _ = writeln!(
                    out,
                    "{ind}                    std::string tmp = json_unescape(es + 1, cl);"
                );
                let _ = writeln!(
                    out,
                    "{ind}                    {target}.push_back(utf8_to_wstring(tmp));"
                );
                let _ = writeln!(out, "{ind}                }}");
            }
            PrimitiveType::Void => {}
        },
        IdlType::Named(named_type) => {
            if let Some(variants) = idx.enum_variants(named_type) {
                let _ = writeln!(
                    out,
                    "{ind}                if (*es == '\"' && ep > es + 2) {{"
                );
                let _ = writeln!(out, "{ind}                    const char* evs = es + 1;");
                let _ = writeln!(
                    out,
                    "{ind}                    std::size_t evl = static_cast<std::size_t>(ep - es - 2);"
                );
                for (i, variant) in variants.iter().enumerate() {
                    let vname = variant;
                    let vlen = vname.len();
                    let kw = if i == 0 { "if" } else { "else if" };
                    let _ = writeln!(
                        out,
                        "{ind}                    {kw} (evl == {vlen} && std::memcmp(evs, \"{vname}\", {vlen}) == 0) {{ {target}.push_back({named_type}::{vname}); }}"
                    );
                }
                let _ = writeln!(out, "{ind}                }}");
            } else if idx.is_struct(named_type) {
                let pubsub_type = format!("{named_type}PubSubType");
                let _ = writeln!(out, "{ind}                if (*es == '{{' && ep > es) {{");
                let _ = writeln!(out, "{ind}                    {target}.emplace_back();");
                let _ = writeln!(
                    out,
                    "{ind}                    std::string sub(es, static_cast<std::size_t>(ep - es));"
                );
                let _ = writeln!(
                    out,
                    "{ind}                    {pubsub_type}::populate_from_json(&{target}.back(), sub.c_str());"
                );
                let _ = writeln!(out, "{ind}                }}");
            } else {
                let _ = writeln!(
                    out,
                    "{ind}                // Unsupported element type \"{named_type}\": skipped"
                );
            }
        }
        IdlType::Sequence { .. } | IdlType::Array { .. } => {
            let _ = writeln!(
                out,
                "{ind}                // Nested array/sequence in map: not supported"
            );
        }
        IdlType::Map { .. } => {
            let _ = writeln!(
                out,
                "{ind}                // Map in map value: not supported"
            );
        }
    }
}

/// Generate C++ code to parse a JSON value and set the corresponding struct field.
/// `indent` is the number of indentation levels to use inside the if-block.
/// An `@optional` member is a `std::optional`: JSON `null` resets it, any
/// other value is parsed into its (emplaced) value.
fn generate_field_setter(
    out: &mut String,
    field: &crate::ast::Field,
    indent: usize,
    idx: &DefinitionIndex,
    fastdds_compat: bool,
) {
    let fname = &field.name;
    let access = field_access(fname, fastdds_compat);
    if field.is_optional() {
        let ind = "    ".repeat(indent);
        let _ = writeln!(
            out,
            "{ind}if (vlen == 4 && std::memcmp(val_start, \"null\", 4) == 0) {{"
        );
        let _ = writeln!(out, "{ind}    {access}.reset();");
        let _ = writeln!(out, "{ind}}} else {{");
        let _ = writeln!(
            out,
            "{ind}    if (!{access}.has_value()) {access}.emplace();"
        );
        let inner = format!("(*{access})");
        emit_value_setter(out, fname, &field.field_type, &inner, None, indent + 1, idx);
        let _ = writeln!(out, "{ind}}}");
        return;
    }
    // Primitive non-optional fields expose only a by-value getter and a setter
    // in fastdds-compat mode, so scalar assignments must go through the setter.
    // All other fields have a mutable-ref accessor: `access` is a valid lvalue.
    let setter = (fastdds_compat && matches!(field.field_type, IdlType::Primitive(_)))
        .then(|| format!("typed->{}", cpp_ident(fname)));
    emit_value_setter(
        out,
        fname,
        &field.field_type,
        &access,
        setter.as_deref(),
        indent,
        idx,
    );
}

/// The statements parsing the JSON value at `val_start` (`vlen` bytes)
/// into the lvalue `access` of type `ty`; `setter`: the setter to call
/// instead of assigning (a primitive member in the `FastDDS` flavour).
#[allow(clippy::too_many_lines)] // Type-directed C++ emission table
fn emit_value_setter(
    out: &mut String,
    fname: &str,
    ty: &IdlType,
    access: &str,
    setter: Option<&str>,
    indent: usize,
    idx: &DefinitionIndex,
) {
    let ind = "    ".repeat(indent);
    let assign = |expr: &str| -> String {
        setter.map_or_else(
            || format!("{access} = {expr};"),
            |f| format!("{f}({expr});"),
        )
    };

    match ty {
        // `string<N>` / `wstring<N>`: a `std::array`, at most N characters.
        IdlType::BoundedString { .. } => {
            let _ = writeln!(out, "{ind}if (val_start[0] == '\"' && vlen >= 2) {{");
            let _ = writeln!(
                out,
                "{ind}    if (!assign_bounded({access}, json_unescape(val_start + 1, vlen - 2))) return false;"
            );
            let _ = writeln!(out, "{ind}}}");
        }
        IdlType::Primitive(pt) => match pt {
            PrimitiveType::Boolean => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("(vlen >= 4 && (val_start[0] == 't' || val_start[0] == 'T'))")
                );
            }
            PrimitiveType::Char | PrimitiveType::WChar => {
                let _ = writeln!(out, "{ind}if (val_start[0] == '\"' && vlen >= 2) {{");
                let _ = writeln!(
                    out,
                    "{ind}    std::string tmp = json_unescape(val_start + 1, vlen - 2);"
                );
                let _ = writeln!(out, "{ind}    {}", assign("tmp.empty() ? 0 : tmp[0]"));
                let _ = writeln!(out, "{ind}}} else {{");
                let _ = writeln!(
                    out,
                    "{ind}    {}",
                    assign("static_cast<char>(std::strtol(val_start, nullptr, 10))")
                );
                let _ = writeln!(out, "{ind}}}");
            }
            PrimitiveType::Octet | PrimitiveType::UInt8 => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<uint8_t>(std::strtoul(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::UInt16 | PrimitiveType::UnsignedShort => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<uint16_t>(std::strtoul(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::UInt32 | PrimitiveType::UnsignedLong => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<uint32_t>(std::strtoul(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::UInt64 | PrimitiveType::UnsignedLongLong => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<uint64_t>(std::strtoull(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::Int8 => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<int8_t>(std::strtol(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::Int16 | PrimitiveType::Short => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<int16_t>(std::strtol(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::Int32 | PrimitiveType::Long => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<int32_t>(std::strtol(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::Int64 | PrimitiveType::LongLong => {
                let _ = writeln!(
                    out,
                    "{ind}{}",
                    assign("static_cast<int64_t>(std::strtoll(val_start, nullptr, 10))")
                );
            }
            PrimitiveType::Float => {
                let _ = writeln!(out, "{ind}{}", assign("std::strtof(val_start, nullptr)"));
            }
            PrimitiveType::Double => {
                let _ = writeln!(out, "{ind}{}", assign("std::strtod(val_start, nullptr)"));
            }
            PrimitiveType::LongDouble | PrimitiveType::Fixed { .. } => {
                // long double: hex string "0x..." from float128 JSON format
                let _ = writeln!(out, "{ind}// long double from hex string \"0x...\"");
                let _ = writeln!(out, "{ind}if (val_start[0] == '\"' && vlen > 10) {{");
                let _ = writeln!(
                    out,
                    "{ind}    // Parse hex string: \"0x0000000000000000XXXXXXXXYYYY\""
                );
                let _ = writeln!(
                    out,
                    "{ind}    // format is 8 bytes low + 8 bytes high as hex"
                );
                let _ = writeln!(out, "{ind}    const char* h = val_start + 1;");
                let _ = writeln!(
                    out,
                    "{ind}    if (*h == '\"' || !*h) {{ {} }} else {{",
                    assign("0.0")
                );
                let _ = writeln!(out, "{ind}        {}", assign("std::strtold(h, nullptr)"));
                let _ = writeln!(out, "{ind}    }}");
                let _ = writeln!(out, "{ind}}}");
            }
            PrimitiveType::String => {
                let _ = writeln!(out, "{ind}if (val_start[0] == '\"' && vlen >= 2) {{");
                let _ = writeln!(
                    out,
                    "{ind}    {}",
                    assign("json_unescape(val_start + 1, vlen - 2)")
                );
                let _ = writeln!(out, "{ind}}}");
            }
            PrimitiveType::WString => {
                let _ = writeln!(out, "{ind}if (val_start[0] == '\"' && vlen >= 2) {{");
                let _ = writeln!(
                    out,
                    "{ind}    std::string tmp = json_unescape(val_start + 1, vlen - 2);"
                );
                if let Some(f) = setter {
                    let _ = writeln!(out, "{ind}    {f}(utf8_to_wstring(tmp));");
                } else {
                    let _ = writeln!(out, "{ind}    {access}.assign(utf8_to_wstring(tmp));");
                }
                let _ = writeln!(out, "{ind}}}");
            }
            PrimitiveType::Void => {
                let _ = writeln!(
                    out,
                    "{ind}(void)val_start; (void)vlen; // void field {fname} ignored"
                );
            }
        },
        IdlType::Array { inner, .. } | IdlType::Sequence { inner, .. } => {
            // An array of `char` / `octet` is read as a string; a sequence
            // (`sequence<char>` included) is a `std::vector`.
            let is_bounded_string = matches!(ty, IdlType::Array { .. })
                && matches!(&**inner, IdlType::Primitive(p) if *p == PrimitiveType::Char || *p == PrimitiveType::Octet);
            if is_bounded_string {
                let _ = writeln!(out, "{ind}if (val_start[0] == '\"' && vlen >= 2) {{");
                let _ = writeln!(
                    out,
                    "{ind}    std::string tmp = json_unescape(val_start + 1, vlen - 2);"
                );
                let _ = writeln!(
                    out,
                    "{ind}    constexpr std::size_t arr_cap = sizeof({access}) / sizeof({access}[0]);"
                );
                let _ = writeln!(out, "{ind}    if (tmp.size() + 1 > arr_cap) return false;");
                let _ = writeln!(
                    out,
                    "{ind}    std::memcpy({access}.data(), tmp.data(), tmp.size());"
                );
                let _ = writeln!(out, "{ind}    {access}[tmp.size()] = '\\0';");
                let _ = writeln!(out, "{ind}}}");
            } else {
                // Every sequence but a bounded string is a std::vector
                // (push_back, the bound checked); arrays are std::array.
                let is_dynamic_sequence = matches!(ty, IdlType::Sequence { .. });
                emit_array_field_population(
                    out,
                    fname,
                    access,
                    inner,
                    idx,
                    &ind,
                    is_dynamic_sequence,
                );
            }
        }
        IdlType::Named(named_type) => {
            if let Some(variants) = idx.enum_variants(named_type) {
                let _ = writeln!(
                    out,
                    "{ind}// Enum field \"{fname}\" of type \"{named_type}\""
                );
                let _ = writeln!(out, "{ind}if (val_start[0] == '\"' && vlen >= 2) {{");
                let _ = writeln!(out, "{ind}    const char* vs = val_start + 1;");
                let _ = writeln!(out, "{ind}    std::size_t vl = vlen - 2;");
                for (i, variant) in variants.iter().enumerate() {
                    let vname = variant;
                    let vlen_val = vname.len();
                    if i == 0 {
                        let _ = writeln!(
                            out,
                            "{ind}    if (vl == {vlen_val} && std::memcmp(vs, \"{vname}\", {vlen_val}) == 0) {{"
                        );
                    } else {
                        let _ = writeln!(
                            out,
                            "{ind}    }} else if (vl == {vlen_val} && std::memcmp(vs, \"{vname}\", {vlen_val}) == 0) {{"
                        );
                    }
                    let _ = writeln!(out, "{ind}        {access} = {named_type}::{vname};");
                }
                if !variants.is_empty() {
                    let _ = writeln!(out, "{ind}    }}");
                }
                let _ = writeln!(out, "{ind}}}");
            } else if idx.is_struct(named_type) {
                let pubsub_type = format!("{named_type}PubSubType");
                let _ = writeln!(
                    out,
                    "{ind}// Nested struct field \"{fname}\" of type \"{named_type}\""
                );
                let _ = writeln!(
                    out,
                    "{ind}if (val_start[0] == '{{' && val_end > val_start) {{"
                );
                let _ = writeln!(
                    out,
                    "{ind}    std::string sub(val_start, static_cast<std::size_t>(val_end - val_start));"
                );
                let _ = writeln!(
                    out,
                    "{ind}    {pubsub_type}::populate_from_json(&{access}, sub.c_str());"
                );
                let _ = writeln!(out, "{ind}}}");
            } else {
                let _ = writeln!(
                    out,
                    "{ind}// Nested struct/enum population not yet generated for field \"{fname}\" of type \"{named_type}\""
                );
                let _ = writeln!(out, "{ind}(void)val_start; (void)vlen;");
            }
        }
        IdlType::Map { key, value, .. } => {
            emit_map_field_population(
                out,
                fname,
                access,
                "val_start",
                "val_end",
                access,
                key,
                value,
                idx,
                &ind,
            );
        }
    }
}

/// Check if a struct has bounded size (no unbounded sequences/strings)
fn is_type_bounded(s: &Struct) -> &'static str {
    use crate::types::IdlType;

    for field in &s.fields {
        #[allow(clippy::unnested_or_patterns)] // More readable with separate arms
        match &field.field_type {
            IdlType::Sequence { bound: None, .. }
            | IdlType::Primitive(crate::types::PrimitiveType::String)
            | IdlType::Primitive(crate::types::PrimitiveType::WString)
            | IdlType::Map { bound: None, .. } => return "false",
            _ => {}
        }
    }
    "true"
}

/// Check if a struct is plain (no dynamic allocation needed)
fn is_type_plain(s: &Struct) -> &'static str {
    use crate::types::IdlType;

    for field in &s.fields {
        #[allow(clippy::unnested_or_patterns)] // More readable with separate arms
        match &field.field_type {
            // A bounded string is not its own wire form (length word).
            IdlType::Sequence { .. }
            | IdlType::BoundedString { .. }
            | IdlType::Primitive(crate::types::PrimitiveType::String)
            | IdlType::Primitive(crate::types::PrimitiveType::WString)
            | IdlType::Map { .. }
            | IdlType::Named(_) => return "false", // Named: conservative - may contain dynamic types
            _ => {}
        }
    }
    "true"
}

