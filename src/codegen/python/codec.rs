//! XCDR2 codec of the generated Python classes (DDS-`XTypes` 1.3
//! 7.4.3.5.3, spec text lines 6750-7016).
//!
//! Every structure and union gets two hidden methods, `_hdds_enc(e)` and
//! `_hdds_dec(cls, d)`, that serialize through the cursor classes
//! `_HddsEnc` / `_HddsDec` emitted once per module. The public methods keep
//! their names: `encode_cdr2_le()` returns the bytes, `decode_cdr2_le(data)`
//! returns `(instance, bytes_read)`. Alignment is measured from the first
//! byte handed to the public entry point, never from the first byte of a
//! nested value (rule 1: one ORIGIN for the whole body, capped at 4 under
//! XCDR2).
//!
//! What the specification fixes at generation time comes from the shared
//! model (`codegen::data_model`): extensibility, member ids, DHEADERs of
//! collections, enumeration and bitmask widths, `EMHEADER1` length codes and
//! the must-understand flag.

