/// How a resolved type serializes.
enum Kind {
    Prim(PrimitiveType),
    Str {
        wide: bool,
        bound: u32,
    },
    Seq {
        inner: IdlType,
        bound: u32,
    },
    Array {
        elem: IdlType,
        dims: Vec<u32>,
    },
    Map {
        key: IdlType,
        value: IdlType,
        bound: u32,
    },
    Aggregate(String),
    Enum {
        name: String,
        width: usize,
        /// Value of the first literal (the default, Table 9).
        first: Option<i64>,
    },
    Bitmask {
        name: String,
        width: usize,
    },
    Bitset(String),
    Unknown(String),
}

/// `struct` format and size of a fixed-size primitive other than boolean,
/// char and wchar.
const fn prim_fmt(p: &PrimitiveType) -> Option<(&'static str, usize)> {
    match p {
        PrimitiveType::Octet | PrimitiveType::UInt8 => Some(("B", 1)),
        PrimitiveType::Int8 => Some(("b", 1)),
        PrimitiveType::Short | PrimitiveType::Int16 => Some(("h", 2)),
        PrimitiveType::UnsignedShort | PrimitiveType::UInt16 => Some(("H", 2)),
        PrimitiveType::Long | PrimitiveType::Int32 => Some(("i", 4)),
        PrimitiveType::UnsignedLong | PrimitiveType::UInt32 => Some(("I", 4)),
        PrimitiveType::LongLong | PrimitiveType::Int64 => Some(("q", 8)),
        PrimitiveType::UnsignedLongLong | PrimitiveType::UInt64 => Some(("Q", 8)),
        PrimitiveType::Float => Some(("f", 4)),
        PrimitiveType::Double | PrimitiveType::LongDouble => Some(("d", 8)),
        _ => None,
    }
}

const fn int_fmt(width: usize, signed: bool) -> &'static str {
    match (width, signed) {
        (1, true) => "b",
        (1, false) => "B",
        (2, true) => "h",
        (2, false) => "H",
        (4, true) => "i",
        (4, false) => "I",
        (_, true) => "q",
        (_, false) => "Q",
    }
}

/// Code emitter: the type index, the output and a counter for unique local
/// names.
struct Gen<'a> {
    idx: &'a TypeIndex,
    out: String,
    var: usize,
    key_only: bool,
    /// Emitting an XCDR1 decoder (`_hdds_dec1`): no DHEADER, nested
    /// values through their own `_hdds_dec1`.
    v1: bool,
}

impl<'a> Gen<'a> {
    const fn new(idx: &'a TypeIndex) -> Self {
        Self {
            idx,
            out: String::new(),
            var: 0,
            key_only: false,
            v1: false,
        }
    }

    const fn encoder_method(&self) -> &'static str {
        if self.key_only {
            "_hdds_key_enc"
        } else {
            "_hdds_enc"
        }
    }

    fn fresh(&mut self, prefix: &str) -> String {
        let v = format!("_{prefix}{}", self.var);
        self.var += 1;
        v
    }

    fn line(&mut self, ind: usize, text: &str) {
        for _ in 0..ind {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn kind(&self, ty: &IdlType) -> Kind {
        let resolved = self.idx.resolve(ty);
        match resolved {
            // string<N> / wstring<N>: a string (rules 3-4), not a sequence.
            IdlType::BoundedString { wide, bound } => Kind::Str { wide, bound },
            IdlType::Primitive(PrimitiveType::String) => Kind::Str {
                wide: false,
                bound: 0,
            },
            IdlType::Primitive(PrimitiveType::WString) => Kind::Str {
                wide: true,
                bound: 0,
            },
            IdlType::Primitive(p) => Kind::Prim(p),
            // sequence<char> / sequence<wchar> are sequences on the wire: an
            // element count, then the elements (1 or 2 bytes), no NUL (rule
            // 11 versus rules 3-4).
            IdlType::Sequence { inner, bound } => Kind::Seq {
                inner: *inner,
                bound: bound.unwrap_or(0),
            },
            IdlType::Array { .. } => {
                let (elem, dims) = flatten_array(self.idx, &resolved)
                    .unwrap_or_else(|| (resolved.clone(), vec![]));
                Kind::Array { elem, dims }
            }
            IdlType::Map { key, value, bound } => Kind::Map {
                key: *key,
                value: *value,
                bound: bound.unwrap_or(0),
            },
            IdlType::Named(n) => match self.idx.named(&n) {
                Some(Named::Struct(_) | Named::Union(_)) => Kind::Aggregate(flat(&n)),
                Some(Named::Enum {
                    bit_bound,
                    literals,
                }) => Kind::Enum {
                    name: flat(&n),
                    width: enum_width(*bit_bound),
                    first: literals.first().map(|(_, v)| *v),
                },
                Some(Named::Bitmask { bit_bound }) => Kind::Bitmask {
                    name: flat(&n),
                    width: bitmask_width(*bit_bound),
                },
                Some(Named::Bitset) => Kind::Bitset(flat(&n)),
                Some(Named::Typedef(_)) | None => Kind::Unknown(n),
            },
        }
    }

    /// Python expression of a fresh default value of `ty` (DDS-XTypes 1.3
    /// Table 9, spec text line 2311): zero, `False`, the empty string or
    /// collection, an array of defaults, the first literal of an
    /// enumeration, a structure or union of defaults.
    fn default_expr(&self, ty: &IdlType) -> String {
        match self.kind(ty) {
            Kind::Prim(p) => match p {
                PrimitiveType::Boolean => "False".to_string(),
                PrimitiveType::Float
                | PrimitiveType::Double
                | PrimitiveType::LongDouble
                | PrimitiveType::Fixed { .. } => "0.0".to_string(),
                PrimitiveType::String | PrimitiveType::WString => "\"\"".to_string(),
                PrimitiveType::Void => "None".to_string(),
                _ => "0".to_string(),
            },
            Kind::Str { .. } => "\"\"".to_string(),
            Kind::Seq { .. } => "[]".to_string(),
            Kind::Map { .. } => "{}".to_string(),
            Kind::Array { elem, dims } => {
                let mut e = self.default_expr(&elem);
                for d in dims.iter().rev() {
                    e = format!("[{e} for _ in range({d})]");
                }
                e
            }
            Kind::Aggregate(n) | Kind::Bitset(n) => format!("{n}()"),
            Kind::Enum { name, first, .. } => {
                first.map_or_else(|| "0".to_string(), |v| format!("{name}({v})"))
            }
            Kind::Bitmask { name, .. } => format!("{name}(0)"),
            Kind::Unknown(_) => "None".to_string(),
        }
    }

    fn is_octet(&self, ty: &IdlType) -> bool {
        matches!(
            self.idx.resolve(ty),
            IdlType::Primitive(PrimitiveType::Octet | PrimitiveType::UInt8)
        )
    }

    // -------------------------------------------------------------------
    // Encoding: statements writing the value of the expression `place`
    // through the encoder `e`.
    // -------------------------------------------------------------------

    fn enc(&mut self, ind: usize, place: &str, ty: &IdlType) {
        match self.kind(ty) {
            Kind::Prim(p) => self.enc_prim(ind, place, &p),
            Kind::Str { wide, bound } => {
                let m = if wide { "wstring" } else { "string" };
                self.line(ind, &format!("e.{m}({place}, {bound})"));
            }
            Kind::Seq { inner, bound } => {
                let dh = self.begin_dheader(ind, ty);
                self.line(ind, &format!("_HddsEnc.bounded(len({place}), {bound})"));
                self.line(ind, &format!("e.count(len({place}))"));
                if self.is_octet(&inner) {
                    self.line(ind, &format!("e.raw(bytes({place}))"));
                } else {
                    let x = self.fresh("x");
                    self.line(ind, &format!("for {x} in {place}:"));
                    self.enc(ind + 1, &x, &inner);
                }
                self.end_dheader(ind, dh.as_deref());
            }
            Kind::Array { elem, dims } => {
                let dh = self.begin_dheader(ind, ty);
                if dims.len() == 1 && self.is_octet(&elem) {
                    self.line(ind, &format!("_HddsEnc.exact(len({place}), {})", dims[0]));
                    self.line(ind, &format!("e.raw(bytes({place}))"));
                } else {
                    let mut cur = place.to_string();
                    let mut depth = ind;
                    for d in &dims {
                        let x = self.fresh("x");
                        self.line(depth, &format!("_HddsEnc.exact(len({cur}), {d})"));
                        self.line(depth, &format!("for {x} in {cur}:"));
                        cur = x;
                        depth += 1;
                    }
                    self.enc(depth, &cur, &elem);
                }
                self.end_dheader(ind, dh.as_deref());
            }
            Kind::Map { key, value, bound } => {
                let dh = self.begin_dheader(ind, ty);
                self.line(ind, &format!("_HddsEnc.bounded(len({place}), {bound})"));
                self.line(ind, &format!("e.count(len({place}))"));
                let k = self.fresh("k");
                let v = self.fresh("v");
                self.line(ind, &format!("for {k}, {v} in {place}.items():"));
                self.enc(ind + 1, &k, &key);
                self.enc(ind + 1, &v, &value);
                self.end_dheader(ind, dh.as_deref());
            }
            Kind::Aggregate(_) => {
                let method = self.encoder_method();
                self.line(ind, &format!("{place}.{method}(e)"));
            }
            Kind::Enum { width, .. } => {
                let f = int_fmt(width, true);
                self.line(ind, &format!("e.put(\"{f}\", {width}, int({place}))"));
            }
            Kind::Bitmask { width, .. } => {
                let f = int_fmt(width, false);
                self.line(ind, &format!("e.put(\"{f}\", {width}, int({place}))"));
            }
            Kind::Bitset(_) => self.line(ind, &format!("e.put(\"Q\", 8, {place}.bits)")),
            Kind::Unknown(n) => self.line(
                ind,
                &format!(
                    "raise TypeError(\"hddsgen: type '{}' is not defined in this IDL file\")",
                    idl_name(&n)
                ),
            ),
        }
    }

    /// Under XCDR2 a collection of non-primitive elements starts with a
    /// DHEADER (rules 9, 12, 15); returns the local holding its position.
    fn begin_dheader(&mut self, ind: usize, ty: &IdlType) -> Option<String> {
        if !collection_has_dheader(self.idx, ty) {
            return None;
        }
        let d = self.fresh("dh");
        self.line(ind, &format!("{d} = e.begin_len()"));
        Some(d)
    }

    fn end_dheader(&mut self, ind: usize, dh: Option<&str>) {
        if let Some(d) = dh {
            self.line(ind, &format!("e.end_len({d})"));
        }
    }

    fn enc_prim(&mut self, ind: usize, place: &str, p: &PrimitiveType) {
        let stmt = match p {
            PrimitiveType::Boolean => format!("e.boolean({place})"),
            PrimitiveType::Char => format!("e.char({place})"),
            PrimitiveType::WChar => format!("e.wchar({place})"),
            PrimitiveType::String => format!("e.string({place}, 0)"),
            PrimitiveType::WString => format!("e.wstring({place}, 0)"),
            PrimitiveType::Fixed { .. } => {
                "raise NotImplementedError(\"hddsgen: fixed is not serialized by the Python backend\")"
                    .to_string()
            }
            PrimitiveType::Void => return,
            other => match prim_fmt(other) {
                Some((f, size)) => format!("e.put(\"{f}\", {size}, {place})"),
                None => return,
            },
        };
        self.line(ind, &stmt);
    }

    // -------------------------------------------------------------------
    // Decoding: statements assigning the value read through the decoder
    // `d` to the local `target`.
    // -------------------------------------------------------------------

    #[allow(clippy::too_many_lines)]
    fn dec(&mut self, ind: usize, target: &str, ty: &IdlType) {
        match self.kind(ty) {
            Kind::Prim(p) => {
                let expr = match p {
                    PrimitiveType::Boolean => "d.boolean()".to_string(),
                    PrimitiveType::Char => "d.get(\"B\", 1)".to_string(),
                    PrimitiveType::WChar => "d.get(\"H\", 2)".to_string(),
                    PrimitiveType::String => "d.string(0)".to_string(),
                    PrimitiveType::WString => "d.wstring(0)".to_string(),
                    PrimitiveType::Void => "None".to_string(),
                    PrimitiveType::Fixed { .. } => {
                        self.line(
                            ind,
                            "raise NotImplementedError(\"hddsgen: fixed is not serialized by the Python backend\")",
                        );
                        return;
                    }
                    other => prim_fmt(&other).map_or_else(
                        || "None".to_string(),
                        |(f, size)| format!("d.get(\"{f}\", {size})"),
                    ),
                };
                self.line(ind, &format!("{target} = {expr}"));
            }
            Kind::Str { wide, bound } => {
                let m = if wide { "wstring" } else { "string" };
                self.line(ind, &format!("{target} = d.{m}({bound})"));
            }
            Kind::Seq { inner, bound } => {
                let end = self.begin_dheader_dec(ind, ty);
                let n = self.fresh("n");
                self.line(ind, &format!("{n} = d.count()"));
                self.line(ind, &format!("_HddsDec.bounded({n}, {bound})"));
                self.bound_values(ind, &n, &[&inner]);
                if self.is_octet(&inner) {
                    self.line(ind, &format!("{target} = list(d.take({n}))"));
                } else {
                    let v = self.fresh("v");
                    self.line(ind, &format!("{target} = []"));
                    self.line(ind, &format!("for _ in range({n}):"));
                    self.dec(ind + 1, &v, &inner);
                    self.line(ind + 1, &format!("{target}.append({v})"));
                }
                self.end_dheader_dec(ind, end.as_deref());
            }
            Kind::Array { elem, dims } => {
                let end = self.begin_dheader_dec(ind, ty);
                if dims.len() == 1 && self.is_octet(&elem) {
                    self.line(ind, &format!("{target} = list(d.take({}))", dims[0]));
                } else {
                    self.dec_dims(ind, target, &elem, &dims);
                }
                self.end_dheader_dec(ind, end.as_deref());
            }
            Kind::Map { key, value, bound } => {
                let end = self.begin_dheader_dec(ind, ty);
                let n = self.fresh("n");
                let k = self.fresh("k");
                let v = self.fresh("v");
                self.line(ind, &format!("{n} = d.count()"));
                self.line(ind, &format!("_HddsDec.bounded({n}, {bound})"));
                self.bound_values(ind, &n, &[&key, &value]);
                self.line(ind, &format!("{target} = {{}}"));
                self.line(ind, &format!("for _ in range({n}):"));
                self.dec(ind + 1, &k, &key);
                self.dec(ind + 1, &v, &value);
                self.line(ind + 1, &format!("{target}[{k}] = {v}"));
                self.end_dheader_dec(ind, end.as_deref());
            }
            Kind::Aggregate(n) if self.v1 => {
                self.line(ind, &format!("{target} = {n}._hdds_dec1(d)"));
            }
            Kind::Aggregate(n) => self.line(ind, &format!("{target} = {n}._hdds_dec(d)")),
            Kind::Enum { name, width, .. } => {
                let f = int_fmt(width, true);
                self.line(ind, &format!("{target} = {name}(d.get(\"{f}\", {width}))"));
            }
            Kind::Bitmask { name, width } => {
                let f = int_fmt(width, false);
                self.line(ind, &format!("{target} = {name}(d.get(\"{f}\", {width}))"));
            }
            Kind::Bitset(n) => self.line(ind, &format!("{target} = {n}(bits=d.get(\"Q\", 8))")),
            Kind::Unknown(n) => self.line(
                ind,
                &format!(
                    "raise TypeError(\"hddsgen: type '{}' is not defined in this IDL file\")",
                    idl_name(&n)
                ),
            ),
        }
    }

    /// The bound of the values the `n` elements of a sequence (`parts`: its
    /// element type) or map (key and value types) can build, checked before
    /// any is: `d.zero_wire(n, weight)` when they take no byte on the wire,
    /// `d.storage(n, weight)` when an element can build more values than
    /// the bytes it takes at least (otherwise the bytes bound them already).
    fn bound_values(&mut self, ind: usize, n: &str, parts: &[&IdlType]) {
        let min = parts.iter().fold(0u64, |acc, t| {
            acc.saturating_add(if self.v1 {
                least_wire::min_wire_xcdr1(self.idx, t)
            } else {
                least_wire::min_wire(self.idx, t)
            })
        });
        let weight = parts.iter().fold(0u64, |acc, t| {
            acc.saturating_add(least_wire::value_weight(self.idx, t))
        });
        if min == 0 {
            self.line(ind, &format!("d.zero_wire({n}, {weight})"));
        } else if weight > min {
            self.line(ind, &format!("d.storage({n}, {weight})"));
        }
    }

    /// Nested lists of an array, row-major.
    fn dec_dims(&mut self, ind: usize, target: &str, elem: &IdlType, dims: &[u32]) {
        let Some((&first, rest)) = dims.split_first() else {
            self.dec(ind, target, elem);
            return;
        };
        let v = self.fresh("v");
        self.line(ind, &format!("{target} = []"));
        self.line(ind, &format!("for _ in range({first}):"));
        self.dec_dims(ind + 1, &v, elem, rest);
        self.line(ind + 1, &format!("{target}.append({v})"));
    }

    fn begin_dheader_dec(&mut self, ind: usize, ty: &IdlType) -> Option<String> {
        if self.v1 || !collection_has_dheader(self.idx, ty) {
            return None;
        }
        let end = self.fresh("end");
        self.line(ind, &format!("{end} = d.begin_len()"));
        Some(end)
    }

    fn end_dheader_dec(&mut self, ind: usize, end: Option<&str>) {
        if let Some(e) = end {
            self.line(ind, &format!("d.skip_to({e})"));
        }
    }
}

/// The public entry points of a structure or union, routed to its hidden
