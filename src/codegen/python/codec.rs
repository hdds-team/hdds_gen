/// Codec of a structure at the class body's indentation level `ind` (in
/// steps of four spaces).
pub(super) fn struct_codec(idx: &TypeIndex, s: &Struct, ind: usize) -> String {
    struct_codec_impl(idx, s, ind, false) + &struct_codec_impl(idx, s, ind, true)
}

#[allow(clippy::too_many_lines)]
fn struct_codec_impl(idx: &TypeIndex, s: &Struct, ind: usize, key_only: bool) -> String {
    let mut g = Gen::new(idx);
    g.key_only = key_only;
    let name = flat(&s.name);
    if !key_only {
        entry_points(&mut g, ind, &name, data_model::struct_ext(s));
    }
    let chain = match member_chain(idx, s) {
        Ok(c) => c,
        Err(reason) => {
            let reason = reason.replace(['"', '\\', '\n'], " ");
            for sig in [
                "def _hdds_enc(self, e) -> None:",
                "def _hdds_dec(cls, d):",
                "def _hdds_dec1(cls, d):",
            ] {
                if sig.contains("cls") {
                    g.line(ind, "@classmethod");
                }
                g.line(ind, sig);
                g.line(
                    ind + 1,
                    &format!(
                        "raise TypeError(\"hddsgen: {}: {reason}\")",
                        idl_name(&s.name)
                    ),
                );
                g.line(0, "");
            }
            return g.out;
        }
    };
    let chain = if key_only {
        data_model::key_members(chain)
    } else {
        chain
    };
    let ext = data_model::struct_ext(s);
    let places: Vec<String> = chain
        .iter()
        .map(|m| format!("self.{}", python_ident(&m.field.name)))
        .collect();

    // ---- encode ----
    g.line(
        ind,
        &format!("def {}(self, e) -> None:", g.encoder_method()),
    );
    let body = ind + 1;
    let start = g.out.len();
    match ext {
        Ext::Final | Ext::Appendable => {
            // Rule 30 (line 7013): an APPENDABLE type is its DHEADER, then
            // its FINAL form.
            if ext == Ext::Appendable {
                g.line(body, "_dh = e.begin_len()");
            }
            for (m, place) in chain.iter().zip(&places) {
                if m.field.is_optional() {
                    // Rule 20: a presence flag, then the value.
                    g.line(body, &format!("if {place} is None:"));
                    g.line(body + 1, "e.boolean(False)");
                    g.line(body, "else:");
                    g.line(body + 1, "e.boolean(True)");
                    g.enc(body + 1, place, &m.field.field_type);
                } else {
                    g.enc(body, place, &m.field.field_type);
                }
            }
            if ext == Ext::Appendable {
                g.line(body, "e.end_len(_dh)");
            }
        }
        Ext::Mutable => {
            // Rules 21-22: DHEADER, then per member EMHEADER1, the NEXTINT
            // when the length code is 4, the value.
            g.line(body, "_dh = e.begin_len()");
            for (m, place) in chain.iter().zip(&places) {
                let mut mi = body;
                if m.field.is_optional() {
                    g.line(body, &format!("if {place} is not None:"));
                    mi += 1;
                }
                let lc = length_code(idx, &m.field.field_type);
                let mu = if must_understand(&m.field) {
                    "True"
                } else {
                    "False"
                };
                g.line(
                    mi,
                    &format!("e.emheader({mu}, {lc}, {:#x})  # {}", m.id, m.field.name),
                );
                if lc == 4 {
                    let n = g.fresh("n");
                    g.line(mi, &format!("{n} = e.begin_len()"));
                    g.enc(mi, place, &m.field.field_type);
                    g.line(mi, &format!("e.end_len({n})"));
                } else {
                    g.enc(mi, place, &m.field.field_type);
                }
            }
            g.line(body, "e.end_len(_dh)");
        }
    }
    if g.out.len() == start {
        g.line(body, "pass");
    }
    g.line(0, "");

    if key_only {
        return key_encoder(&g.out, ind);
    }

    // ---- decode ----
    g.line(ind, "@classmethod");
    g.line(ind, &format!("def _hdds_dec(cls, d) -> '{name}':"));
    let locals: Vec<String> = (0..chain.len()).map(|i| format!("_f{i}")).collect();
    match ext {
        Ext::Final => {
            for (m, local) in chain.iter().zip(&locals) {
                if m.field.is_optional() {
                    g.line(body, &format!("{local} = None"));
                    g.line(body, "if d.boolean():");
                    g.dec(body + 1, local, &m.field.field_type);
                } else {
                    g.dec(body, local, &m.field.field_type);
                }
            }
        }
        Ext::Appendable => {
            // Type evolution (DDS-XTypes 1.3 7.4.1.2.3, spec text lines
            // 6195-6203; Table 9 line 2311): a member after the end the
            // DHEADER gives was not written (an older writer): it takes its
            // default; what follows the known members is skipped.
            g.line(body, "_dh = d.begin_len()");
            for (m, local) in chain.iter().zip(&locals) {
                if m.field.is_optional() {
                    g.line(body, &format!("{local} = None"));
                    g.line(body, "if d.pos < _dh and d.boolean():");
                    g.dec(body + 1, local, &m.field.field_type);
                } else {
                    g.line(body, "if d.pos < _dh:");
                    g.dec(body + 1, local, &m.field.field_type);
                    g.line(body, "else:");
                    let dflt = g.default_expr(&m.field.field_type);
                    g.line(body + 1, &format!("{local} = {dflt}"));
                }
            }
            g.line(body, "d.skip_to(_dh)");
        }
        Ext::Mutable => {
            // A member absent from the data takes its default value, never
            // what an object held before (7.4.1.2.3, lines 6195-6203; lines
            // 3390-3393); an absent optional member has no value.
            for (m, local) in chain.iter().zip(&locals) {
                let dflt = if m.field.is_optional() {
                    "None".to_string()
                } else {
                    g.default_expr(&m.field.field_type)
                };
                g.line(body, &format!("{local} = {dflt}"));
            }
            g.line(body, "_dh = d.begin_len()");
            g.line(body, "while d.pos < _dh:");
            g.line(body + 1, "_mu, _id, _end = d.emheader(_dh)");
            let mut kw = "if";
            for (m, local) in chain.iter().zip(&locals) {
                g.line(body + 1, &format!("{kw} _id == {:#x}:", m.id));
                g.dec(body + 2, local, &m.field.field_type);
                kw = "elif";
            }
            g.line(body + 1, &format!("{kw} _mu:"));
            g.line(
                body + 2,
                "raise ValueError(\"unknown must-understand member id %#x\" % _id)",
            );
            g.line(body + 1, "d.skip_to(_end)");
            g.line(body, "d.skip_to(_dh)");
        }
    }
    let args: Vec<String> = chain
        .iter()
        .zip(&locals)
        .map(|(m, l)| format!("{}={l}", python_ident(&m.field.name)))
        .collect();
    g.line(body, &format!("return cls({})", args.join(", ")));
    g.line(0, "");
    struct_dec1(&mut g, &chain, ext, ind, &name, &args);
    g.out
}

/// `_hdds_dec1`, the XCDR1 decoder of a structure (DDS-XTypes 1.3 7.4.1):
/// FINAL and APPENDABLE alike, no DHEADER (a member of an APPENDABLE
/// structure past the end of the data at its default, 7.4.1.2.3), an
/// optional member as a parameter (rule 19); MUTABLE as a parameter list
/// closed by `PID_LIST_END` (rules 24-25), members by id, an unknown one
/// skipped unless it must be understood, a missing one at its default.
fn struct_dec1(
    g: &mut Gen<'_>,
    chain: &[data_model::ChainMember],
    ext: Ext,
    ind: usize,
    name: &str,
    args: &[String],
) {
    let body = ind + 1;
    g.v1 = true;
    g.line(ind, "@classmethod");
    g.line(ind, &format!("def _hdds_dec1(cls, d) -> '{name}':"));
    let locals: Vec<String> = (0..chain.len()).map(|i| format!("_f{i}")).collect();
    if ext == Ext::Mutable {
        for (m, local) in chain.iter().zip(&locals) {
            let dflt = if m.field.is_optional() {
                "None".to_string()
            } else {
                g.default_expr(&m.field.field_type)
            };
            g.line(body, &format!("{local} = {dflt}"));
        }
        g.line(body, "while True:");
        g.line(body + 1, "_p = d.pl1_member()");
        g.line(body + 1, "if _p is None:");
        g.line(body + 2, "break");
        g.line(body + 1, "_id, _mu, _end, _prev = _p");
        let mut kw = "if";
        for (m, local) in chain.iter().zip(&locals) {
            g.line(body + 1, &format!("{kw} _id == {:#x}:", m.id));
            g.dec(body + 2, local, &m.field.field_type);
            kw = "elif";
        }
        g.line(body + 1, &format!("{kw} _mu:"));
        g.line(
            body + 2,
            "raise ValueError(\"unknown must-understand member id %#x\" % _id)",
        );
        g.line(body + 1, "d.pl1_done(_end, _prev)");
    } else {
        let app = ext == Ext::Appendable;
        for (m, local) in chain.iter().zip(&locals) {
            let mut mi = body;
            if app {
                let dflt = if m.field.is_optional() {
                    "None".to_string()
                } else {
                    g.default_expr(&m.field.field_type)
                };
                g.line(body, &format!("{local} = {dflt}"));
                g.line(body, "if d.pos < len(d.buf):");
                mi += 1;
            }
            if m.field.is_optional() {
                g.line(mi, &format!("{local} = None"));
                g.line(mi, "_p = d.pl1_member()");
                g.line(mi, "if _p is None:");
                g.line(
                    mi + 1,
                    "raise ValueError(\"parameter list end where an optional member is expected\")",
                );
                g.line(mi, "if _p[2] > d.pos:");
                g.dec(mi + 1, local, &m.field.field_type);
                g.line(mi, "d.pl1_done(_p[2], _p[3])");
            } else {
                g.dec(mi, local, &m.field.field_type);
            }
        }
    }
    g.line(body, &format!("return cls({})", args.join(", ")));
    g.v1 = false;
}

/// The discriminator's `struct` format and width (rule 26: the
/// discriminator serializes as its type does; an enumeration at its
/// `@bit_bound` width).
fn disc_holder(idx: &TypeIndex, ty: &IdlType) -> (&'static str, usize) {
    match idx.resolve(ty) {
        IdlType::Primitive(p) => match p {
            PrimitiveType::Boolean
            | PrimitiveType::Octet
            | PrimitiveType::UInt8
            | PrimitiveType::Char => ("B", 1),
            PrimitiveType::Int8 => ("b", 1),
            PrimitiveType::WChar | PrimitiveType::UnsignedShort | PrimitiveType::UInt16 => ("H", 2),
            PrimitiveType::Short | PrimitiveType::Int16 => ("h", 2),
            PrimitiveType::UnsignedLong | PrimitiveType::UInt32 => ("I", 4),
            PrimitiveType::LongLong | PrimitiveType::Int64 => ("q", 8),
            PrimitiveType::UnsignedLongLong | PrimitiveType::UInt64 => ("Q", 8),
            _ => ("i", 4),
        },
        IdlType::Named(n) => match idx.named(&n) {
            Some(Named::Enum { bit_bound, .. }) => {
                let w = enum_width(*bit_bound);
                (int_fmt(w, true), w)
            }
            _ => ("i", 4),
        },
        _ => ("i", 4),
    }
}

/// The integer value of every label of every case of `u`, read by
/// `data_model::union_label_value` (integers, `TRUE` / `FALSE`, character
/// literals, enumerators, scoped or not); the `default` label has none.
///
/// # Errors
///
/// Returns the label no value can be read from.
pub(super) fn label_values(idx: &TypeIndex, u: &Union) -> Result<Vec<Vec<i64>>, String> {
    u.cases
        .iter()
        .map(|c| {
            c.labels
                .iter()
                .filter_map(|l| match l {
                    UnionLabel::Value(v) => Some(
                        union_label_value(idx, &u.discriminator, v)
                            .ok_or_else(|| format!("case label `{v}` has no value")),
                    ),
                    UnionLabel::Default => None,
                })
                .collect()
        })
        .collect()
}

/// A Python tuple of integers.
pub(super) fn py_tuple(values: &[i64]) -> String {
    match values {
        [v] => format!("({v},)"),
        _ => format!(
            "({})",
            values
                .iter()
                .map(ToString::to_string)
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// The condition selecting a case of labels `values`, on the integer
/// discriminator `_k`.
fn case_cond(values: &[i64]) -> String {
    match values {
        [v] => format!("_k == {v}"),
        _ => format!("_k in {}", py_tuple(values)),
    }
}

/// The class attribute default (` = ...`) of a member of type `ty`: its
/// default value (Table 9), through a factory when it is mutable.
pub(super) fn field_default(idx: &TypeIndex, ty: &IdlType) -> String {
    let g = Gen::new(idx);
    match g.kind(ty) {
        Kind::Seq { .. } => " = field(default_factory=list)".to_string(),
        Kind::Map { .. } => " = field(default_factory=dict)".to_string(),
        Kind::Aggregate(n) | Kind::Bitset(n) => format!(" = field(default_factory={n})"),
        Kind::Array { .. } => format!(" = field(default_factory=lambda: {})", g.default_expr(ty)),
        _ => format!(" = {}", g.default_expr(ty)),
    }
}

/// The default discriminator of `u` and the class attribute default of its
/// value (DDS-XTypes 1.3 Table 9, spec text line 2342): the discriminator
/// type's default (zero, `False`, the first literal), and the default of
/// the member it selects, `None` when it selects none.
pub(super) fn union_defaults(idx: &TypeIndex, u: &Union, labels: &[Vec<i64>]) -> (String, String) {
    let (d0, disc) = match idx.resolve(&u.discriminator) {
        IdlType::Named(n) => match idx.named(&n) {
            Some(Named::Enum { literals, .. }) => literals.first().map_or_else(
                || (0, "0".to_string()),
                |(_, v)| (*v, format!("{}({v})", flat(&n))),
            ),
            _ => (0, "0".to_string()),
        },
        IdlType::Primitive(PrimitiveType::Boolean) => (0, "False".to_string()),
        _ => (0, "0".to_string()),
    };
    let selected = labels.iter().position(|l| l.contains(&d0)).or_else(|| {
        u.cases
            .iter()
            .position(|c| c.labels.iter().any(|l| matches!(l, UnionLabel::Default)))
    });
    let value = selected
        .map(|i| &u.cases[i].field.field_type)
        .filter(|t| !matches!(t, IdlType::Primitive(PrimitiveType::Void)))
        .map_or_else(|| " = None".to_string(), |t| field_default(idx, t));
    (disc, value)
}

/// Codec of a union at the class body's indentation level `ind`. FINAL and
/// APPENDABLE (DHEADER, rules 26, 30); a discriminator no case selects is
/// serialized alone (rule 26: the selected member is optional). `labels`
/// are the label values of each case (`label_values`).
pub(super) fn union_codec(idx: &TypeIndex, u: &Union, ind: usize, labels: &[Vec<i64>]) -> String {
    let mut out = union_codec_impl(idx, u, ind, labels, false);
    let mut key_union = u.clone();
    let labels = if u.discriminator_is_key() {
        key_union.cases.clear();
        &[][..]
    } else {
        labels
    };
    let key = union_codec_impl(idx, &key_union, ind, labels, true);
    if let Some(start) = key.find(&format!("{}def _hdds_key_enc", "    ".repeat(ind))) {
        let end = key[start..]
            .find(&format!("{}@classmethod", "    ".repeat(ind)))
            .map_or(key.len(), |n| start + n);
        out.push_str(&key_encoder(&key[start..end], ind));
    }
    out
}

fn key_encoder(body: &str, ind: usize) -> String {
    let indent = "    ".repeat(ind);
    format!("{indent}def encode_key_cdr2_le(self) -> bytes:\n{indent}    e = _HddsEnc()\n{indent}    self._hdds_key_enc(e)\n{indent}    return bytes(e.buf)\n\n{body}")
}

#[allow(clippy::too_many_lines)]
fn union_codec_impl(
    idx: &TypeIndex,
    u: &Union,
    ind: usize,
    labels: &[Vec<i64>],
    key_only: bool,
) -> String {
    let name = flat(&u.name);
    let mut g = Gen::new(idx);
    g.key_only = key_only;
    let ext = union_ext(u);
    if !key_only {
        entry_points(&mut g, ind, &name, ext);
    }
    let body = ind + 1;
    let (fmt, width) = disc_holder(idx, &u.discriminator);
    let disc_enum = match idx.resolve(&u.discriminator) {
        IdlType::Named(n) if matches!(idx.named(&n), Some(Named::Enum { .. })) => Some(flat(&n)),
        _ => None,
    };
    let is_bool = matches!(
        idx.resolve(&u.discriminator),
        IdlType::Primitive(PrimitiveType::Boolean)
    );
    let is_char = matches!(
        idx.resolve(&u.discriminator),
        IdlType::Primitive(PrimitiveType::Char)
    );

    // (condition, case) per non-default case, then the default case.
    let mut arms: Vec<(String, usize)> = Vec::new();
    let mut default = None;
    for (i, (case, values)) in u.cases.iter().zip(labels).enumerate() {
        if case.labels.iter().any(|l| matches!(l, UnionLabel::Default)) {
            default = Some(i);
        }
        if !values.is_empty() {
            arms.push((case_cond(values), i));
        }
    }

    if ext == Ext::Mutable {
        let disc_write = if is_bool {
            "e.boolean(_d)".to_string()
        } else if is_char {
            "e.char(_d)".to_string()
        } else {
            format!("e.put(\"{fmt}\", {width}, int(_d))")
        };
        let disc_read = if is_bool {
            "d.boolean()".to_string()
        } else {
            let read = format!("d.get(\"{fmt}\", {width})");
            disc_enum
                .as_ref()
                .map_or_else(|| read.clone(), |e| format!("{e}({read})"))
        };
        mutable_union(&mut g, u, ind, &arms, default, &disc_write, &disc_read);
        return g.out;
    }

    // ---- encode ----
    g.line(
        ind,
        &format!("def {}(self, e) -> None:", g.encoder_method()),
    );
    if ext == Ext::Appendable {
        g.line(body, "_dh = e.begin_len()");
    }
    g.line(body, "_d = self._discriminator");
    g.line(body, "_k = _hdds_disc(_d)");
    if is_bool {
        g.line(body, "e.boolean(_d)");
    } else if is_char {
        g.line(body, "e.char(_d)");
    } else {
        g.line(body, &format!("e.put(\"{fmt}\", {width}, int(_d))"));
    }
    let mut kw = "if";
    for (cond, i) in &arms {
        g.line(body, &format!("{kw} {cond}:"));
        g.enc(body + 1, "self._value", &u.cases[*i].field.field_type);
        if g.out.ends_with(":\n") {
            g.line(body + 1, "pass");
        }
        kw = "elif";
    }
    if let Some(i) = default {
        let open = if arms.is_empty() { "if True:" } else { "else:" };
        g.line(body, open);
        g.enc(body + 1, "self._value", &u.cases[i].field.field_type);
        if g.out.ends_with(":\n") {
            g.line(body + 1, "pass");
        }
    }
    if ext == Ext::Appendable {
        g.line(body, "e.end_len(_dh)");
    }
    g.line(0, "");

    // ---- decode ----
    g.line(ind, "@classmethod");
    g.line(ind, &format!("def _hdds_dec(cls, d) -> '{name}':"));
    if ext == Ext::Appendable {
        g.line(body, "_dh = d.begin_len()");
    }
    if is_bool {
        g.line(body, "_d = d.boolean()");
    } else {
        let read = format!("d.get(\"{fmt}\", {width})");
        match &disc_enum {
            Some(e) => g.line(body, &format!("_d = {e}({read})")),
            None => g.line(body, &format!("_d = {read}")),
        }
    }
    g.line(body, "_k = _hdds_disc(_d)");
    g.line(body, "_v = None");
    let mut kw = "if";
    for (cond, i) in &arms {
        g.line(body, &format!("{kw} {cond}:"));
        g.dec(body + 1, "_v", &u.cases[*i].field.field_type);
        kw = "elif";
    }
    if let Some(i) = default {
        let open = if arms.is_empty() { "if True:" } else { "else:" };
        g.line(body, open);
        g.dec(body + 1, "_v", &u.cases[i].field.field_type);
    }
    if ext == Ext::Appendable {
        g.line(body, "d.skip_to(_dh)");
    }
    g.line(body, "return cls(_discriminator=_d, _value=_v)");
    g.line(0, "");

    // ---- XCDR1 decode: FINAL and APPENDABLE alike, no DHEADER ----
    g.v1 = true;
    g.line(ind, "@classmethod");
    g.line(ind, &format!("def _hdds_dec1(cls, d) -> '{name}':"));
    if is_bool {
        g.line(body, "_d = d.boolean()");
    } else {
        let read = format!("d.get(\"{fmt}\", {width})");
        match &disc_enum {
            Some(e) => g.line(body, &format!("_d = {e}({read})")),
            None => g.line(body, &format!("_d = {read}")),
        }
    }
    g.line(body, "_k = _hdds_disc(_d)");
    g.line(body, "_v = None");
    let mut kw = "if";
    for (cond, i) in &arms {
        g.line(body, &format!("{kw} {cond}:"));
        g.dec(body + 1, "_v", &u.cases[*i].field.field_type);
        kw = "elif";
    }
    if let Some(i) = default {
        let open = if arms.is_empty() { "if True:" } else { "else:" };
        g.line(body, open);
        g.dec(body + 1, "_v", &u.cases[i].field.field_type);
    }
    g.line(body, "return cls(_discriminator=_d, _value=_v)");
    g.v1 = false;
    g.out
}

/// A MUTABLE union (rule 27, spec text line 6986): DHEADER, the
/// discriminator as member 0 with the must-understand flag (7.2.2.4.4.4.6,
/// line 2299), then the selected case as member `union_case_ids(u)[i]`.
/// The decoder reads members by id, skips unknown ones (refuses them with
/// the M flag), requires the discriminator, and refuses a case member that
/// is not the one the discriminator selects.
#[allow(clippy::too_many_lines)]
fn mutable_union(
    g: &mut Gen<'_>,
    u: &Union,
    ind: usize,
    arms: &[(String, usize)],
    default: Option<usize>,
    disc_write: &str,
    disc_read: &str,
) {
    let idx = g.idx;
    let body = ind + 1;
    let ids = union_case_ids(idx, u);
    let disc_lc = discriminator_length_code(idx, &u.discriminator);
    let is_void = |i: usize| {
        matches!(
            u.cases[i].field.field_type,
            IdlType::Primitive(PrimitiveType::Void)
        )
    };
    // (condition, case) in the order the discriminator selects.
    let mut select: Vec<(String, usize)> = arms.to_vec();
    if let Some(i) = default {
        select.push((String::new(), i));
    }

    // ---- encode ----
    g.line(
        ind,
        &format!("def {}(self, e) -> None:", g.encoder_method()),
    );
    g.line(body, "_dh = e.begin_len()");
    g.line(body, "_d = self._discriminator");
    g.line(body, "_k = _hdds_disc(_d)");
    g.line(body, &format!("e.emheader(True, {disc_lc}, 0x0)"));
    g.line(body, disc_write);
    for (k, (cond, i)) in select.iter().enumerate() {
        let open = match (k, cond.is_empty()) {
            (0, true) => "if True:".to_string(),
            (_, true) => "else:".to_string(),
            (0, false) => format!("if {cond}:"),
            (_, false) => format!("elif {cond}:"),
        };
        g.line(body, &open);
        if is_void(*i) {
            g.line(body + 1, "pass");
            continue;
        }
        let field = &u.cases[*i].field;
        let lc = length_code(idx, &field.field_type);
        let mu = if must_understand(field) {
            "True"
        } else {
            "False"
        };
        g.line(
            body + 1,
            &format!("e.emheader({mu}, {lc}, {:#x})  # {}", ids[*i], field.name),
        );
        if lc == 4 {
            g.line(body + 1, "_n = e.begin_len()");
            g.enc(body + 1, "self._value", &field.field_type);
            g.line(body + 1, "e.end_len(_n)");
        } else {
            g.enc(body + 1, "self._value", &field.field_type);
        }
    }
    g.line(body, "e.end_len(_dh)");
    g.line(0, "");

    // The discriminator read, the case member checked against it.
    let check_case = |g: &mut Gen<'_>| {
        g.line(body, "if _d is None:");
        g.line(
            body + 1,
            &format!(
                "raise ValueError(\"{}: discriminator missing\")",
                idl_name(&u.name)
            ),
        );
        g.line(body, "_k = _hdds_disc(_d)");
        g.line(body, "_sel = None");
        for (k, (cond, i)) in select.iter().enumerate() {
            let open = match (k, cond.is_empty()) {
                (0, true) => "if True:".to_string(),
                (_, true) => "else:".to_string(),
                (0, false) => format!("if {cond}:"),
                (_, false) => format!("elif {cond}:"),
            };
            g.line(body, &open);
            if is_void(*i) {
                g.line(body + 1, "pass");
            } else {
                g.line(body + 1, &format!("_sel = {i}"));
            }
        }
        g.line(body, "if _sel != _case:");
        g.line(
            body + 1,
            &format!(
                "raise ValueError(\"{}: the case member is not the one the discriminator selects\")",
                idl_name(&u.name)
            ),
        );
        g.line(body, "return cls(_discriminator=_d, _value=_v)");
    };

    // ---- decode ----
    g.line(ind, "@classmethod");
    let name = flat(&u.name);
    g.line(ind, &format!("def _hdds_dec(cls, d) -> '{name}':"));
    g.line(body, "_d = None");
    g.line(body, "_v = None");
    g.line(body, "_case = None");
    g.line(body, "_dh = d.begin_len()");
    g.line(body, "while d.pos < _dh:");
    g.line(body + 1, "_mu, _id, _end = d.emheader(_dh)");
    g.line(body + 1, "if _id == 0x0:");
    g.line(body + 2, &format!("_d = {disc_read}"));
    for (i, case) in u.cases.iter().enumerate() {
        if is_void(i) {
            continue;
        }
        g.line(body + 1, &format!("elif _id == {:#x}:", ids[i]));
        g.dec(body + 2, "_v", &case.field.field_type);
        g.line(body + 2, &format!("_case = {i}"));
    }
    g.line(body + 1, "elif _mu:");
    g.line(
        body + 2,
        "raise ValueError(\"unknown must-understand member id %#x\" % _id)",
    );
    g.line(body + 1, "d.skip_to(_end)");
    g.line(body, "d.skip_to(_dh)");
    check_case(g);
    g.line(0, "");

    // ---- XCDR1 decode: the parameter list of the discriminator (member
    // 0) and the selected case (rules 27, 24-25) ----
    g.v1 = true;
    g.line(ind, "@classmethod");
    g.line(ind, &format!("def _hdds_dec1(cls, d) -> '{name}':"));
    g.line(body, "_d = None");
    g.line(body, "_v = None");
    g.line(body, "_case = None");
    g.line(body, "while True:");
    g.line(body + 1, "_p = d.pl1_member()");
    g.line(body + 1, "if _p is None:");
    g.line(body + 2, "break");
    g.line(body + 1, "_id, _mu, _end, _prev = _p");
    g.line(body + 1, "if _id == 0x0:");
    g.line(body + 2, &format!("_d = {disc_read}"));
    for (i, case) in u.cases.iter().enumerate() {
        if is_void(i) {
            continue;
        }
        g.line(body + 1, &format!("elif _id == {:#x}:", ids[i]));
        g.dec(body + 2, "_v", &case.field.field_type);
        g.line(body + 2, &format!("_case = {i}"));
    }
    g.line(body + 1, "elif _mu:");
    g.line(
        body + 2,
        "raise ValueError(\"unknown must-understand member id %#x\" % _id)",
    );
    g.line(body + 1, "d.pl1_done(_end, _prev)");
    check_case(g);
    g.v1 = false;
}

/// The standalone encode / decode of a bitmask class (its value alone, at
/// its `@bit_bound` width), at the class body's indentation `indent`.
pub(super) fn bitmask_codec(name: &str, width: usize, indent: &str) -> String {
    let f = int_fmt(width, false);
    let mut out = String::new();
    let _ = writeln!(out, "{indent}def encode_cdr2_le(self) -> bytes:");
    let _ = writeln!(
        out,
        "{indent}    \"\"\"Encode to XCDR2 little endian ({width} bytes, the @bit_bound width).\"\"\""
    );
    let _ = writeln!(out, "{indent}    return struct.pack('<{f}', int(self))\n");
    let _ = writeln!(out, "{indent}@classmethod");
    let _ = writeln!(
        out,
        "{indent}def decode_cdr2_le(cls, data: bytes) -> Tuple['{name}', int]:"
    );
    let _ = writeln!(
        out,
        "{indent}    \"\"\"Decode from XCDR2 little endian. Returns (instance, bytes_read).\"\"\""
    );
    let _ = writeln!(
        out,
        "{indent}    return cls(struct.unpack_from('<{f}', data, 0)[0]), {width}\n"
    );
    out
}
