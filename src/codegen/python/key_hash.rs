//! Instance `KeyHash` of generated Python classes (RTPS 2.5 9.6.4.8).
//!
//! A module with a keyed type carries `_HddsKeyHolder`, which serializes
//! the `KeyHolder` as `PLAIN_CDR2` big endian (alignment capped at 4, zero
//! padding) with `struct.pack`, then reduces it with zero padding or
//! `hashlib.md5`. `compute_key()` writes the `KeyHolder` members in member-id
//! order, as the shared model (`codegen::key_holder`) orders them, and
//! passes the padded-or-MD5 choice computed at generation time.

use std::fmt::Write as _;

use super::super::key_holder::{
    is_default_case, KhCase, KhNode, KhPrim, KhScalar, KhStruct, KhUnion, TypeIndex,
};
use crate::ast::{Definition, IdlFile, Struct, UnionLabel};
use crate::codegen::data_model::union_label_value;
use crate::codegen::keywords::python_ident;

/// The writer class, emitted once after the imports of a module with a
/// keyed type.
pub(super) const WRITER_CLASS: &str = r#"class _HddsKeyHolder:
    """KeyHolder serialization of RTPS 2.5 9.6.4.8 (generated by hddsgen):
    PLAIN_CDR2 big endian, alignment capped at 4, zero padding."""

    __slots__ = ("buf", "max_align")

    def __init__(self, max_align=4) -> None:
        self.buf = bytearray()
        self.max_align = max_align

    def _put(self, fmt: str, size: int, value) -> None:
        align = min(size, self.max_align)
        self.buf += b"\x00" * ((align - len(self.buf) % align) % align)
        self.buf += struct.pack(">" + fmt, value)

    def boolean(self, v) -> None:
        self.buf.append(1 if v else 0)

    def octet(self, v) -> None:
        self.buf.append(int(v) & 0xFF)

    def char(self, v) -> None:
        self.buf.append((ord(v) if isinstance(v, str) else int(v)) & 0xFF)

    def wchar(self, v) -> None:
        self._put("H", 2, (ord(v) if isinstance(v, str) else int(v)) & 0xFFFF)

    def i8(self, v) -> None:
        self._put("b", 1, int(v))

    def i16(self, v) -> None:
        self._put("h", 2, int(v))

    def u16(self, v) -> None:
        self._put("H", 2, int(v) & 0xFFFF)

    def i32(self, v) -> None:
        self._put("i", 4, int(v))

    def u32(self, v) -> None:
        self._put("I", 4, int(v) & 0xFFFFFFFF)

    def i64(self, v) -> None:
        self._put("q", 8, int(v))

    def u64(self, v) -> None:
        self._put("Q", 8, int(v) & 0xFFFFFFFFFFFFFFFF)

    def f32(self, v) -> None:
        self._put("f", 4, float(v))

    def f64(self, v) -> None:
        self._put("d", 8, float(v))

    def octets(self, v) -> None:
        self.buf += bytes(v)

    def string(self, v) -> None:
        data = v.encode("utf-8") if isinstance(v, str) else bytes(v)
        self.u32(len(data) + 1)
        self.buf += data + b"\x00"

    def wstring(self, v) -> None:
        if isinstance(v, str):
            data = v.encode("utf-16-be")
        else:
            data = b"".join(struct.pack(">H", int(c) & 0xFFFF) for c in v)
        self.u32(len(data))
        self.buf += data

    def finish(self, padded: bool) -> bytes:
        """The KeyHash: zero-padded when the KeyHolder's maximum size is at
        most 16 bytes, the MD5 of the serialization otherwise."""
        if padded and len(self.buf) <= 16:
            return bytes(self.buf) + bytes(16 - len(self.buf))
        return hashlib.md5(bytes(self.buf)).digest()


"#;

/// Writer method of a primitive.
const fn method(p: KhPrim) -> &'static str {
    match p {
        KhPrim::Bool => "boolean",
        KhPrim::Octet => "octet",
        KhPrim::Char => "char",
        KhPrim::I8 => "i8",
        KhPrim::I16 => "i16",
        KhPrim::U16 => "u16",
        KhPrim::WChar => "wchar",
        KhPrim::I32 => "i32",
        KhPrim::U32 => "u32",
        KhPrim::I64 => "i64",
        KhPrim::U64 => "u64",
        KhPrim::F32 => "f32",
        KhPrim::F64 => "f64",
    }
}

struct Emit<'a> {
    idx: &'a TypeIndex,
    out: String,
    next_var: usize,
}

impl<'a> Emit<'a> {
    const fn new(idx: &'a TypeIndex) -> Self {
        Self {
            idx,
            out: String::new(),
            next_var: 0,
        }
    }

    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn var(&mut self, prefix: &str) -> String {
        let v = format!("_{prefix}{}", self.next_var);
        self.next_var += 1;
        v
    }
}

fn scalar(e: &mut Emit<'_>, ind: usize, s: &KhScalar, place: &str) {
    e.line(ind, &format!("w.{}({place})", method(s.prim())));
}

fn node(e: &mut Emit<'_>, ind: usize, n: &KhNode, place: &str) {
    match n {
        KhNode::Scalar(s) => scalar(e, ind, s, place),
        KhNode::String { .. } => e.line(ind, &format!("w.string({place})")),
        KhNode::WString { .. } => e.line(ind, &format!("w.wstring({place})")),
        KhNode::Sequence { elem, .. } => {
            e.line(ind, &format!("w.u32(len({place}))"));
            if elem.prim() == KhPrim::Octet {
                e.line(ind, &format!("w.octets({place})"));
            } else {
                let v = e.var("e");
                e.line(ind, &format!("for {v} in {place}:"));
                scalar(e, ind + 1, elem, &v);
            }
        }
        KhNode::Array { elem, dims } => {
            if dims.len() == 1 && elem.prim() == KhPrim::Octet {
                e.line(ind, &format!("w.octets({place})"));
                return;
            }
            let mut cur = place.to_string();
            let mut depth = ind;
            for _ in dims {
                let v = e.var("e");
                e.line(depth, &format!("for {v} in {cur}:"));
                cur = v;
                depth += 1;
            }
            scalar(e, depth, elem, &cur);
        }
        KhNode::Struct(s) => structure(e, ind, s, place),
        KhNode::Union(u) => union(e, ind, u, place),
    }
}

/// Python classes inherit their base's attributes, so a base member is read
/// from the same object as the type's own members.
fn structure(e: &mut Emit<'_>, ind: usize, s: &KhStruct, place: &str) {
    for m in s.hash_order() {
        let p = format!("{place}.{}", python_ident(&m.field.name));
        node(e, ind, &m.node, &p);
    }
}

fn case_body(e: &mut Emit<'_>, ind: usize, case: &KhCase, place: &str) {
    match &case.node {
        Some(n) => node(e, ind, n, &format!("{place}._value")),
        None => e.line(ind, "pass"),
    }
}

/// The discriminator, then the member its value selects (a case's labels,
/// else the `default` case, else nothing), unless the discriminator is a
/// key.
fn union(e: &mut Emit<'_>, ind: usize, u: &KhUnion, place: &str) {
    let d = e.var("d");
    e.line(ind, &format!("{d} = {place}._discriminator"));
    scalar(e, ind, &u.disc, &d);
    if u.disc_is_key {
        return;
    }
    let key = e.var("k");
    e.line(ind, &format!("{key} = _hdds_disc({d})"));
    let mut first = true;
    let mut default: Option<&KhCase> = None;
    for case in &u.cases {
        if is_default_case(&case.labels) {
            default = Some(case);
            continue;
        }
        let conds: Vec<String> = case
            .labels
            .iter()
            .filter_map(|l| match l {
                // An unreadable label is refused when the union's own codec
                // is generated.
                UnionLabel::Value(v) => {
                    union_label_value(e.idx, &u.disc_type, v).map(|n| format!("{key} == {n}"))
                }
                UnionLabel::Default => None,
            })
            .collect();
        if conds.is_empty() {
            continue;
        }
        let kw = if first { "if" } else { "elif" };
        first = false;
        e.line(ind, &format!("{kw} {}:", conds.join(" or ")));
        case_body(e, ind + 1, case, place);
    }
    if let Some(case) = default {
        e.line(ind, if first { "if True:" } else { "else:" });
        case_body(e, ind + 1, case, place);
    }
}

/// Whether the module needs [`WRITER_CLASS`]: some structure has a
/// `KeyHolder` the model covers.
pub(super) fn module_needs_writer(ast: &IdlFile, idx: &TypeIndex) -> bool {
    fn walk(defs: &[Definition], idx: &TypeIndex) -> bool {
        defs.iter().any(|d| match d {
            Definition::Struct(s) => matches!(idx.key_holder(s), Ok(Some(_))),
            Definition::Union(u) => u.discriminator_is_key(),
            Definition::Module(m) => walk(&m.definitions, idx),
            _ => false,
        })
    }
    walk(&ast.definitions, idx)
}

/// The `compute_key()` method of `s`, at the class body's indentation
/// `indent` (a string of spaces).
pub(super) fn compute_key_method(s: &Struct, idx: &TypeIndex, indent: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "{indent}def compute_key(self, protected_key: bool = False) -> bytes:"
    );
    let _ = writeln!(
        out,
        "{indent}    \"\"\"Instance KeyHash (RTPS 2.5 9.6.4.8): the KeyHolder serialized as\n\
         {indent}    PLAIN_CDR2 big endian, zero-padded to 16 bytes when its maximum size is\n\
         {indent}    at most 16, its MD5 otherwise. All zeros for a type without key.\"\"\""
    );
    match idx.key_holder(s) {
        Ok(Some(kh)) => {
            let mut e = Emit::new(idx);
            structure(&mut e, 0, &kh, "self");
            let _ = writeln!(
                out,
                "{indent}    w = _HddsKeyHolder(8 if protected_key else 4)"
            );
            for line in e.out.lines() {
                let _ = writeln!(out, "{indent}    {line}");
            }
            let padded = if kh.is_padded_form() { "True" } else { "False" };
            let _ = writeln!(
                out,
                "{indent}    return w.finish({padded} and not protected_key)"
            );
        }
        Ok(None) => {
            let _ = writeln!(out, "{indent}    return bytes(16)");
        }
        Err(reason) => {
            let reason = reason.replace(['\n', '\r'], " ");
            let _ = writeln!(
                out,
                "{indent}    # No KeyHolder generated: the key of this type is not covered by\n\
                 {indent}    # hddsgen's KeyHash model ({reason}).\n\
                 {indent}    return bytes(16)"
            );
        }
    }
    out
}
